#!/usr/bin/env python3
"""node_modules integrity probe: DETECT symlink corruption of the shared install.

Follow-up to #6818 (#6805 incident). ``_provision_data_symlinks`` in
``scripts/delegate.py`` symlinks the PRIMARY checkout's ``node_modules`` and
``site/node_modules`` directly into every dispatch worktree — a direct write
conduit, not an upward workspace-root-search gap (see #6818 design note round
2, adopting the K3 cross-family review's correction). Any package-manager or
build-tool write inside a worktree's ``node_modules/`` writes straight through
to the primary's real files, because the worktree's ``node_modules`` *is* the
primary's directory, not a copy.

This module is DETECTION ONLY, mirroring ``check_primary_integrity.py``'s
posture and its "git-layer enforcement against a same-UID process is
categorically impossible" precedent, transplanted to the Node layer:

- DETECT: symlinks under the PRIMARY's own ``node_modules/`` and
  ``site/node_modules/`` (depth <= 2, including ``.bin``) whose realpath
  resolves OUTSIDE the primary checkout root. Realpath-based, not
  ``*worktrees*`` string matching, so a healthy relative ``.bin`` shim
  (``.bin/foo -> ../foo/bin/cli.js``) never false-positives and macOS's
  ``/var`` vs ``/private/var`` symlink aliasing never false-positives either
  (both sides of the comparison go through the same ``os.path.realpath``).
- Sentinel check: ``node_modules/acpx/dist/cli.js`` exists and
  ``node_modules/.bin/acpx`` resolves — the project-local ACPX install every
  seat depends on (``docs/agent-runtime-guide.md``).
- RECORD: every detection appends a JSONL event (mirrors
  ``check_primary_integrity``'s RECORD contract) with the offending link(s),
  their targets, and the dispatches running at the time — enough to identify
  the likely offending actor.
- ALERT ONLY, never blocks, never repairs. Per the K3-constrained design,
  auto-repair is gated on the Node-version pin (``.nvmrc``/``engines``)
  landing first — repairing under the wrong Node risks reproducing the
  better-sqlite3 native-module rebuild failure the #6818 incident hit — and is
  an operator decision, not this probe's scope.

Usage::

    python scripts/audit/check_node_modules_integrity.py

Wired ALERT-only into the same three call sites as ``check_primary_integrity``:
``cmd_dispatch`` pre-dispatch gate, ``_run_worker`` post-exit sweep (both
``scripts/delegate.py``), and the Monitor API health-orient canary
(``scripts/api/main.py``). Callers fail open on any probe exception —
consistent with the existing watchdog, an integrity-probe bug must never
itself block or crash a dispatch.
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import sys
from pathlib import Path
from typing import Any


def _load_sibling(module_name: str, filename: str):
    """Load a sibling module by FILE PATH, bypassing ``scripts.audit``'s own
    package ``__init__.py``.

    Importing via the package path (``from scripts.audit.X import ...`` /
    ``from audit.X import ...``) forces Python to initialize the
    ``scripts.audit`` *package* first — a large, unrelated curriculum-audit
    import chain. That chain assumes the real ``scripts/config.py`` resolves
    before ``scripts/audit/config.py``'s own bare ``from config import ...``;
    when this script is invoked directly (``python
    scripts/audit/check_node_modules_integrity.py``), Python puts this
    script's own directory (``scripts/audit``) on ``sys.path`` too, and that
    ordering can make the bare import resolve to itself instead — an
    ``ImportError`` entirely unrelated to node_modules integrity. Loading the
    sibling by path sidesteps the package ``__init__.py`` (and that whole
    class of sys.path-ordering fragility) altogether.
    """
    if module_name in sys.modules:
        return sys.modules[module_name]
    spec = importlib.util.spec_from_file_location(module_name, Path(__file__).resolve().parent / filename)
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module


_check_primary_integrity = _load_sibling(
    "_node_modules_integrity_check_primary_integrity", "check_primary_integrity.py"
)
_append_event = _check_primary_integrity._append_event
_resolve_main_root = _check_primary_integrity._resolve_main_root
_running_dispatches = _check_primary_integrity._running_dispatches

# node_modules trees `_provision_data_symlinks` (scripts/delegate.py) links
# whole into every dispatch worktree.
_NODE_MODULES_DIRS = ("node_modules", "site/node_modules")

# Depth of the symlink walk below each node_modules root: 1 = direct entries
# (packages, `.bin`), 2 = one level in (scoped `@scope/pkg` entries and the
# individual shims under `.bin/`). Matches the K3-reviewed design scope.
_MAX_DEPTH = 2

# acpx is the one project-local ACPX install every dispatch seat resolves
# from the primary (docs/agent-runtime-guide.md) — a missing/dangling sentinel
# means the shared install itself is gone, not just a stray outside link.
_SENTINEL_CLI = Path("node_modules/acpx/dist/cli.js")
_SENTINEL_BIN = Path("node_modules/.bin/acpx")


def _realpath(path: Path) -> Path:
    """``os.path.realpath`` wrapped as a ``Path``.

    Resolves symlink targets AND filesystem-level aliasing (macOS's
    ``/var`` -> ``/private/var``) the same way for every comparison, so a
    ``Path.resolve()``-only comparison never silently disagrees with what the
    OS actually opens.
    """
    return Path(os.path.realpath(path))


def _is_within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
    except ValueError:
        return False
    return True


def _iter_symlinks(root: Path, *, max_depth: int) -> list[Path]:
    """Symlinks under ``root``, depth <= ``max_depth`` (root's children = depth 1).

    Never descends into a symlink (would re-walk whatever it points at,
    possibly outside ``root`` entirely) or into another ``node_modules``
    directory (nested devDependency installs are out of scope here).
    """
    found: list[Path] = []

    def _walk(dir_path: Path, depth: int) -> None:
        try:
            entries = list(dir_path.iterdir())
        except OSError:
            return
        for entry in entries:
            if entry.is_symlink():
                found.append(entry)
                continue
            if entry.is_dir() and entry.name != "node_modules" and depth < max_depth:
                _walk(entry, depth + 1)

    if root.is_dir() and not root.is_symlink():
        _walk(root, 1)
    return found


def _relative_label(path: Path, root: Path) -> str:
    return str(path.relative_to(root)) if _is_within(path, root) else str(path)


def find_outside_symlinks(primary_root: Path) -> list[dict[str, str]]:
    """Symlinks under the primary's node_modules trees resolving OUTSIDE it.

    Returns a list of ``{"link": <relative path>, "target": <realpath>}``
    dicts, one per offending symlink. Empty when everything resolves inside
    ``primary_root`` (the healthy case — including every normal ``.bin``
    shim).
    """
    real_root = _realpath(primary_root)
    findings: list[dict[str, str]] = []
    for relative in _NODE_MODULES_DIRS:
        for link in _iter_symlinks(primary_root / relative, max_depth=_MAX_DEPTH):
            target_real = _realpath(link)
            if not _is_within(target_real, real_root):
                findings.append(
                    {
                        "link": _relative_label(link, primary_root),
                        "target": str(target_real),
                    }
                )
    return findings


def check_sentinel(primary_root: Path) -> tuple[bool, str]:
    """The project-local acpx install is present and its ``.bin`` shim resolves."""
    cli = primary_root / _SENTINEL_CLI
    bin_shim = primary_root / _SENTINEL_BIN
    if not cli.exists():
        return False, f"sentinel missing: {_SENTINEL_CLI} does not exist"
    if not bin_shim.exists():  # .exists() follows symlinks: dangling -> False
        return False, f"sentinel missing: {_SENTINEL_BIN} does not resolve"
    return True, "sentinel ok: acpx cli present, .bin/acpx resolves"


def check_node_modules_integrity(
    repo: Path,
    *,
    tasks_dir: Path | None = None,
    state_dir: Path | None = None,
) -> tuple[bool, str]:
    """Detect (never repair) node_modules symlink corruption of the primary.

    Returns ``(ok, message)``. ``ok`` is False when an outside-resolving
    symlink or a failed sentinel is found; this is an ALERT signal only —
    callers must never block or auto-repair on it in this PR (operator-gated,
    see module docstring).
    """
    main_root = _resolve_main_root(Path(repo))
    sdir = state_dir or (main_root / "data" / "telemetry" / "node-modules-integrity")

    outside = find_outside_symlinks(main_root)
    sentinel_ok, sentinel_message = check_sentinel(main_root)

    if not outside and sentinel_ok:
        return True, f"node_modules integrity ok ({main_root})"

    evidence: dict[str, Any] = {
        "outside_symlinks": outside,
        "sentinel_ok": sentinel_ok,
        "sentinel_message": sentinel_message,
        "running_dispatches": _running_dispatches(tasks_dir),
        "main_root": str(main_root),
    }
    _append_event(sdir, "node_modules_integrity_alert", **evidence)

    reasons = []
    if outside:
        links = ", ".join(f"{f['link']} -> {f['target']}" for f in outside)
        reasons.append(f"{len(outside)} symlink(s) resolve OUTSIDE the primary: {links}")
    if not sentinel_ok:
        reasons.append(sentinel_message)
    return False, (
        f"ALERT: node_modules integrity issue(s) — {'; '.join(reasons)}. "
        f"NOT repaired (detection only); evidence preserved under {sdir}/events.jsonl."
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Detect node_modules symlink corruption of the primary checkout (#6818).",
    )
    parser.add_argument(
        "-q",
        "--quiet",
        action="store_true",
        help="suppress the OK message (alerts still print)",
    )
    parser.add_argument(
        "--repo",
        type=Path,
        default=Path(__file__).resolve().parents[2],
        help="repo path to check (default: this project root)",
    )
    parser.add_argument(
        "--tasks-dir",
        type=Path,
        default=None,
        help="dispatch tasks dir for attribution (default: <root>/batch_state/tasks)",
    )
    parser.add_argument(
        "--state-dir",
        type=Path,
        default=None,
        help="watchdog state/log dir (default: <main_root>/data/telemetry/node-modules-integrity)",
    )
    args = parser.parse_args(argv)

    tasks_dir = args.tasks_dir
    if tasks_dir is None:
        try:
            tasks_dir = _resolve_main_root(args.repo) / "batch_state" / "tasks"
        except Exception:
            tasks_dir = None

    ok, message = check_node_modules_integrity(
        args.repo,
        tasks_dir=tasks_dir,
        state_dir=args.state_dir,
    )
    if not ok:
        print(f"❌ {message}", file=sys.stderr)
        return 1
    if not args.quiet:
        print(f"✅ {message}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
