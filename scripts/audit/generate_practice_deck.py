class JsonVesumVerifier:
    """Fixture verifier used by tests and fixture-only local generation."""

    def __init__(self, payload: dict[str, Any]) -> None:
        self.payload = payload

    @classmethod
    def from_path(cls, path: Path) -> JsonVesumVerifier:
        return cls(json.loads(path.read_text(encoding="utf-8")))

    def verify_words(
        self,
        words: list[str],
        pos_filter: str | None = None,
    ) -> dict[str, list[dict[str, Any]]]:
        result: dict[str, list[dict[str, Any]]] = {}
        for word in words:
            matches = self.payload.get(word, [])
            if not isinstance(matches, list):
                matches = []
            if pos_filter:
                matches = [row for row in matches if isinstance(row, dict) and row.get("pos") == pos_filter]
            result[word] = [row for row in matches if isinstance(row, dict)]
        return result


def _has_text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _clean_text(value: Any) -> str | None:
    return value.strip() if _has_text(value) else None


def _contains_forbidden_text(value: Any) -> bool:
    """Reject source text with controls, format controls, or private-use glyphs."""
    text = _clean_text(value)
    if text is None:
        return False
    return any(
        unicodedata.category(char) in {"Cc", "Cf"}
        or 0xE000 <= ord(char) <= 0xF8FF
        for char in text
    )


def _plain(value: str) -> str:
    return (
        value.casefold()
        .replace("\u0301", "")
        .replace("́", "")
        .replace("’", "'")
        .replace("ʼ", "'")
        .strip()
    )


def _surface_variants(value: str) -> tuple[str, ...]:
    """Return safe VESUM lookup forms for a source-preserved surface."""
    return tuple(dict.fromkeys((value, value.casefold(), _plain(value))))


def _verified_surface_matches(
    form: str,
    verifier: VesumVerifier,
    pos_filter: str | None = None,
) -> list[dict[str, Any]]:
    """Look up a source surface without weakening lemma/POS filtering.

    Source sentences preserve capitalization and apostrophe spelling exactly,
    while VESUM stores dictionary surfaces in normalized lowercase form. Query
    both representations, but leave the emitted answer unchanged so the cloze
    still reproduces the attested source token.
    """
    matches: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str]] = set()
    for variant in _surface_variants(form):
        for match in verifier.verify_words([variant], pos_filter).get(variant, []):
            if not isinstance(match, dict):
                continue
            key = (
                str(match.get("lemma") or ""),
                str(match.get("pos") or ""),
                str(match.get("tags") or ""),
            )
            if key not in seen:
                seen.add(key)
                matches.append(match)
    if not matches and pos_filter:
        return _verified_surface_matches(form, verifier)
    return matches


def _strip_stress(value: str) -> str:
    return unicodedata.normalize("NFC", unicodedata.normalize("NFD", value).replace(STRESS_MARK, ""))


def _stress_position(stressed: str) -> tuple[str, int | None]:
    nfd = unicodedata.normalize("NFD", stressed)
    if nfd.count(STRESS_MARK) != 1:
        return (_strip_stress(stressed), None)
    prefix, _suffix = nfd.split(STRESS_MARK, 1)
    prefix_nfc = unicodedata.normalize("NFC", prefix)
    if not prefix_nfc:
        return (_strip_stress(stressed), None)
    return (_strip_stress(stressed), len(prefix_nfc) - 1)


