def _json_bytes(payload: dict[str, Any]) -> bytes:
    # Shards are machine-consumed static assets.  Keeping the canonical key
    # order and UTF-8 text makes builds reproducible while avoiding whitespace
    # that consumes the per-shard mobile budget.
    text = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n"
    return text.encode("utf-8")


def compact_cloze_emit_fields(
    shards: dict[str, dict[str, dict[str, Any]]],
) -> None:
    """Remove builder-only cloze fields before measuring production shards.

    The in-memory builder output deliberately retains diagnostic fields for
    tests, audits, and downstream quality decisions.  The browser only needs
    the sentence, answer, rules, attribution, and validated option metadata;
    omitting the unused diagnostics from the static emit keeps the cloze
    budget focused on distinct eligible lemmas.  Non-empty ``acceptedAlt``
    remains part of the runtime answer contract.
    """
    for level_shards in shards.values():
        payload = level_shards.get("cloze")
        if not isinstance(payload, dict) or not isinstance(payload.get("cloze"), list):
            continue
        for item in payload["cloze"]:
            if not isinstance(item, dict):
                continue
            if not item.get("acceptedAlt"):
                item.pop("acceptedAlt", None)
            for field in ("number", "cefr", "lemma"):
                item.pop(field, None)
            options = item.get("options")
            if isinstance(options, list):
                for option in options:
                    if isinstance(option, dict):
                        option.pop("strategy", None)


def _size_budget(payload: dict[str, Any], raw_limit: int, gzip_limit: int) -> dict[str, int | bool]:
    raw = _json_bytes(payload)
    gzipped = gzip.compress(raw, mtime=0)
    return {
        "rawBytes": len(raw),
        "gzipBytes": len(gzipped),
        "rawLimitBytes": raw_limit,
        "gzipLimitBytes": gzip_limit,
        "ok": len(raw) <= raw_limit and len(gzipped) <= gzip_limit,
    }


def apply_size_budgets(
    shards: dict[str, dict[str, dict[str, Any]]],
    raw_limit: int,
    gzip_limit: int,
    *,
    cloze_raw_limit: int | None = None,
    cloze_gzip_limit: int | None = None,
) -> None:
    """Measure shards and trim only the payload that exceeds its own budget.

    A previous implementation removed the last lexeme from the level index
    whenever *any* mode was oversized.  That made a large recognition or
    classify shard silently delete unrelated cloze cards, and the repeated
    whole-level serialization made production regeneration unnecessarily
    expensive.  Surface payloads (index + lexemes) are trimmed together when
    they themselves exceed a limit; cloze and drill payloads are otherwise
    trimmed independently.
    """

    def body_items(level_shards: dict[str, dict[str, Any]], kind: str) -> list[Any] | None:
        payload = level_shards.get(kind)
        if not isinstance(payload, dict):
            return None
        key = "items" if kind == "index" else "lexemes" if kind == "lexemes" else MODE_BODY_KEYS.get(kind)
        if not key or not isinstance(payload.get(key), list):
            return None
        return payload[key]

    def set_budget(payload: dict[str, Any], kind: str) -> dict[str, int | bool]:
        effective_raw_limit = (
            cloze_raw_limit if kind == "cloze" and cloze_raw_limit is not None else raw_limit
        )
        effective_gzip_limit = (
            cloze_gzip_limit if kind == "cloze" and cloze_gzip_limit is not None else gzip_limit
        )
        budget = _size_budget(payload, effective_raw_limit, effective_gzip_limit)
        payload["sizeBudget"] = budget
        return budget

    def refresh_level_metadata(
        level_shards: dict[str, dict[str, Any]],
        mode_lemma_ids: dict[str, set[str]],
    ) -> None:
        """Keep index counts and mode flags coherent after a local trim."""
        index_items = body_items(level_shards, "index")
        lexemes = body_items(level_shards, "lexemes")
        cloze_items = body_items(level_shards, "cloze")
        if index_items is None:
            return
        lexeme_count = len(lexemes) if lexemes is not None else 0
        cloze_items = cloze_items or []
        cloze_by_lemma: dict[str, list[str]] = {}
        for item in cloze_items:
            if not isinstance(item, dict):
                continue
            lemma_id = _clean_text(item.get("lemmaId"))
            cloze_id = _clean_text(item.get("clozeId"))
            if lemma_id and cloze_id:
                cloze_by_lemma.setdefault(lemma_id, []).append(cloze_id)
        for item in index_items:
            if not isinstance(item, dict):
                continue
            lemma_id = _clean_text(item.get("lemmaId"))
            cloze_ids = cloze_by_lemma.get(lemma_id, [])
            existing_modes = set(item.get("modes") or [])
            modes = ["flashcards"]
            if "matching" in existing_modes:
                modes.append("matching")
            if "choice" in existing_modes:
                modes.append("choice")
            if cloze_ids:
                modes.append("cloze")
            for mode in DRILL_MODES:
                if lemma_id in mode_lemma_ids.get(mode, set()):
                    modes.append(mode)
            item["modes"] = modes
            item["hasCloze"] = bool(cloze_ids)
            item["clozeIds"] = cloze_ids

        counts = level_shards.get("index", {}).get("counts")
        if not isinstance(counts, dict):
            return
        counts["lexemes"] = lexeme_count
        counts["cloze"] = len(cloze_items)
        counts["clozeEligibleLexemes"] = len(cloze_by_lemma)
        counts["clozeCoverage"] = round(
            len(cloze_by_lemma) / lexeme_count, 4
        ) if lexeme_count else 0
        mode_counts = counts.setdefault("modeCounts", {})
        mode_coverage = counts.setdefault("modeCoverage", {})
        if not isinstance(mode_counts, dict) or not isinstance(mode_coverage, dict):
            return
        mode_counts["cloze"] = len(cloze_items)
        mode_coverage["cloze"] = counts["clozeCoverage"]
        for mode in DRILL_MODES:
            mode_items = body_items(level_shards, mode) or []
            mode_counts[mode] = len(mode_items)
            mode_item_lemma_ids = {
                _clean_text(item.get("lemmaId"))
                for item in mode_items
                if isinstance(item, dict)
                and _clean_text(item.get("lemmaId"))
            }
            mode_coverage[mode] = round(
                len(mode_item_lemma_ids) / lexeme_count, 4
            ) if lexeme_count else 0

    def refresh_all_metadata() -> None:
        """Rebuild mode links from each level's post-trim mode payload."""
        mode_lemma_ids_by_level: dict[str, dict[str, set[str]]] = {
            level: {mode: set() for mode in DRILL_MODES}
            for level in shards
        }
        for level, level_shards in shards.items():
            level_lemma_ids = {
                _clean_text(lexeme.get("lemmaId"))
                for lexeme in body_items(level_shards, "lexemes") or []
                if isinstance(lexeme, dict) and _clean_text(lexeme.get("lemmaId"))
            }
            for mode in DRILL_MODES:
                for item in body_items(level_shards, mode) or []:
                    if not isinstance(item, dict):
                        continue
                    lemma_id = _clean_text(item.get("lemmaId"))
                    if lemma_id in level_lemma_ids:
                        mode_lemma_ids_by_level[level][mode].add(lemma_id)

        for level, level_shards in shards.items():
            refresh_level_metadata(level_shards, mode_lemma_ids_by_level[level])

    def filter_to_lemma_ids(
        level_shards: dict[str, dict[str, Any]],
        original_bodies: dict[str, list[Any]],
        kept_ids: set[str],
    ) -> None:
        for kind, original in original_bodies.items():
            current = body_items(level_shards, kind)
            if current is None:
                continue
            current[:] = [
                item
                for item in original
                if not isinstance(item, dict) or _clean_text(item.get("lemmaId")) in kept_ids
            ]

    def item_lemma_id(item: Any, index: int) -> str:
        if isinstance(item, dict):
            lemma_id = _clean_text(item.get("lemmaId"))
            if lemma_id:
                return lemma_id
        # Validator-approved production items all have lemmaId.  Keep malformed
        # fixture rows independently addressable so trimming never aliases them.
        return f"__item_{index}"

    def item_size(item: Any) -> int:
        return len(_json_bytes(item)) if isinstance(item, dict) else len(str(item).encode("utf-8"))

    def coverage_first_rows(original: list[Any]) -> list[tuple[int, Any]]:
        """Order one representative per lemma before duplicate cards.

        The source row order remains authoritative within a lemma (inventory
        rows have already been ranked for playability).  Across lemmas, the
        smallest representative payloads go first so a tight budget admits the
        greatest number of distinct lemma IDs before spending bytes on repeats.
        Remaining cards retain their source order after the representatives.
        """
        groups: dict[str, list[tuple[int, Any]]] = {}
        for index, item in enumerate(original):
            groups.setdefault(item_lemma_id(item, index), []).append((index, item))
        representatives = [rows[0] for rows in groups.values()]
        representatives.sort(key=lambda row: (item_size(row[1]), row[0]))
        representative_indexes = {index for index, _item in representatives}
        extras = [
            (index, item)
            for index, item in enumerate(original)
            if index not in representative_indexes
        ]
        return [*representatives, *extras]

    def trim_surface(
        level: str,
        level_shards: dict[str, dict[str, Any]],
        oversized_surface: set[str],
    ) -> bool:
        index_items = body_items(level_shards, "index")
        if index_items is None:
            return False
        original_index = list(index_items)
        original_bodies = {
            kind: list(items)
            for kind in ("index", "lexemes", "cloze", *DRILL_MODES)
            if (items := body_items(level_shards, kind)) is not None
        }
        if not original_index:
            return False

        lexeme_by_id = {
            _clean_text(item.get("lemmaId")): item
            for item in original_bodies.get("lexemes", [])
            if isinstance(item, dict) and _clean_text(item.get("lemmaId"))
        }
        original_positions = {id(item): index for index, item in enumerate(original_index)}
        cloze_first = [
            item
            for item in original_index
            if isinstance(item, dict) and item.get("clozeIds")
        ]
        cloze_first_ids = {id(item) for item in cloze_first}
        non_cloze = [item for item in original_index if id(item) not in cloze_first_ids]

        def surface_item_size(item: Any) -> int:
            lemma_id = _clean_text(item.get("lemmaId")) if isinstance(item, dict) else None
            return item_size(item) + item_size(lexeme_by_id.get(lemma_id))

        candidates = sorted(
            cloze_first,
            key=lambda item: (surface_item_size(item), original_positions[id(item)]),
        )
        candidates.extend(non_cloze)

        def apply_selection(selected: list[Any]) -> None:
            kept_index = sorted(selected, key=lambda item: original_positions[id(item)])
            index_items[:] = kept_index
            kept_ids = {
                _clean_text(item.get("lemmaId"))
                for item in kept_index
                if isinstance(item, dict) and _clean_text(item.get("lemmaId"))
            }
            filter_to_lemma_ids(level_shards, original_bodies, kept_ids)

        def surface_fits(selected: list[Any]) -> bool:
            apply_selection(selected)
            return all(
                set_budget(level_shards[kind], kind)["ok"]
                for kind in oversized_surface
                if kind in level_shards
            )

        selected: list[Any] = []
        for candidate in candidates:
            trial = [*selected, candidate]
            if surface_fits(trial):
                selected = trial
        apply_selection(selected)
        kept = len(selected)
        if kept == len(original_index):
            return False
        print(
            f"WARN: {', '.join(level_shards[kind]['schema'] + '.' + level for kind in sorted(oversized_surface))} "
            f"exceeds size budget; trimmed surface lexemes {len(original_index)} -> {kept}",
            file=sys.stderr,
        )
        return True

    def trim_mode(level: str, level_shards: dict[str, dict[str, Any]], kind: str) -> bool:
        items = body_items(level_shards, kind)
        if items is None or not items:
            return False
        payload = level_shards[kind]
        original = list(items)

        def mode_fits(candidate: list[Any]) -> bool:
            items[:] = candidate
            return bool(set_budget(payload, kind)["ok"])

        selected: list[Any] = []
        for _index, candidate in coverage_first_rows(original):
            trial = [*selected, candidate]
            if mode_fits(trial):
                selected = trial
        # Selection is coverage-first, but the emitted order remains the source
        # order so deterministic deck sequencing and source ranking are stable.
        selected_ids = {id(item) for item in selected}
        items[:] = [item for item in original if id(item) in selected_ids]
        set_budget(payload, kind)
        kept = len(selected)
        if kept == len(original):
            return False
        original_lemma_count = len(
            {item_lemma_id(item, index) for index, item in enumerate(original)}
        )
        selected_lemma_count = len(
            {item_lemma_id(item, index) for index, item in enumerate(selected)}
        )
        print(
            f"WARN: {payload['schema']}.{level} exceeds size budget; "
            f"trimmed {kind} items {len(original)} -> {kept}; "
            f"eligible lemmas {original_lemma_count} -> {selected_lemma_count}",
            file=sys.stderr,
        )
        return True

    for level, level_shards in shards.items():
        oversized_kinds: set[str] = set()
        for kind, payload in level_shards.items():
            if not isinstance(payload, dict):
                continue
            if not set_budget(payload, kind)["ok"]:
                oversized_kinds.add(kind)
        if not oversized_kinds:
            continue
        oversized_surface = oversized_kinds & {"index", "lexemes"}
        trimmed = trim_surface(level, level_shards, oversized_surface) if oversized_surface else False
        if trimmed:
            refresh_all_metadata()

        # Surface trimming can only reduce mode payloads.  Re-measure all
        # payloads before the mode-local pass so the warning names the actual
        # remaining offender.
        if trimmed:
            oversized_kinds = set()
            for kind, payload in level_shards.items():
                if isinstance(payload, dict) and not set_budget(payload, kind)["ok"]:
                    oversized_kinds.add(kind)
        mode_trimmed = False
        for kind in ("cloze", *DRILL_MODES):
            if kind in oversized_kinds:
                mode_trimmed = trim_mode(level, level_shards, kind) or mode_trimmed
        if mode_trimmed:
            refresh_all_metadata()

        if not trimmed and not mode_trimmed:
            for kind in sorted(oversized_kinds):
                payload = level_shards[kind]
                print(
                    f"WARN: {payload.get('schema', kind)}.{level} remains over size budget "
                    "because its payload has no trim target",
                    file=sys.stderr,
                )
            continue

        # Keep the published metadata truthful.  If an empty payload still
        # cannot fit, leave it intact and make the residual explicit instead
        # of silently deleting unrelated lexemes.
        for kind, payload in level_shards.items():
            if not isinstance(payload, dict):
                continue
            budget = set_budget(payload, kind)
            if not budget["ok"]:
                print(
                    f"WARN: {payload.get('schema', kind)}.{level} remains over size budget "
                    "after its payload was exhausted",
                    file=sys.stderr,
                )


def write_shards(shards: dict[str, dict[str, dict[str, Any]]], out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for level, level_shards in sorted(shards.items()):
        for kind, payload in sorted(level_shards.items()):
            path = out_dir / f"practice-{kind}.{level}.json"
            path.write_bytes(_json_bytes(payload))
            written.append(path)
    return written


