def read_practice_seed(path: Path, *, allow_local_private: bool = False) -> list[dict[str, Any]]:
    """Read a reviewed practice admission overlay.

    A normal seed can only admit an already-public Atlas slug and attach a
    source-backed example. A local-only teacher seed may instead carry an
    attested no-route phrase with a CEFR inherited from its public head lemma;
    it is accepted only through the explicit local-private path and permits
    recognition drills without an example or any public export.
    """
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or payload.get("schema") != "curated-v5-practice-seed-v1":
        raise ValueError(f"unsupported practice seed schema: {path}")
    entries = payload.get("entries")
    if not isinstance(entries, list) or not entries:
        raise ValueError(f"practice seed entries must be a nonempty list: {path}")

    local_only = payload.get("localOnly") is True
    if local_only and not allow_local_private:
        raise ValueError(f"local-only practice seed requires --local-practice-seed: {path}")
    validated: list[dict[str, Any]] = []
    for index, row in enumerate(entries):
        if not isinstance(row, dict):
            raise ValueError(f"practice seed entries[{index}] must be an object: {path}")
        lemma = _clean_text(row.get("lemma"))
        slug = _clean_text(row.get("slug"))
        cefr = _normalize_cefr(row.get("cefr"))
        example = _clean_text(row.get("example"))
        provenance = row.get("provenance")
        is_local_recognition = (
            local_only
            and row.get("sentenceStatus") == "has_candidates"
            and row.get("admissionMode") == "local_practice_private_teacher"
        )
        is_local_no_route = is_local_recognition and row.get("localOnly") is True
        if not lemma or not slug or not cefr:
            raise ValueError(
                f"practice seed entries[{index}] requires lemma, slug, and CEFR: {path}"
            )
        if is_local_recognition:
            if example or provenance is not None:
                raise ValueError(f"local-only practice seed entries[{index}] must not contain example or provenance: {path}")
            if is_local_no_route and _clean_text(row.get("gloss")) is None:
                raise ValueError(f"local-only no-route practice seed entries[{index}] requires a private gloss: {path}")
            validated.append(row)
            continue
        if not example or not isinstance(provenance, dict):
            raise ValueError(
                f"practice seed entries[{index}] requires example and provenance: {path}"
            )
        if row.get("sentenceStatus") != "ok":
            raise ValueError(f"practice seed entries[{index}] must retain sentenceStatus=ok: {path}")
        if _clean_text(provenance.get("source_file")) is None or _clean_text(provenance.get("credit")) is None:
            raise ValueError(f"practice seed entries[{index}] provenance lacks source_file or credit: {path}")
        validated.append(row)
    return validated


def merge_practice_seed_entries(
    entries: list[dict[str, Any]],
    seed_rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Admit reviewed rows without allowing local teacher rows into Atlas.

    Public-route rows wrap their existing Atlas entry. An explicitly marked
    local no-route row becomes an in-memory Practice-only entry: it never
    receives a public route, manifest write, cloze example, or export flag.
    """
    by_slug = {
        slug: index
        for index, entry in enumerate(entries)
        if (slug := _clean_text(entry.get("url_slug"))) is not None
    }
    merged = list(entries)
    applied_slugs: set[str] = set()
    for seed in seed_rows:
        slug = str(seed["slug"])
        target_index = by_slug.get(slug)
        if target_index is None:
            is_local_no_route = (
                seed.get("admissionMode") == "local_practice_private_teacher"
                and seed.get("localOnly") is True
            )
            if not is_local_no_route:
                raise ValueError(f"practice seed slug is not a public Atlas entry: {slug}")
            if slug in applied_slugs:
                continue
            gloss = _clean_text(seed.get("gloss"))
            if gloss is None:
                raise ValueError(f"local-only no-route practice seed requires gloss: {slug}")
            applied_slugs.add(slug)
            merged.append(
                {
                    "lemma": str(seed["lemma"]),
                    "url_slug": slug,
                    "gloss": gloss,
                    "cefr": seed["cefr"],
                    "primary_source": "private_teacher_local_only",
                    "surface_admission": {SURFACE_CLOZE: False, SURFACE_PRACTICE: True},
                    "local_practice_private_teacher": True,
                    "local_only": True,
                }
            )
            continue
        target = merged[target_index]
        if _plain(str(target.get("lemma") or "")) != _plain(str(seed["lemma"])):
            raise ValueError(f"practice seed lemma does not match Atlas slug {slug}")
        is_local_recognition = seed.get("admissionMode") == "local_practice_private_teacher"
        seed_cefr = _normalize_cefr(seed.get("cefr"))
        atlas_cefr = _cefr_level(target)
        if is_local_recognition:
            # Private teacher recognition may carry soft/head/PULS guidance when
            # the public Atlas entry has no enrichment CEFR. Never rewrite the
            # public manifest; only stamp the in-memory practice view.
            if seed_cefr is None:
                raise ValueError(f"local-practice seed requires CEFR: {slug}")
            if atlas_cefr is not None and atlas_cefr != seed_cefr:
                raise ValueError(f"practice seed CEFR differs from Atlas entry for {slug}")
        else:
            if atlas_cefr is None:
                raise ValueError(f"practice seed Atlas entry has no CEFR level: {slug}")
            if atlas_cefr != seed_cefr:
                raise ValueError(f"practice seed CEFR differs from Atlas entry for {slug}")

        # Several source-backed seed rows may attest one canonical Atlas route.
        # Validate every row above, but do not fabricate multiple cards for one
        # lexical item; the earliest seed-row example is deterministic.
        if slug in applied_slugs:
            continue
        applied_slugs.add(slug)

        admission = target.get("surface_admission")
        merged_admission = dict(admission) if isinstance(admission, dict) else {}
        merged_admission[SURFACE_CLOZE] = False if is_local_recognition else bool(merged_admission.get(SURFACE_CLOZE))
        merged_admission["practice"] = True
        merged_entry = {
            **target,
            "surface_admission": merged_admission,
        }
        if is_local_recognition:
            merged_entry["local_practice_private_teacher"] = True
            if atlas_cefr is None:
                merged_entry["cefr"] = seed_cefr
                source = _clean_text(seed.get("cefrSource")) or "local_practice_unleveled"
                merged_entry["cefr_source"] = source
        else:
            merged_entry["practice_example"] = {
                "text": seed["example"],
                "provenance": seed["provenance"],
                "seedRow": seed.get("seedRow"),
            }
        merged[target_index] = merged_entry
    return merged


def read_atlas_db(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"{path} not found; run npm --prefix site run atlas:build-db")
    conn = sqlite3.connect(path)
    try:
        rows = conn.execute(
            "SELECT payload_json FROM article_payloads WHERE is_public_route=1 ORDER BY route_order"
        ).fetchall()
    finally:
        conn.close()
    entries = []
    for (payload_json,) in rows:
        payload = json.loads(payload_json)
        if isinstance(payload, dict):
            entries.append(payload)
    return entries


def read_cloze_sources(path: Path | None) -> list[dict[str, Any]]:
    if path is None or not path.exists():
        print("WARN: no curated cloze sources found; emitting recognition-only deck", file=sys.stderr)
        return []
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, list):
        raise ValueError("cloze sources must be a list")
    rows = [row for row in payload if isinstance(row, dict)]
    if not rows:
        print("WARN: curated cloze sources empty; emitting recognition-only deck", file=sys.stderr)
    return rows


def read_sentence_inventory(path: Path | None) -> list[dict[str, Any]]:
    """Normalize public sentence-inventory examples into cloze candidates.

    The inventory remains the source of truth: we preserve its sentence,
    target form, CEFR, source metadata, and license.  A candidate is formed
    only by replacing one exact attested target token with the exercise slot;
    morphology is checked later against VESUM in ``_build_cloze_items``.
    """
    if path is None or not path.exists():
        print("WARN: no public sentence inventory found; inventory cloze is unavailable", file=sys.stderr)
        return []
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or payload.get("schema") != "atlas-sentence-inventory":
        raise ValueError("sentence inventory must use atlas-sentence-inventory schema")
    rows = payload.get("rows")
    if not isinstance(rows, list):
        raise ValueError("sentence inventory rows must be a list")
    # Small additive residual inventories stay CF-reviewable as separate files
    # while the multi-MB base inventory remains stable on main.
    residual_path = path.with_name(path.stem + ".residual" + path.suffix)
    if residual_path.exists():
        residual_payload = json.loads(residual_path.read_text(encoding="utf-8"))
        if (
            not isinstance(residual_payload, dict)
            or residual_payload.get("schema") != "atlas-sentence-inventory"
        ):
            raise ValueError("residual sentence inventory must use atlas-sentence-inventory schema")
        residual_rows = residual_payload.get("rows")
        if not isinstance(residual_rows, list):
            raise ValueError("residual sentence inventory rows must be a list")
        rows = [*rows, *residual_rows]
    try:
        provenance_path = path.resolve().relative_to(PROJECT_ROOT.resolve()).as_posix()
    except ValueError:
        provenance_path = str(path)

    candidates: list[dict[str, Any]] = []
    for index, row in enumerate(rows):
        if not isinstance(row, dict):
            continue
        uses = row.get("uses")
        if not isinstance(uses, list) or "example" not in uses:
            continue
        lemma = _clean_text(row.get("lemma"))
        lemma_id = _clean_text(row.get("lemmaId"))
        sentence = _clean_text(row.get("sentence"))
        target_form = _clean_text(row.get("targetForm"))
        source_provenance = row.get("provenance")
        license_info = row.get("license")
        if not all((lemma, lemma_id, sentence, target_form)):
            continue
        if not isinstance(source_provenance, dict) or not isinstance(license_info, dict):
            continue
        # Strip whitespace before this check: an OCR bullet/control at the
        # beginning of a token must fail closed, not become a seemingly clean
        # learner sentence after normalization.
        if any(_contains_forbidden_text(value) for value in (lemma, sentence, target_form)):
            continue
        # Treat hyphenated and apostrophe-bearing words as one source token;
        # ``сумка`` in ``сумка-пакет`` is not an independently blankable form.
        # Include ASCII hyphen and Unicode Pd-ish dashes U+2010–U+2015 so en/em
        # dash compounds are not split (CF #6186 F1).
        _dash = r"\-\u2010\u2011\u2012\u2013\u2014\u2015"
        pattern = re.compile(
            rf"(?<![\wʼ'’{_dash}]){re.escape(target_form)}(?![\wʼ'’{_dash}])"
        )
        blanked_sentence, replacements = pattern.subn("___", sentence)
        if replacements != 1:
            continue
        source_fields = {key: value for key, value in source_provenance.items() if key not in {"status", "path"}}
        provenance = {
            "status": "sentence_inventory",
            "path": provenance_path,
            **source_fields,
            "license": license_info,
        }
        candidate = {
            "clozeId": f"{lemma_id}:inventory:{index + 1}",
            "lemma": lemma,
            "lemmaId": lemma_id,
            "sentence": blanked_sentence,
            "originalSentence": sentence,
            "form": target_form,
            "cefr": _clean_text(row.get("cefr")),
            "provenance": provenance,
            "sourceType": "sentence_inventory",
        }
        if row.get("curated") is True:
            candidate["curated"] = True
        candidates.append(candidate)
    candidates = _prefer_inventory_sources(candidates)
    for candidate in candidates:
        candidate.pop("originalSentence", None)
    return candidates


