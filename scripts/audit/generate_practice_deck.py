def _gender_category(labels: list[str]) -> str | None:
    singular_labels = [label for label in labels if "множина" not in label]
    if not singular_labels:
        return None
    genders: set[str] = set()
    for label in singular_labels:
        if "чол." in label:
            genders.add("masculine")
        if "жін." in label:
            genders.add("feminine")
        if "сер." in label:
            genders.add("neuter")
    return next(iter(genders)) if len(genders) == 1 else None


def _aspect_category(labels: list[str]) -> str | None:
    has_present = any("теперішній" in label for label in labels)
    has_future = any("майбутній" in label for label in labels)
    if has_present:
        return "imperfective"
    if has_future:
        return "perfective"
    return None


def _declension_category(entry: dict[str, Any], labels: list[str], paradigm: dict[str, Any]) -> str | None:
    if _morph_pos(entry) != "noun":
        return None
    if not _gender_category(labels):
        return None
    cases = paradigm.get("cases")
    if not isinstance(cases, dict):
        return None
    nominative = cases.get("називний") or cases.get("nominative")
    if not isinstance(nominative, dict):
        return None
    singular = _clean_text(nominative.get("singular"))
    plural = _clean_text(nominative.get("plural"))
    if not singular or (plural and _plain(singular) == _plain(plural)):
        return None
    lemma = _clean_text(entry.get("lemma")) or singular
    gender = _gender_category(labels)
    plain_lemma = _plain(lemma)
    if gender == "feminine" and plain_lemma.endswith(("а", "я")):
        return "declension-1"
    if gender == "neuter" and plain_lemma.endswith(("а", "я")):
        return "declension-4"
    if gender in {"masculine", "neuter"}:
        return "declension-2"
    if gender == "feminine" and not plain_lemma.endswith(("а", "я")):
        return "declension-3"
    return None


def _category_set_payload(set_id: str, value: str, level: str) -> dict[str, Any]:
    set_label_uk, set_label_en = CLASSIFY_SET_LABELS[set_id]
    answer_label_uk, answer_label_en = CLASSIFY_LABELS[set_id][value]
    payload: dict[str, Any] = {
        "setId": set_id,
        "setLabelUk": set_label_uk,
        "answer": value,
        "answerLabelUk": answer_label_uk,
        "options": _classify_options(set_id, level),
    }
    if CEFR_RANK[level] <= CEFR_RANK["A1"]:
        if set_label_en:
            payload["setLabelEn"] = set_label_en
        if answer_label_en:
            payload["answerLabelEn"] = answer_label_en
    return payload


def _build_classify_items(entry: dict[str, Any], lexeme: dict[str, Any]) -> list[dict[str, Any]]:
    if not _normalize_cefr(lexeme.get("cefr")):
        return []
    morphology = _morphology(entry)
    if not morphology:
        return []
    labels = _morph_labels(morphology)
    pos = _morph_pos(entry, morphology)
    pos_buckets = _entry_pos_buckets(entry, morphology)
    sets: list[dict[str, Any]] = []
    if pos == "noun":
        gender = _gender_category(labels)
        if gender:
            sets.append(_category_set_payload("gender", gender, lexeme["cefr"]))
        declension = _declension_category(entry, labels, morphology.get("paradigm") if isinstance(morphology.get("paradigm"), dict) else {})
        if declension and CEFR_RANK[lexeme["cefr"]] >= CEFR_RANK["B1"]:
            sets.append(_category_set_payload("declension", declension, lexeme["cefr"]))
    elif pos == "verb":
        aspect = _aspect_category(labels)
        if aspect and CEFR_RANK[lexeme["cefr"]] >= CEFR_RANK["A2"]:
            sets.append(_category_set_payload("aspect", aspect, lexeme["cefr"]))
    # A context-free POS prompt is unsafe when the entry carries more than one
    # normalized reading.  Morphology remains the source for safe noun/verb
    # drills above, but no single POS answer is emitted in that case.
    if len(pos_buckets) <= 1 and pos in CLASSIFY_LABELS["pos"] and CEFR_RANK[lexeme["cefr"]] >= CEFR_RANK["A2"]:
        sets.append(_category_set_payload("pos", pos, lexeme["cefr"]))
    if not sets:
        return []
    return [
        {
            "classifyId": f"{lexeme['lemmaId']}:classify",
            "lemmaId": lexeme["lemmaId"],
            "lemma": lexeme["lemma"],
            "sets": sets,
            "source": "VESUM",
        }
    ]


CASE_SLOT_LABELS: dict[str, tuple[str, str]] = {
    "називний": ("називний відмінок", "nom."),
    "родовий": ("родовий відмінок", "gen."),
    "давальний": ("давальний відмінок", "dat."),
    "знахідний": ("знахідний відмінок", "acc."),
    "орудний": ("орудний відмінок", "instr."),
    "місцевий": ("місцевий відмінок", "loc."),
    "кличний": ("кличний відмінок", "voc."),
}


def _single_surface(value: Any) -> str | None:
    text = _clean_text(value)
    if not text or "/" in text:
        return None
    return text


def _build_paradigm_items(lexeme: dict[str, Any]) -> list[dict[str, Any]]:
    if not _normalize_cefr(lexeme.get("cefr")):
        return []
    cases = lexeme.get("paradigm", {}).get("cases")
    if not isinstance(cases, dict):
        return []
    slots: list[dict[str, str]] = []
    seen_forms: set[str] = set()
    duplicate_forms: set[str] = set()
    for case_name, forms in cases.items():
        if not isinstance(case_name, str) or not isinstance(forms, dict):
            continue
        case_key = case_name.strip()
        if case_key not in CASE_SLOT_LABELS:
            continue
        for number in NUMBER_KEYS:
            form = _single_surface(forms.get(number))
            if not form:
                continue
            normalized = _plain(form)
            if normalized in seen_forms:
                duplicate_forms.add(normalized)
            seen_forms.add(normalized)
            slots.append({"case": case_key, "number": number, "form": form})
    usable = [slot for slot in slots if _plain(slot["form"]) not in duplicate_forms]
    if len(usable) < 3:
        return []
    forms = [slot["form"] for slot in usable]
    items = []
    for index, slot in enumerate(usable):
        label_uk, label_en = CASE_SLOT_LABELS[slot["case"]]
        number_uk = "однина" if slot["number"] == "singular" else "множина"
        number_en = "sg" if slot["number"] == "singular" else "pl"
        options = [{"label": slot["form"], "kind": "answer"}]
        for other in usable:
            if other is slot or _plain(other["form"]) == _plain(slot["form"]):
                continue
            options.append({"label": other["form"], "kind": "same-paradigm"})
            if len(options) == 4:
                break
        if len(options) < 4:
            continue
        paradigm_id = f"{lexeme['lemmaId']}:paradigm:{index + 1}"
        answer_index = int(hashlib.sha1(paradigm_id.encode("utf-8")).hexdigest()[:2], 16) % len(options)
        answer = options.pop(0)
        options.insert(answer_index, answer)
        item: dict[str, Any] = {
            "paradigmId": paradigm_id,
            "lemmaId": lexeme["lemmaId"],
            "lemma": lexeme["lemma"],
            "slot": {
                "case": slot["case"],
                "number": slot["number"],
                "labelUk": f"{label_uk}, {number_uk}",
            },
            "form": slot["form"],
            "options": options,
        }
        if CEFR_RANK[lexeme["cefr"]] <= CEFR_RANK["A1"]:
            item["slot"]["labelEn"] = f"{label_en} {number_en}"
        items.append(item)
    return items


def _section_items(entry: dict[str, Any], section_name: str) -> list[str]:
    sections = entry.get("sections")
    if not isinstance(sections, dict):
        return []
    section = sections.get(section_name)
    if not isinstance(section, dict):
        return []
    items = section.get("items")
    if not isinstance(items, list):
        return []
    cleaned: list[str] = []
    for item in items:
        text = _clean_text(re.sub(r"\s*\([^)]*\)\s*", "", str(item)))
        if text:
            cleaned.append(text)
    return cleaned


def _synonym_pair_key(a: str, b: str, polarity: str) -> tuple[str, str, str]:
    a_plain = _plain(a)
    b_plain = _plain(b)
    if a_plain > b_plain:
        a_plain, b_plain = b_plain, a_plain
    return (a_plain, b_plain, polarity)


def _synonym_core_errors(record: dict[str, Any]) -> list[str]:
    """Errors that make a record unusable — the pair key cannot be formed."""
    errors: list[str] = []
    for field in ("a", "b", "polarity"):
        if not _clean_text(record.get(field)):
            errors.append(f"synonym verdict missing {field}")
    return errors


def _synonym_exception_flag_errors(record: dict[str, Any]) -> list[str]:
    """Errors specific to the additive a2Exception flag (curator gate, type)."""
    errors: list[str] = []
    a2_exception = record.get("a2Exception")
    curator = _clean_text(record.get("curator"))
    if a2_exception not in (None, False, True):
        errors.append("synonym verdict a2Exception must be boolean")
    if a2_exception is True and not curator:
        errors.append("synonym verdict a2Exception requires curator")
    if curator and a2_exception is not True:
        errors.append("synonym verdict curator requires a2Exception: true")
    return errors


def validate_synonym_verdict_record(record: dict[str, Any]) -> list[str]:
    return _synonym_core_errors(record) + _synonym_exception_flag_errors(record)


def build_synonym_verdict_sets(
    synonym_verdicts: dict[str, Any] | None,
) -> tuple[set[tuple[str, str, str]], set[tuple[str, str, str]], set[tuple[str, str, str]]]:
    approved_set: set[tuple[str, str, str]] = set()
    rejected_set: set[tuple[str, str, str]] = set()
    a2_exception_set: set[tuple[str, str, str]] = set()
    if not synonym_verdicts:
        return approved_set, rejected_set, a2_exception_set
    for item in synonym_verdicts.get("approved", []):
        if not isinstance(item, dict):
            continue
        core_errors = _synonym_core_errors(item)
        if core_errors:
            print(f"WARN: synonym verdict dropped: {'; '.join(core_errors)}", file=sys.stderr)
            continue
        key = _synonym_pair_key(str(item["a"]), str(item["b"]), str(item["polarity"]))
        approved_set.add(key)
        flag_errors = _synonym_exception_flag_errors(item)
        if flag_errors:
            # The a2Exception flag is additive: if it fails validation, drop only the
            # flag (the pair stays approved at the B1+ default) instead of suppressing
            # the whole approved pair.
            print(
                "WARN: synonym verdict a2Exception flag dropped (pair stays B1+): "
                + "; ".join(flag_errors),
                file=sys.stderr,
            )
        elif item.get("a2Exception") is True:
            a2_exception_set.add(key)
    for item in synonym_verdicts.get("rejected", []):
        if not isinstance(item, dict):
            continue
        core_errors = _synonym_core_errors(item)
        if core_errors:
            print(f"WARN: synonym verdict dropped: {'; '.join(core_errors)}", file=sys.stderr)
            continue
        key = _synonym_pair_key(str(item["a"]), str(item["b"]), str(item["polarity"]))
        rejected_set.add(key)
    return approved_set, rejected_set, a2_exception_set


def _synonym_option(
    label: str,
    lemma_id: str,
    kind: str,
) -> dict[str, str]:
    return {"label": label, "lemmaId": lemma_id, "kind": kind}


def _valid_synonym_distractors(
    answer: dict[str, Any],
    prompt: dict[str, Any],
    lexemes: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    blocked_heads = {_headword(prompt["gloss"]), _headword(answer["gloss"])}
    candidates = []
    for lexeme in lexemes:
        if lexeme["lemmaId"] in {prompt["lemmaId"], answer["lemmaId"]}:
            continue
        if not lexeme.get("cefr"):
            continue
        if lexeme.get("pos") != answer.get("pos"):
            continue
        if _headword(lexeme["gloss"]) in blocked_heads:
            continue
        if _plain(lexeme["lemma"]) in {_plain(prompt["lemma"]), _plain(answer["lemma"])}:
            continue
        candidates.append(lexeme)
    answer_len = len(answer["lemma"])
    return sorted(
        candidates,
        key=lambda item: (
            abs(len(item["lemma"]) - answer_len),
            item["cefr"] != answer["cefr"],
            item["lemmaId"],
        ),
    )


def _synonym_availability_level(
    prompt: dict[str, Any],
    target: dict[str, Any],
    pair_key: tuple[str, str, str],
    a2_exception_set: set[tuple[str, str, str]],
) -> str:
    """Return the learner level at which a verified pair becomes available.

    Synonym cards have a B1 floor by default.  The floor is a placement level,
    not a reason to discard a verified lower-level prompt: cumulative decks
    already load lower lexeme shards.  A curator-approved both-leg-A2
    exception may lower that floor to A2, but never to A1.
    """
    both_legs_a2 = prompt["cefr"] == "A2" and target["cefr"] == "A2"
    floor = "A2" if pair_key in a2_exception_set and both_legs_a2 else SYNONYM_DEFAULT_AVAILABILITY
    return max((floor, prompt["cefr"], target["cefr"]), key=lambda level: CEFR_RANK[level])


def _lexeme_lists_synonym_target(entry: dict[str, Any], target_plain: str, polarity: str) -> bool:
    section_name = "synonyms" if polarity == "synonym" else "antonyms"
    return any(_plain(label) == target_plain for label in _section_items(entry, section_name))


def nominate_a2_synonym_pairs(
    entries: list[dict[str, Any]],
    synonym_verdicts: dict[str, Any] | None,
    all_lexemes: list[dict[str, Any]],
    by_plain_lemma: dict[str, dict[str, Any]],
) -> list[dict[str, Any]]:
    """Report approved both-leg-A2 synonym pairs for curator a2Exception review (#4698)."""
    approved_set, _, _a2_exception_set = build_synonym_verdict_sets(synonym_verdicts)
    entry_by_lemma_id = {
        _stable_lemma_id(entry): entry
        for entry in entries
        if _stable_lemma_id(entry)
    }
    nominations: list[dict[str, Any]] = []
    for item in (synonym_verdicts or {}).get("approved", []):
        if not isinstance(item, dict):
            continue
        if item.get("a2Exception") is True:
            continue
        key = _synonym_pair_key(str(item["a"]), str(item["b"]), str(item["polarity"]))
        if key not in approved_set:
            continue
        lexeme_a = by_plain_lemma.get(key[0])
        lexeme_b = by_plain_lemma.get(key[1])
        if not lexeme_a or not lexeme_b:
            continue
        if lexeme_a["cefr"] != "A2" or lexeme_b["cefr"] != "A2":
            continue
        entry_a = entry_by_lemma_id.get(lexeme_a["lemmaId"])
        entry_b = entry_by_lemma_id.get(lexeme_b["lemmaId"])
        if not entry_a or not entry_b:
            continue
        polarity = str(item["polarity"])
        linked = (
            _lexeme_lists_synonym_target(entry_a, key[1], polarity)
            or _lexeme_lists_synonym_target(entry_b, key[0], polarity)
        )
        if not linked:
            continue
        distractors_ab = len(_valid_synonym_distractors(lexeme_b, lexeme_a, all_lexemes))
        distractors_ba = len(_valid_synonym_distractors(lexeme_a, lexeme_b, all_lexemes))
        if max(distractors_ab, distractors_ba) < 3:
            continue
        nominations.append(
            {
                "a": lexeme_a["lemma"],
                "b": lexeme_b["lemma"],
                "polarity": polarity,
                "sources": sorted(set(item.get("sources") or [])),
                "prompt_cefr": lexeme_a["cefr"],
                "target_cefr": lexeme_b["cefr"],
                "distractors_ab": distractors_ab,
                "distractors_ba": distractors_ba,
                "pair_key": key,
            }
        )
    nominations.sort(key=lambda row: (row["pair_key"], row["a"], row["b"]))
    return nominations


def format_a2_synonym_nomination_report(rows: list[dict[str, Any]]) -> str:
    header = "a\tb\tpolarity\tsources\tprompt_cefr\ttarget_cefr\tdistractors_ab\tdistractors_ba"
    lines = [header, f"total\t{len(rows)}"]
    for row in rows:
        sources = ",".join(row.get("sources") or [])
        lines.append(
            "\t".join(
                (
                    str(row["a"]),
                    str(row["b"]),
                    str(row["polarity"]),
                    sources,
                    str(row["prompt_cefr"]),
                    str(row["target_cefr"]),
                    str(row["distractors_ab"]),
                    str(row["distractors_ba"]),
                )
            )
        )
    return "\n".join(lines) + "\n"


def _build_synonym_items(
    lexemes_by_entry: list[tuple[dict[str, Any], dict[str, Any]]],
    by_plain_lemma: dict[str, dict[str, Any]],
    all_lexemes: list[dict[str, Any]],
    deck_version: str,
    approved_set: set[tuple[str, str, str]],
    rejected_set: set[tuple[str, str, str]],
    a2_exception_set: set[tuple[str, str, str]],
    synonym_verdicts_loaded: bool,
    encountered_pairs: dict[str, dict[str, set[tuple[str, str, str]]]],
) -> list[dict[str, Any]]:
    """Build cards from the approved verdict set, not relation-link discovery.

    Manifest relation sections remain useful for reporting unreviewed and
    rejected candidates, but an approved verdict is the source of truth for
    emission.  This also covers approved pairs whose two Atlas entries do not
    link back to one another through the current relation sections.
    """
    for entry, lexeme in lexemes_by_entry:
        if not lexeme.get("cefr"):
            continue
        for polarity, section_name in (("synonym", "synonyms"), ("antonym", "antonyms")):
            for target_label in _section_items(entry, section_name):
                target = by_plain_lemma.get(_plain(target_label))
                if not target or not target.get("cefr"):
                    continue
                pair_key = _synonym_pair_key(lexeme["lemma"], target["lemma"], polarity)
                flagged_a2_exception = pair_key in a2_exception_set
                both_legs_a2 = lexeme["cefr"] == "A2" and target["cefr"] == "A2"
                a2_exception = flagged_a2_exception and both_legs_a2
                if (
                    CEFR_RANK[lexeme["cefr"]] < CEFR_RANK[SYNONYM_DEFAULT_AVAILABILITY]
                    and not a2_exception
                ):
                    continue
                if CEFR_RANK[target["cefr"]] > CEFR_RANK[lexeme["cefr"]]:
                    continue
                if len(_valid_synonym_distractors(target, lexeme, all_lexemes)) < 3:
                    continue
                if not synonym_verdicts_loaded:
                    encountered_pairs[lexeme["cefr"]]["awaiting"].add(pair_key)
                elif pair_key in rejected_set:
                    encountered_pairs[lexeme["cefr"]]["rejected"].add(pair_key)
                elif pair_key not in approved_set:
                    encountered_pairs[lexeme["cefr"]]["awaiting"].add(pair_key)

    if not synonym_verdicts_loaded:
        return []

    items: list[dict[str, Any]] = []
    warned_a2_flags: set[tuple[str, str, str]] = set()
    for pair_key in sorted(approved_set):
        prompt_a = by_plain_lemma.get(pair_key[0])
        prompt_b = by_plain_lemma.get(pair_key[1])
        if not prompt_a or not prompt_b or not prompt_a.get("cefr") or not prompt_b.get("cefr"):
            continue

        both_legs_a2 = prompt_a["cefr"] == "A2" and prompt_b["cefr"] == "A2"
        if pair_key in a2_exception_set and not both_legs_a2 and pair_key not in warned_a2_flags:
            print(
                f"WARN: synonym pair {pair_key!r} a2Exception ignored: "
                "both legs must be A2 vocabulary; staying B1+",
                file=sys.stderr,
            )
            warned_a2_flags.add(pair_key)
        level = _synonym_availability_level(prompt_a, prompt_b, pair_key, a2_exception_set)
        encountered_pairs[level]["approved"].add(pair_key)

        for prompt, target in ((prompt_a, prompt_b), (prompt_b, prompt_a)):
            distractors = _valid_synonym_distractors(target, prompt, all_lexemes)
            if len(distractors) < 3:
                continue

            polarity = pair_key[2]
            key = "\x1f".join((deck_version, prompt["lemmaId"], target["lemmaId"], polarity))
            synonym_id = "syn_" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]
            options = [
                _synonym_option(target["lemma"], target["lemmaId"], "answer"),
                *[
                    _synonym_option(distractor["lemma"], distractor["lemmaId"], "distractor")
                    for distractor in distractors[:3]
                ],
            ]
            answer_index = int(hashlib.sha1(synonym_id.encode("utf-8")).hexdigest()[:2], 16) % len(options)
            answer = options.pop(0)
            options.insert(answer_index, answer)
            items.append(
                {
                    "synonymId": synonym_id,
                    "lemmaId": prompt["lemmaId"],
                    "targetLemmaId": target["lemmaId"],
                    "polarity": polarity,
                    "prompt": prompt["lemma"],
                    "answer": target["lemma"],
                    "level": level,
                    "promptLevel": prompt["cefr"],
                    "options": options,
                    "source": "ukrajinet-auto-translation",
                }
            )
    return items


def _clean_text_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [text for item in value if (text := _clean_text(item))]


def _heritage_availability_level(pair: dict[str, Any]) -> str:
    # CEFR is a curator-facing guidance signal, not a hard exclusion from a
    # learner's path.  B1 remains the default for unreviewed placement, while
    # a curator may explicitly admit an easy native replacement at A1.
    return _normalize_cefr(pair.get("cefrAvailability")) or HERITAGE_DEFAULT_AVAILABILITY


def _curated_prompt_en(frame: dict[str, Any]) -> str | None:
    """Return curator-supplied English only; never manufacture a translation."""
    for field in ("sentence_en", "prompt_en", "sentence_with_slot_en"):
        english = _clean_text(frame.get(field))
        if english and not re.match(r"^context sentence for\b", english, flags=re.IGNORECASE):
            return english
    return None


def _heritage_frame_errors(frame: Any, kind: str) -> list[str]:
    errors: list[str] = []
    if not isinstance(frame, dict):
        return ["heritage_pair frame must be an object"]
    sentence = _clean_text(frame.get("sentence_with_slot"))
    if not sentence:
        errors.append("heritage_pair frame missing sentence_with_slot")
    elif sentence.count("___") != 1:
        errors.append("heritage_pair frame sentence_with_slot must contain exactly one ___ slot")
    for field in ("answer_form", "calque_form", "origin"):
        if not _clean_text(frame.get(field)):
            errors.append(f"heritage_pair frame missing {field}")
    if kind == "sense_restricted" and frame.get("disambiguated") is not True:
        errors.append("sense_restricted heritage_pair frames require disambiguated: true")
    distractors = frame.get("distractors")
    if distractors is not None:
        if not isinstance(distractors, list):
            errors.append("heritage_pair frame distractors must be a list")
        else:
            for i, d in enumerate(distractors):
                if not isinstance(d, str) or not d.strip():
                    errors.append(f"heritage_pair frame distractors[{i}] must be a non-empty string")
    return errors


def _valid_heritage_frames(pair: dict[str, Any]) -> list[dict[str, Any]]:
    kind = _clean_text(pair.get("kind")) or ""
    frames = pair.get("frames")
    if not isinstance(frames, list):
        return []
    return [
        frame
        for frame in frames
        if isinstance(frame, dict) and not _heritage_frame_errors(frame, kind)
    ]


def _heritage_pair_native_lexeme(
    pair: dict[str, Any],
    lexemes_by_id: dict[str, dict[str, Any]],
) -> dict[str, Any] | None:
    native_slug = _clean_text(pair.get("nativeSlug"))
    if native_slug and native_slug in lexemes_by_id:
        return lexemes_by_id[native_slug]
    return None


def _heritage_option(
    label: str,
    kind: str,
    lemma_id: str | None = None,
    pos: str | None = None,
) -> dict[str, str]:
    option = {"label": label, "kind": kind}
    if lemma_id:
        option["lemmaId"] = lemma_id
    if pos:
        option["pos"] = pos
    return option


def _valid_heritage_distractors(
    answer: dict[str, Any],
    frame: dict[str, Any],
    pair: dict[str, Any],
    lexemes: list[dict[str, Any]],
    level: str,
    verifier: VesumVerifier | None = None,
) -> list[dict[str, Any]]:
    answer_form = _clean_text(frame.get("answer_form")) or answer["lemma"]
    calque_form = _clean_text(frame.get("calque_form")) or ""
    blocked = {
        _plain(answer["lemma"]),
        _plain(answer_form),
        _plain(calque_form),
        _plain(_clean_text(pair.get("calqueLabel")) or ""),
        *{_plain(value) for value in _clean_text_list(pair.get("corrections"))},
        *{_plain(value) for value in _clean_text_list(pair.get("calqueSurfaces"))},
    }

    curated_distractors = frame.get("distractors")
    if curated_distractors is not None:
        resolved_distractors = []
        for dist_lemma in curated_distractors:
            dist_lemma_clean = _clean_text(dist_lemma)
            if not dist_lemma_clean:
                continue

            # Find matching lexeme in all_lexemes (lexemes) first
            matching_lexeme = next((l for l in lexemes if _plain(l["lemma"]) == _plain(dist_lemma_clean)), None)
            if matching_lexeme:
                resolved_distractors.append({
                    **matching_lexeme,
                    "pos": answer.get("pos")
                })
            else:
                # Verify against VESUM
                if verifier is not None:
                    plain_dist = _plain(dist_lemma_clean)
                    matches = verifier.verify_words([plain_dist]).get(plain_dist, [])
                    if not matches:
                        matches = verifier.verify_words([dist_lemma_clean]).get(dist_lemma_clean, [])

                    if matches:
                        resolved_distractors.append({
                            "lemmaId": f"cur_{_plain(dist_lemma_clean)}",
                            "lemma": dist_lemma_clean,
                            "lemmaPlain": _plain(dist_lemma_clean),
                            "pos": answer.get("pos"),
                            "cefr": level,
                        })
                else:
                    resolved_distractors.append({
                        "lemmaId": f"cur_{_plain(dist_lemma_clean)}",
                        "lemma": dist_lemma_clean,
                        "lemmaPlain": _plain(dist_lemma_clean),
                        "pos": answer.get("pos"),
                        "cefr": level,
                    })
        return resolved_distractors

    candidates = []
    base_labels = [answer_form, calque_form]
    for lexeme in lexemes:
        if lexeme["lemmaId"] == answer["lemmaId"]:
            continue
        if lexeme.get("pos") != answer.get("pos"):
            continue
        if CEFR_RANK[lexeme["cefr"]] > CEFR_RANK[level]:
            continue
        label = lexeme["lemma"]
        if _plain(label) in blocked:
            continue
        labels = [*base_labels, label]
        if max(len(item) for item in labels) - min(len(item) for item in labels) > 12:
            continue
        candidates.append(lexeme)
    answer_len = len(answer_form)
    return sorted(
        candidates,
        key=lambda item: (
            abs(len(item["lemma"]) - answer_len),
            item["cefr"] != answer["cefr"],
            item["lemmaId"],
        ),
    )


def _shuffle_heritage_options(heritage_id: str, options: list[dict[str, str]]) -> list[dict[str, str]]:
    return sorted(
        options,
        key=lambda option: hashlib.sha1(
            "\x1f".join(
                (
                    heritage_id,
                    option.get("kind", ""),
                    option.get("label", ""),
                    option.get("lemmaId", ""),
                )
            ).encode("utf-8")
        ).hexdigest(),
    )


def _strip_heritage_option_metadata(item: dict[str, Any]) -> dict[str, Any]:
    stripped = {**item}
    stripped["options"] = [
        {"label": str(option.get("label") or "")}
        for option in item.get("options", [])
        if isinstance(option, dict)
    ]
    return stripped


def _build_heritage_items(
    pair: dict[str, Any],
    lexeme: dict[str, Any],
    all_lexemes: list[dict[str, Any]],
    deck_version: str,
    *,
    verifier: VesumVerifier | None = None,
    public_options: bool = True,
) -> list[dict[str, Any]]:
    frames = _valid_heritage_frames(pair)
    if not frames:
        return []
    # Heritage SRS identity is the native lemma, and the static client reaches
    # drill items through the same-level index/lexeme shards — so the item must
    # sit AT OR ABOVE the lexeme's shard (cumulative loading pulls lower-level
    # lexeme shards in, keeping the join resolvable). But the curator
    # availability floor is a curator-selected guidance floor — level-local
    # placement must never drop below it, but explicitly A1-admitted pairs are
    # allowed when the native lemma and pedagogy are suitable (#6140).
    lexeme_level = _normalize_cefr(lexeme.get("cefr"))
    if not lexeme_level:
        return []
    floor = _heritage_availability_level(pair)
    level = max(
        (lvl for lvl in (lexeme_level, floor) if lvl),
        key=lambda lvl: CEFR_RANK[lvl],
        default=floor,
    )
    items: list[dict[str, Any]] = []
    for index, frame in enumerate(frames, start=1):
        answer_form = _clean_text(frame.get("answer_form"))
        calque_form = _clean_text(frame.get("calque_form"))
        sentence = _clean_text(frame.get("sentence_with_slot"))
        origin = _clean_text(frame.get("origin"))
        rationale = _clean_text(pair.get("rationale")) or ""
        citations = _clean_text_list(pair.get("citations"))
        pair_label = _clean_text(pair.get("calqueLabel")) or lexeme["lemmaId"]
        if not all((answer_form, calque_form, sentence, origin, rationale, citations)):
            print(
                f"WARN: heritage_pair {pair_label!r} frame {index} dropped: missing required field",
                file=sys.stderr,
            )
            continue
        distractors = _valid_heritage_distractors(lexeme, frame, pair, all_lexemes, level, verifier=verifier)
        if len(distractors) < 2:
            print(
                f"WARN: heritage_pair {pair_label!r} frame {index} dropped: "
                f"{len(distractors)} same-POS distractors within level {level} (need 2)",
                file=sys.stderr,
            )
            continue
        key = "\x1f".join((deck_version, lexeme["lemmaId"], sentence, answer_form, calque_form, origin))
        heritage_id = "her_" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]
        options = [
            _heritage_option(answer_form, "answer", lexeme["lemmaId"], lexeme.get("pos")),
            _heritage_option(calque_form, "calque"),
            *[
                _heritage_option(distractor["lemma"], "distractor", distractor["lemmaId"], distractor.get("pos"))
                for distractor in distractors[:2]
            ],
        ]
        item: dict[str, Any] = {
            "heritageId": heritage_id,
            "lemmaId": lexeme["lemmaId"],
            # §9.5: SRS identity is the native lemma, not each sentence frame.
            "srsKey": f"{lexeme['lemmaId']}::heritage",
            "lemma": lexeme["lemma"],
            "nativeLemma": _clean_text(pair.get("nativeLemma")) or lexeme["lemma"],
            "calqueLabel": _clean_text(pair.get("calqueLabel")) or calque_form,
            "kind": _clean_text(pair.get("kind")) or "lexical",
            "severity": _clean_text(pair.get("severity")) or "enrichment",
            "prompt": sentence,
            "answer": answer_form,
            "calque": calque_form,
            "origin": origin,
            "frameIndex": index,
            "cefr": level,
            "options": _shuffle_heritage_options(heritage_id, options),
            "rationale": rationale,
            "citations": citations,
            "corrections": _clean_text_list(pair.get("corrections")),
            "sourceFamily": _clean_text(pair.get("sourceFamily")) or "",
        }
        if prompt_en := _curated_prompt_en(frame):
            item["promptEn"] = prompt_en
        rat_uk = _clean_text(pair.get("rationaleUk"))
        if rat_uk:
            item["rationaleUk"] = rat_uk
        if item["kind"] == "sense_restricted":
            item["calqueSense"] = _clean_text(pair.get("calqueSense")) or ""
            item["authenticSense"] = _clean_text(pair.get("authenticSense")) or ""
        items.append(_strip_heritage_option_metadata(item) if public_options else item)
    return items


