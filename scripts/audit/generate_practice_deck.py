def _representative_seed_entries(
    seed_entries: list[dict[str, Any]],
    limit: int,
) -> list[dict[str, Any]]:
    """Select seed entries evenly across available CEFR/POS strata.

    This is deliberately only an explicit gold-slice profile.  Normal decks
    retain their priority ordering; a small verification deck needs coverage
    across the admitted set without inventing any lexical metadata.
    """
    strata: dict[int, dict[str, list[dict[str, Any]]]] = {}
    for entry in seed_entries:
        level = _cefr_level(entry) or ""
        rank = CEFR_RANK.get(level, len(CEFR_RANK))
        pos = _clean_text(entry.get("pos")) or "other"
        strata.setdefault(rank, {}).setdefault(pos, []).append(entry)

    level_queues: dict[int, list[dict[str, Any]]] = {}
    for rank, pos_groups in strata.items():
        for entries in pos_groups.values():
            entries.sort(key=_stable_lemma_id)
        queue: list[dict[str, Any]] = []
        while True:
            added = False
            for pos in sorted(pos_groups):
                entries = pos_groups[pos]
                if entries:
                    queue.append(entries.pop(0))
                    added = True
            if not added:
                break
        level_queues[rank] = queue

    selected: list[dict[str, Any]] = []
    while len(selected) < limit:
        added = False
        for rank in sorted(level_queues):
            entries = level_queues[rank]
            if not entries:
                continue
            selected.append(entries.pop(0))
            added = True
            if len(selected) == limit:
                break
        if not added:
            break
    return selected


def _select_practice_lexemes(
    entries: list[dict[str, Any]],
    verifier: VesumVerifier,
    config: BuildConfig,
    priority_lemma_keys: set[str] | None = None,
) -> tuple[list[tuple[dict[str, Any], dict[str, Any]]], list[dict[str, Any]], dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    eligible = [entry for entry in entries if is_practice_eligible(entry)]
    # A practice seed is an explicit curriculum admission, not merely a source of
    # optional fill entries. Keep those entries ahead of ordinary course/fill
    # selection so the per-shard size budget cannot silently discard the curated
    # overlay from the tail of a level.
    seed_entries = [
        entry
        for entry in eligible
        if (
            isinstance(entry.get("practice_example"), dict)
            or entry.get("local_practice_private_teacher") is True
            or entry.get("curated_membership") is True
        )
        and is_surface_admitted(entry, SURFACE_PRACTICE)
    ]
    seed_entry_ids = {id(entry) for entry in seed_entries}
    non_seed_entries = [entry for entry in eligible if id(entry) not in seed_entry_ids]
    priority_keys = priority_lemma_keys or set()
    priority_entries = [
        entry
        for entry in non_seed_entries
        if _stable_lemma_id(entry) in priority_keys
        or (_clean_text(entry.get("lemma")) and _plain(str(entry["lemma"])) in priority_keys)
    ]
    priority_entry_ids = {id(entry) for entry in priority_entries}
    remaining_entries = [entry for entry in non_seed_entries if id(entry) not in priority_entry_ids]
    course_entries = [entry for entry in remaining_entries if _course_usage(entry)]
    fill_entries = [entry for entry in remaining_entries if not _course_usage(entry)]
    seed_entries.sort(key=_stable_lemma_id)
    priority_entries.sort(key=_stable_lemma_id)
    if config.seed_selection == "representative":
        seed_entries = _representative_seed_entries(seed_entries, config.target)
    course_entries.sort(key=_course_key)
    fill_entries.sort(
        key=lambda entry: (CEFR_RANK.get(_cefr_level(entry) or "", len(CEFR_RANK)), _stable_lemma_id(entry))
    )
    selected = list(seed_entries)
    selected.extend(priority_entries)
    selected.extend(course_entries)
    if len(selected) < config.target:
        selected.extend(fill_entries[: config.target - len(selected)])

    lexemes_by_entry: list[tuple[dict[str, Any], dict[str, Any]]] = []
    for entry in selected[: config.target]:
        lexeme = _build_lexeme(entry, verifier)
        if lexeme:
            lexemes_by_entry.append((entry, lexeme))

    all_lexemes = [lexeme for _, lexeme in lexemes_by_entry]
    lexemes_by_id = {lexeme["lemmaId"]: lexeme for lexeme in all_lexemes}
    by_plain_lemma: dict[str, dict[str, Any]] = {}
    for lexeme in all_lexemes:
        by_plain_lemma.setdefault(_plain(lexeme["lemma"]), lexeme)
    return lexemes_by_entry, all_lexemes, by_plain_lemma, lexemes_by_id


def _practice_priority_keys(
    cloze_sources: list[dict[str, Any]],
    heritage_pairs: list[dict[str, Any]] | None,
    paronym_pairs: list[dict[str, Any]] | None,
    synonym_verdicts: dict[str, Any] | None,
    antonym_pairs: list[dict[str, Any]] | None = None,
    homonym_pairs: list[dict[str, Any]] | None = None,
) -> set[str]:
    """Keep source-backed thin-mode legs ahead of ordinary fill lexemes.

    The size budget removes tail lexemes.  Place every existing cloze or
    approved pair leg before the general course/fill population so a full
    rebuild does not silently cut the thin modes first.
    """
    keys: set[str] = set()

    def add(value: Any) -> None:
        text = _clean_text(value)
        if text:
            keys.add(text)
            keys.add(_plain(text))

    for row in cloze_sources:
        add(row.get("lemmaId"))
        add(row.get("lemma"))
    for pair in heritage_pairs or []:
        add(pair.get("nativeSlug"))
    for pair in paronym_pairs or []:
        add(pair.get("slugA"))
        add(pair.get("slugB"))
    for pair in antonym_pairs or []:
        add(pair.get("slugA"))
        add(pair.get("slugB"))
    for pair in homonym_pairs or []:
        add(pair.get("slugA"))
        add(pair.get("slugB"))
    for pair in (synonym_verdicts or {}).get("approved", []):
        if isinstance(pair, dict):
            add(pair.get("a"))
            add(pair.get("b"))
    return keys


def build_practice_shards(
    entries: list[dict[str, Any]],
    allowlist: ReviewedSourceAllowlist,
    verifier: VesumVerifier,
    cloze_sources: list[dict[str, Any]] | None = None,
    config: BuildConfig | None = None,
    heritage_pairs: list[dict[str, Any]] | None = None,
    paronym_pairs: list[dict[str, Any]] | None = None,
    synonym_verdicts: dict[str, Any] | None = None,
    end_dictionary_stress: dict[str, dict[str, str]] | None = None,
    antonym_pairs: list[dict[str, Any]] | None = None,
    homonym_pairs: list[dict[str, Any]] | None = None,
) -> dict[str, dict[str, dict[str, Any]]]:
    if isinstance(cloze_sources, BuildConfig) and config is None:
        config = cloze_sources
        cloze_sources = None
    if config is None:
        config = BuildConfig()
    if config.target < 0:
        raise ValueError("target must be non-negative")

    if synonym_verdicts is None:
        print("WARN: synonym verdicts file not found; emitting no synonym items", file=sys.stderr)
        synonym_verdicts_loaded = False
    elif isinstance(synonym_verdicts, Path):
        synonym_verdicts = read_synonym_verdicts(synonym_verdicts)
        synonym_verdicts_loaded = synonym_verdicts is not None
    else:
        synonym_verdicts_loaded = True
    approved_set, rejected_set, a2_exception_set = build_synonym_verdict_sets(synonym_verdicts)

    encountered_pairs: dict[str, dict[str, set[tuple[str, str, str]]]] = {
        level: {"approved": set(), "rejected": set(), "awaiting": set()}
        for level in CEFR_ORDER
    }

    deck_version = compute_deck_version(
        entries,
        heritage_pairs,
        paronym_pairs,
        synonym_verdicts,
        cloze_sources,
        SCHEMA_VERSION,
        antonym_pairs=antonym_pairs,
        homonym_pairs=homonym_pairs,
    )
    # Seed from the DATA-ONLY fingerprint, not deck_version: builder-version
    # bumps mint new asset names but must not reshuffle seeded content.
    inputs_fingerprint = compute_deck_inputs_fingerprint(
        entries, heritage_pairs, paronym_pairs, synonym_verdicts, cloze_sources, SCHEMA_VERSION, antonym_pairs=antonym_pairs, homonym_pairs=homonym_pairs
    )
    rng_seed = int(hashlib.sha256(inputs_fingerprint.encode("utf-8")).hexdigest()[:16], 16)
    rng = random.Random(rng_seed)
    cloze_sources = cloze_sources or []
    priority_lemma_keys = _practice_priority_keys(
        cloze_sources,
        heritage_pairs,
        paronym_pairs,
        synonym_verdicts,
        antonym_pairs=antonym_pairs,
        homonym_pairs=homonym_pairs,
    )
    lexemes_by_entry, all_lexemes, by_plain_lemma, lexemes_by_id = _select_practice_lexemes(
        entries,
        verifier,
        config,
        priority_lemma_keys,
    )
    # Paronym emit resolves adjudicated pair slugs against the selected pool
    # (main's _select_practice_lexemes refactor supplies the pool; this map is
    # the branch's paronym-specific addition kept through the merge).
    slug_to_lex: dict[str, dict[str, Any]] = {}
    for lexeme in all_lexemes:
        s = _clean_text(lexeme.get("url_slug")) or _clean_text(lexeme.get("slug")) or lexeme.get("lemmaId")
        if s:
            slug_to_lex[s] = lexeme
    cloze_by_lemma_id: dict[str, list[dict[str, Any]]] = {}
    cloze_by_lemma: dict[str, list[dict[str, Any]]] = {}
    for row in cloze_sources:
        key = _cloze_join_key(row)
        if key is None:
            continue
        key_type, key_value = key
        target = cloze_by_lemma_id if key_type == "lemmaId" else cloze_by_lemma
        target.setdefault(key_value, []).append(row)
    cloze_by_level: dict[str, list[dict[str, Any]]] = {level: [] for level in CEFR_ORDER}
    cloze_ids_by_lemma: dict[str, list[str]] = {}
    mode_by_level: dict[str, dict[str, list[dict[str, Any]]]] = {
        level: {mode: [] for mode in DRILL_MODES}
        for level in CEFR_ORDER
    }
    for _entry, lexeme in lexemes_by_entry:
        # Unlevelled entries stay eligible for recognition.  Cloze and the
        # level-sensitive optional drills retain their existing gates.
        if not lexeme.get("cefr"):
            continue
        if config.cloze_enabled and is_surface_admitted(_entry, SURFACE_CLOZE):
            source_rows = [
                *cloze_by_lemma_id.get(lexeme["lemmaId"], []),
                *cloze_by_lemma.get(lexeme["lemmaPlain"], []),
            ]
        else:
            source_rows = []
        items = _build_cloze_items(lexeme, source_rows, allowlist, verifier, deck_version)
        for item in items:
            item["options"] = _make_options(item, lexeme, all_lexemes, rng)
            option_errors = validate_option_set(item)
            if option_errors:
                continue
            cloze_by_level[lexeme["cefr"]].append(item)
            cloze_ids_by_lemma.setdefault(lexeme["lemmaId"], []).append(item["clozeId"])
        stress = _stress_payload(_entry, end_dictionary_stress=end_dictionary_stress)
        if stress:
            mode_by_level[lexeme["cefr"]]["stress"].append(
                {
                    "stressId": f"{lexeme['lemmaId']}:stress",
                    "lemmaId": lexeme["lemmaId"],
                    "lemma": lexeme["lemma"],
                    **stress,
                }
            )

        classify_items = _build_classify_items(_entry, lexeme)
        mode_by_level[lexeme["cefr"]]["classify"].extend(classify_items)
        paradigm_items = _build_paradigm_items(lexeme)
        mode_by_level[lexeme["cefr"]]["paradigm"].extend(paradigm_items)

    synonym_items = _build_synonym_items(
        lexemes_by_entry,
        by_plain_lemma,
        all_lexemes,
        deck_version,
        approved_set - rejected_set,
        rejected_set,
        a2_exception_set,
        synonym_verdicts_loaded,
        encountered_pairs,
    )
    for item in synonym_items:
        level = str(item.pop("level"))
        item.pop("promptLevel", None)
