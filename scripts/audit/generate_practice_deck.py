def _gloss_clean(gloss: str) -> str:
    first_sense = re.split(r"[;,]", gloss, maxsplit=1)[0]
    return re.sub(r"\s+", " ", first_sense).strip()


def _meaning_label_word_count(label: str) -> int:
    return len(re.findall(r"[^\W_]+(?:[-'][^\W_]+)?", label, flags=re.UNICODE))


def _meaning_label_is_phrase(label: str) -> bool:
    clean = re.sub(r"\s+", " ", label).strip()
    return (
        not clean
        or "?" in clean
        or "(" in clean
        or ")" in clean
        or _meaning_label_word_count(clean) > MEANING_MC_MAX_WORDS
    )


def _is_english_learner_gloss(label: str) -> bool:
    clean = label.strip()
    if not clean:
        return False
    latin_letters = 0
    cyrillic_letters = 0
    for char in clean:
        if not unicodedata.category(char).startswith("L"):
            continue
        name = unicodedata.name(char, "")
        if "LATIN" in name:
            latin_letters += 1
        elif "CYRILLIC" in name:
            cyrillic_letters += 1
    return latin_letters > cyrillic_letters


def _romanize_ukrainian_plain(value: str) -> str:
    return "".join(_UKRAINIAN_ROMANIZATION.get(char, char) for char in value.casefold())


def _ascii_key(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", value.casefold())


def _is_transliteration_only_gloss(gloss_clean: str, lemma_plain: str) -> bool:
    romanized = _ascii_key(_romanize_ukrainian_plain(lemma_plain))
    return bool(romanized) and _ascii_key(gloss_clean) == romanized


def _meaning_mc_eligible(gloss_clean: str, lemma_plain: str, pos: str | None) -> bool:
    if not gloss_clean or len(gloss_clean) > MEANING_MC_MAX_CHARS:
        return False
    if not _is_english_learner_gloss(gloss_clean):
        return False
    if _meaning_label_is_phrase(gloss_clean):
        return False
    if re.search(r"[.!:]$", gloss_clean):
        return False
    if _headword(gloss_clean) in _FUNCTION_GLOSS_HEADWORDS:
        return False
    if pos and pos.casefold() in _FUNCTION_POS:
        return False
    return not _is_transliteration_only_gloss(gloss_clean, lemma_plain)


def _stable_lemma_id(entry: dict[str, Any]) -> str:
    slug = _clean_text(entry.get("url_slug")) or _clean_text(entry.get("slug"))
    if slug:
        return slug
    key = "\x1f".join(
        (
            _clean_text(entry.get("lemma")) or "",
            _clean_text(entry.get("gloss")) or "",
            _clean_text(entry.get("pos")) or "",
        )
    )
    return hashlib.sha1(key.encode("utf-8")).hexdigest()[:16]


def _normalize_cefr(value: Any) -> str | None:
    if isinstance(value, dict):
        value = value.get("level") or value.get("cefr")
    level_text = _clean_text(value)
    if not level_text:
        return None
    match = re.search(r"\b([ABC][12])\b", level_text.upper())
    if not match:
        return None
    level = match.group(1)
    return level if level in CEFR_RANK else None


def _cefr_level(entry: dict[str, Any]) -> str | None:
    enrichment = entry.get("enrichment")
    if isinstance(enrichment, dict):
        level = _normalize_cefr(enrichment.get("cefr"))
        if level:
            return level
    level = _normalize_cefr(entry.get("cefr"))
    if level:
        return level
    for usage in _course_usage(entry):
        level = _normalize_cefr(usage.get("track"))
        if level:
            return level
    return None


def _ipa(entry: dict[str, Any]) -> str | None:
    enrichment = entry.get("enrichment")
    if isinstance(enrichment, dict):
        for key in ("ipa", "pronunciation"):
            value = _clean_text(enrichment.get(key))
            if value:
                return value
    return _clean_text(entry.get("ipa"))


def _heritage(entry: dict[str, Any]) -> str | None:
    enrichment = entry.get("enrichment")
    if isinstance(enrichment, dict):
        heritage = enrichment.get("heritage")
        if isinstance(heritage, dict):
            value = _clean_text(heritage.get("classification")) or _clean_text(heritage.get("status"))
            if value:
                return value
        value = _clean_text(heritage)
        if value:
            return value
    status = entry.get("heritage_status")
    if isinstance(status, dict):
        for key in ("classification", "status", "label", "category"):
            value = _clean_text(status.get(key))
            if value:
                return value
    return None


def _severity(entry: dict[str, Any]) -> str | None:
    enrichment = entry.get("enrichment")
    if isinstance(enrichment, dict):
        severity = enrichment.get("severity")
        if isinstance(severity, dict):
            value = _clean_text(severity.get("level")) or _clean_text(severity.get("label"))
            if value:
                return value
        value = _clean_text(severity)
        if value:
            return value
    return _clean_text(entry.get("severity"))


def _paradigm(entry: dict[str, Any]) -> dict[str, Any]:
    enrichment = entry.get("enrichment")
    if not isinstance(enrichment, dict):
        return {"cases": {}}
    morphology = enrichment.get("morphology")
    if not isinstance(morphology, dict):
        return {"cases": {}}
    paradigm = morphology.get("paradigm")
    if not isinstance(paradigm, dict):
        return {"cases": {}}
    cases = paradigm.get("cases")
    if not isinstance(cases, dict):
        return {"cases": {}}
    clean_cases: dict[str, dict[str, str]] = {}
    for case_name, forms in cases.items():
        if not isinstance(case_name, str) or not isinstance(forms, dict):
            continue
        case_key = case_name.strip().casefold()
        clean_forms: dict[str, str] = {}
        for number in NUMBER_KEYS:
            value = _clean_text(forms.get(number))
            if value:
                clean_forms[number] = value
        if clean_forms:
            clean_cases[case_key] = clean_forms
    return {"cases": clean_cases}


def _vesum_pos(pos: str | None) -> str | None:
    if not pos:
        return None
    pos_key = pos.casefold()
    if pos_key in {"noun", "verb", "adj", "adjective", "adv", "adverb"}:
        return {"adjective": "adj", "adverb": "adv"}.get(pos_key, pos_key)
    return pos_key


def _course_usage(entry: dict[str, Any]) -> list[dict[str, Any]]:
    usage = entry.get("course_usage")
    if isinstance(usage, dict):
        return [usage]
    if not isinstance(usage, list):
        return []
    return [item for item in usage if isinstance(item, dict)]


def _course_key(entry: dict[str, Any]) -> tuple[str, str, str]:
    usage = _course_usage(entry)
    first = usage[0] if usage else {}
    return (
        str(first.get("track") or ""),
        str(first.get("slug") or first.get("module") or ""),
        _stable_lemma_id(entry),
    )


def _cloze_join_key(row: dict[str, Any]) -> tuple[str, str] | None:
    lemma_id = _clean_text(row.get("lemmaId"))
    if lemma_id:
        return ("lemmaId", lemma_id)
    lemma = _clean_text(row.get("lemma"))
    if lemma:
        return ("lemma", _plain(lemma))
    return None


def _all_paradigm_forms(paradigm: dict[str, Any]) -> list[str]:
    cases = paradigm.get("cases")
    if not isinstance(cases, dict):
        return []
    forms: list[str] = []
    seen: set[str] = set()
    for case_forms in cases.values():
        if not isinstance(case_forms, dict):
            continue
        for number in NUMBER_KEYS:
            value = _clean_text(case_forms.get(number))
            if value and value not in seen:
                seen.add(value)
                forms.append(value)
    return forms


def _match_cases(match: dict[str, Any]) -> set[str]:
    tokens = set(str(match.get("tags") or "").replace(":", " ").split())
    return {
        case_name
        for case_name, tag in CASE_VESUM_TAGS.items()
        if tag in tokens
    }


def _verify_paradigm(
    lemma_plain: str,
    pos: str | None,
    paradigm: dict[str, Any],
    verifier: VesumVerifier,
) -> bool:
    forms = _all_paradigm_forms(paradigm)
    if not forms:
        return False
    verified = verifier.verify_words(forms, _vesum_pos(pos))
    for form in forms:
        matches = verified.get(form, [])
        if not matches:
            return False
        if not any(_plain(str(match.get("lemma") or "")) == lemma_plain for match in matches):
            return False
    return True


def _verify_discriminative_form(
    lemma_plain: str,
    pos: str | None,
    form: str,
    case_name: str,
    verifier: VesumVerifier,
) -> bool:
    matches = _verified_surface_matches(form, verifier, _vesum_pos(pos))
    if len(matches) != 1:
        return False
    match = matches[0]
    if _plain(str(match.get("lemma") or "")) != lemma_plain:
        return False
    return _match_cases(match) == {case_name}


def _case_form(
    paradigm: dict[str, Any],
    case_name: str,
    number: str,
) -> str | None:
    cases = paradigm.get("cases")
    if not isinstance(cases, dict):
        return None
    forms = cases.get(case_name)
    if not isinstance(forms, dict):
        forms = cases.get(CASE_LABELS_UA.get(case_name, ""))
    if not isinstance(forms, dict):
        return None
    return _clean_text(forms.get(number))


def _case_rule_payload(rule_id: str, lemma: str, form: str) -> dict[str, str] | None:
    rule = CASE_RULES.get(rule_id)
    if not rule:
        return None
    feedback_template = str(rule["feedbackTemplate"])
    if _plain(lemma) == _plain(form):
        feedback_template = str(rule.get("sameFormFeedbackTemplate", feedback_template))
    return {
        "ruleId": rule_id,
        "case": str(rule["case"]),
        "caseLabel": CASE_LABELS_UA[str(rule["case"])],
        "trigger": str(rule["trigger"]),
        "triggerLabel": str(rule["triggerLabel"]),
        "feedback": feedback_template.format(lemma=lemma, form=form),
    }


def _candidate_sentence_level(candidate: dict[str, Any], fallback: str) -> str:
    return _normalize_cefr(candidate.get("cefr")) or _normalize_cefr(candidate.get("level")) or fallback


_INVENTORY_LANGUAGE_SOURCE_MARKERS = (
    "ukrmova",
    "ukrlit",
    "ulp",
    "ukrainska-mova",
    "ukrajinska-mova",
    "ukrainska-literatura",
    "ukrajinska-literatura",
)
# The source database currently labels most rows simply as ``textbook``; the
# locator carries the actual book family.  For A1/A2, a language-source row is
# preferred over these subject/academic families.  Subject-only fallback is
# intentionally conservative: <=120 characters, <=18 words, no formula-like
# punctuation, and no non-target word longer than 14 characters.  This is a
# short/common-vocabulary proxy, not a new coverage floor; harder rows remain
# residual inventory for later curation.
_INVENTORY_SUBJECT_SOURCE_MARKERS = (
    "algebra",
    "astronom",
    "biolog",
    "fizyk",
    "geograf",
    "geometr",
    "informat",
    "istori",
    "istorija",
    "khim",
    "matem",
    "mystetstvo",
    "pravoznav",
    "pryrod",
    "zakhyst",
    "zdorov",
)
_INVENTORY_SIMPLE_MAX_CHARS = 120
_INVENTORY_SIMPLE_MAX_WORDS = 18
_INVENTORY_SIMPLE_MAX_NON_TARGET_WORD_LENGTH = 14
_INVENTORY_WORD_RE = re.compile(r"[^\W_]+(?:[-'’ʼ][^\W_]+)*", re.UNICODE)


def _inventory_source_text(provenance: dict[str, Any]) -> str:
    return " ".join(
        _clean_text(provenance.get(key)) or ""
        for key in ("source", "label", "locator", "title")
    ).casefold()


def _inventory_source_kind(provenance: dict[str, Any]) -> str:
    source_text = _inventory_source_text(provenance)
    if any(marker in source_text for marker in _INVENTORY_LANGUAGE_SOURCE_MARKERS):
        return "language"
    if any(marker in source_text for marker in _INVENTORY_SUBJECT_SOURCE_MARKERS):
        return "subject"
    return "other"


def _inventory_sentence_is_short_common(sentence: str, target_form: str) -> bool:
    if len(sentence) > _INVENTORY_SIMPLE_MAX_CHARS:
        return False
    if re.search(r"[=<>±×÷/]", sentence):
        return False
    if sum(char.isdigit() for char in sentence) > 2:
        return False
    words = _INVENTORY_WORD_RE.findall(sentence)
    if not words or len(words) > _INVENTORY_SIMPLE_MAX_WORDS:
        return False
    target_plain = _plain(target_form)
    return all(
        len(_plain(_strip_stress(word))) <= _INVENTORY_SIMPLE_MAX_NON_TARGET_WORD_LENGTH
        for word in words
        if _plain(_strip_stress(word)) != target_plain
    )


def _prefer_inventory_sources(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Rank duplicate A1/A2 inventory rows by source quality per lemma."""
    grouped: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        key = _clean_text(row.get("lemmaId")) or _plain(str(row.get("lemma") or ""))
        if key:
            grouped.setdefault(key, []).append(row)

    selected: list[dict[str, Any]] = []
    for group in grouped.values():
        low_level = [
            row
            for row in group
            if _normalize_cefr(row.get("cefr")) in {"A1", "A2"}
        ]
        if not low_level:
            selected.extend(group)
            continue

        language_rows = [
            row
            for row in low_level
            if _inventory_source_kind(row["provenance"]) == "language"
        ]
        if language_rows:
            selected.extend(language_rows)
        else:
            non_subject_rows = [
                row
                for row in low_level
                if _inventory_source_kind(row["provenance"]) != "subject"
            ]
            if non_subject_rows:
                selected.extend(non_subject_rows)
            else:
                selected.extend(
                    row
                    for row in low_level
                    if _inventory_sentence_is_short_common(row["originalSentence"], row["form"])
                )
        selected.extend(row for row in group if row not in low_level)
    return selected


def _cloze_candidate_ok_for_level(candidate: dict[str, Any], word_level: str) -> bool:
    sentence_level = _candidate_sentence_level(candidate, word_level)
    return CEFR_RANK[sentence_level] <= CEFR_RANK[word_level]


def _inventory_form_details(
    lemma_plain: str,
    pos: str | None,
    form: str,
    verifier: VesumVerifier,
) -> tuple[str, str] | None:
    """Return the VESUM-supported slot for an inventory target.

    Sentence-inventory rows deliberately preserve an attested surface form but
    do not annotate morphology.  Dictionary-form rows are safe to use as
    identity clozes for any POS when VESUM confirms that the exact surface is
    the target lemma.  This matters for invariant lemmas and for nouns whose
    dictionary form has more than one VESUM analysis (for example, a
    nominative/accusative syncretism): rejecting those rows merely because the
    form has multiple analyses was the production thin-mode gate.

    Inflected rows still need one matching lemma/case/number analysis.  No
    grammatical label is inferred from sentence text, and unsupported cases
    are left for the caller to reject rather than guessed here.
    """
    pos_filter = _vesum_pos(pos)
    matches = _verified_surface_matches(form, verifier, pos_filter)
    # Manifest POS values include variants such as ``propn``, ``noun:f``, and
    # ``proper noun`` that are not VESUM ``pos`` values.  A filtered miss is
    # not proof that the source form is absent; ``_verified_surface_matches``
    # retries without the incompatible filter.
    matching = [
        match
        for match in matches
        if _plain(str(match.get("lemma") or "")) == lemma_plain
    ]
    if not matching:
        return None

    # The inventory target is an exact dictionary form.  Its sentence
    # context supplies the example, while the cloze asks for the attested
    # lemma; it is not a case exercise.  Do not force an arbitrary case when
    # VESUM has several analyses for the same surface.
    if _plain(form) == lemma_plain:
        return ("nominative", "singular")

    analyses: set[tuple[str, str]] = set()
    for match in matching:
        cases = _match_cases(match)
        tokens = set(str(match.get("tags") or "").replace(":", " ").split())
        if "p" in tokens:
            number = "plural"
        elif {"m", "f", "n"} & tokens:
            number = "singular"
        else:
            continue
        analyses.update((case_name, number) for case_name in cases)
    return next(iter(analyses)) if len(analyses) == 1 else None


def _eligible_decoys(
    answer: dict[str, Any],
    lexemes: list[dict[str, Any]],
    case_name: str,
    number: str,
) -> list[tuple[dict[str, Any], str]]:
    answer_head = _headword(answer["gloss"])
    candidates: list[tuple[dict[str, Any], str]] = []
    for lexeme in lexemes:
        if lexeme["lemmaId"] == answer["lemmaId"]:
            continue
        # Unknown CEFR is valid for recognition, but cannot participate in a
        # level-bounded cloze option set without inventing a placement.
        if not lexeme.get("cefr") or not answer.get("cefr"):
            continue
        if lexeme.get("pos") != answer.get("pos"):
            continue
        if CEFR_RANK[lexeme["cefr"]] > CEFR_RANK[answer["cefr"]]:
            continue
        if _headword(lexeme["gloss"]) == answer_head:
            continue
        decoy_form = _case_form(lexeme.get("paradigm", {}), case_name, number)
        if decoy_form and (
            case_name == "nominative" or _plain(decoy_form) != _plain(lexeme["lemma"])
        ):
            candidates.append((lexeme, decoy_form))
    return candidates


def _option_pos_bucket(pos: Any) -> str:
    """Map manifest POS variants into a safe option-comparison bucket."""
    value = _clean_text(pos)
    if not value:
        return ""
    normalized = value.casefold()
    # The hydrated manifest uses these standard shorthand/form labels for
    # lexical categories already represented by the broader buckets below.
    # Keep this list deliberately narrow: semantic labels such as
    # ``predicative`` and ``sequence word`` remain separate until their
    # exercise contract is reviewed.
    if normalized in {
        "imperative",
        "infinitive",
    }:
        return "verb"
    if normalized == "intj":
        return "interjection"
    if normalized == "numr":
        return "numeral"
    if "pronoun" in normalized or normalized in {"pron", "negative pronoun"}:
        return "pronoun"
    if "adverb" in normalized or normalized == "adv":
        return "adverb"
    if "noun" in normalized or normalized in {"propn", "proper noun"}:
        return "noun"
    if "verb" in normalized or normalized in {"passive", "participle", "gerund"}:
        return "verb"
    if "adject" in normalized or normalized in {"adj", "adjective"}:
        return "adjective"
    if "numeral" in normalized or normalized in {"num", "number"}:
        return "numeral"
    if normalized in {"preposition", "prep", "conjunction", "conj", "particle", "part"}:
        return "function"
    return normalized


def _eligible_dictionary_decoys(
    answer: dict[str, Any],
    lexemes: list[dict[str, Any]],
    answer_surface: Any | None = None,
) -> list[tuple[dict[str, Any], str]]:
    """Return same-POS dictionary forms for an inventory identity cloze.

    Inventory examples are not authored case prompts.  Requiring every
    distractor to have a verified paradigm would therefore throw away verbs,
    adverbs, proper nouns, and other perfectly valid practice lexemes even
    though the exercise only asks the learner to identify the source-backed
    lemma.
    """
    answer_bucket = _option_pos_bucket(answer.get("pos"))
    answer_head = _headword(answer["gloss"])
    answer_label = _plain(answer["lemma"])
    candidates: list[tuple[dict[str, Any], str]] = []
    seen_labels: set[str] = {answer_label}
    for lexeme in lexemes:
        if lexeme["lemmaId"] == answer["lemmaId"]:
            continue
        if not lexeme.get("cefr") or not answer.get("cefr"):
            continue
        if _option_pos_bucket(lexeme.get("pos")) != answer_bucket:
            continue
        if CEFR_RANK[lexeme["cefr"]] > CEFR_RANK[answer["cefr"]]:
            continue
        if _headword(lexeme["gloss"]) == answer_head:
            continue
        label = _clean_text(lexeme.get("lemma"))
        if not label or _meaning_label_is_phrase(label) or _plain(label) in seen_labels:
            continue
        seen_labels.add(_plain(label))
        candidates.append((lexeme, label))

    # A capitalized source lemma should not be the only capitalized option;
    # prefer decoys with the same initial-capital state when the pool allows.
    # Inventory rows preserve the source token's capitalization.  The lexeme
    # lemma is normalized lowercase, so using it here makes a sentence-initial
    # answer look uniquely capitalized even when a safe capitalized decoy is
    # available in the practice pool.
    answer_cap = _initial_capitalization(
        answer.get("lemma") if answer_surface is None else answer_surface
    )
    same_capitalization = [
        candidate
        for candidate in candidates
        if _initial_capitalization(candidate[1]) == answer_cap
    ]
    if len(same_capitalization) >= 3:
        return same_capitalization
    return candidates


def _pick_decoy(
    answer: dict[str, Any],
    lexemes: list[dict[str, Any]],
    rng: random.Random,
    case_name: str,
    number: str,
) -> tuple[dict[str, Any], str] | None:
    candidates = _eligible_decoys(answer, lexemes, case_name, number)
    if not candidates:
        return None
    return rng.choice(candidates)


def _option(
    cloze_id: str,
    suffix: str,
    label: str,
    lemma_id: str,
    kind: str,
    case_name: str,
    pos: str | None,
) -> dict[str, str]:
    return {
        "optionId": f"{cloze_id}:{suffix}",
        "label": label,
        "lemmaId": lemma_id,
        "kind": kind,
        "case": case_name,
        "pos": pos or "",
    }


def _option_strategy_for_level(level: str, rng: random.Random) -> str:
    no_pair_probability = NO_PAIR_PROBABILITY.get(level, NO_PAIR_PROBABILITY["B1"])
    return "no-pair" if rng.random() < no_pair_probability else "two-pair"


def _make_two_pair_options(
    cloze: dict[str, Any],
    answer: dict[str, Any],
    lexemes: list[dict[str, Any]],
    rng: random.Random,
) -> list[dict[str, str]]:
    decoy = _pick_decoy(answer, lexemes, rng, cloze["blankCase"], cloze["number"])
    if decoy is None:
        return []
    decoy_lexeme, decoy_form = decoy
    options = [
        _option(
            cloze["clozeId"],
            "answer",
            cloze["form"],
            answer["lemmaId"],
            "answer",
            cloze["blankCase"],
            answer.get("pos"),
        ),
        _option(
            cloze["clozeId"],
            "lemma",
            answer["lemma"],
            answer["lemmaId"],
            "same-root-lemma",
            "nominative",
            answer.get("pos"),
        ),
        _option(
            cloze["clozeId"],
            "decoy-lemma",
            decoy_lexeme["lemma"],
            decoy_lexeme["lemmaId"],
            "decoy-lemma",
            "nominative",
            decoy_lexeme.get("pos"),
        ),
        _option(
            cloze["clozeId"],
            "decoy-oblique",
            decoy_form,
            decoy_lexeme["lemmaId"],
            "decoy-oblique",
            cloze["blankCase"],
            decoy_lexeme.get("pos"),
        ),
    ]
    rng.shuffle(options)
    return options


def _make_no_pair_options(
    cloze: dict[str, Any],
    answer: dict[str, Any],
    lexemes: list[dict[str, Any]],
    rng: random.Random,
) -> list[dict[str, str]]:
    provenance = cloze.get("provenance")
    case_rule = cloze.get("caseRule")
    is_inventory_identity = (
        isinstance(provenance, dict)
        and provenance.get("status") == "sentence_inventory"
        and isinstance(case_rule, dict)
        and case_rule.get("ruleId") == "nominative_identification"
        and _plain(str(cloze.get("form") or "")) == _plain(str(cloze.get("lemma") or ""))
    )
    if is_inventory_identity:
        decoys = _eligible_dictionary_decoys(answer, lexemes, cloze.get("form"))
        # Dictionary lemmas are normalized lowercase, while an inventory
        # target may preserve sentence-initial capitalization.  Render the
        # option labels at the source surface's initial-capital state before
        # applying the existing length and answer-leak gates; otherwise a
        # safe same-POS decoy is discarded solely because its dictionary
        # spelling is lowercase.
        decoys = [
            (decoy_lexeme, _match_initial_capitalization(decoy_form, cloze.get("form")))
            for decoy_lexeme, decoy_form in decoys
        ]
        answer_length = len(str(cloze.get("form") or ""))
        decoys = [
            candidate
            for candidate in decoys
            if abs(len(candidate[1]) - answer_length) <= 3
        ]
        # Inventory identity cards used to take the alphabetically earliest POS
        # entries, which made chips look like an unrelated word list.  Keep the
        # same POS and a tight length band, then use the build's seeded RNG so
        # the selected decoys are varied but reproducible.
        rng.shuffle(decoys)
        answer_cap = _initial_capitalization(cloze.get("form"))
        selected_decoys: list[tuple[dict[str, Any], str]] = []
        # A greedy scan can choose a long decoy first and then strand the
        # card with fewer than three compatible labels.  Search the small
        # length windows that contain the answer instead; candidates were
        # shuffled above, so the first valid window remains seeded and varied.
        for lower_length in range(max(1, answer_length - 3), answer_length + 1):
            upper_length = lower_length + 3
            window = [
                candidate
                for candidate in decoys
                if lower_length <= len(candidate[1]) <= upper_length
            ]
            if answer_cap is not None:
                matching_cap = [
                    candidate
                    for candidate in window
                    if _initial_capitalization(candidate[1]) == answer_cap
                ]
                if not matching_cap:
                    continue
                first = matching_cap[0]
                selected_decoys = [first, *(candidate for candidate in window if candidate != first)]
            else:
                selected_decoys = window
            if len(selected_decoys) >= 3:
                selected_decoys = selected_decoys[:3]
                break
        if len(selected_decoys) < 3:
            return []
        rng.shuffle(selected_decoys)
        option_pos = _option_pos_bucket(answer.get("pos"))
        options = [
            _option(
                cloze["clozeId"],
                "answer",
                cloze["form"],
                answer["lemmaId"],
                "answer",
                "nominative",
                option_pos,
            )
        ]
        for index, (decoy_lexeme, decoy_form) in enumerate(selected_decoys, start=1):
            options.append(
                _option(
                    cloze["clozeId"],
                    f"decoy-{index}",
                    decoy_form,
                    decoy_lexeme["lemmaId"],
                    "decoy-lemma",
                    "nominative",
                    option_pos,
                )
            )
        rng.shuffle(options)
        return options

    decoys = _eligible_decoys(answer, lexemes, cloze["blankCase"], cloze["number"])
    rng.shuffle(decoys)
    if len(decoys) < 3:
        return []
    options = [
        _option(
            cloze["clozeId"],
            "answer",
            cloze["form"],
            answer["lemmaId"],
            "answer",
            cloze["blankCase"],
            answer.get("pos"),
        )
    ]
    for index, (decoy_lexeme, decoy_form) in enumerate(decoys[:3], start=1):
        label = decoy_form if index <= 2 else decoy_lexeme["lemma"]
        case_name = cloze["blankCase"] if index <= 2 else "nominative"
        kind = "decoy-oblique" if index <= 2 else "decoy-lemma"
        options.append(
            _option(
                cloze["clozeId"],
                f"decoy-{index}",
                label,
                decoy_lexeme["lemmaId"],
                kind,
                case_name,
                decoy_lexeme.get("pos"),
            )
        )
    rng.shuffle(options)
    return options


def _make_options(
    cloze: dict[str, Any],
    answer: dict[str, Any],
    lexemes: list[dict[str, Any]],
    rng: random.Random,
) -> list[dict[str, str]]:
    # A nominative-identification cloze has the lemma itself as its answer.
    # A two-pair set would therefore repeat that label as the same-root lemma
    # distractor.  Use four distinct roots instead of constructing an invalid
    # option set that validation must discard.
    rule_id = cloze.get("caseRule", {}).get("ruleId") if isinstance(cloze.get("caseRule"), dict) else None
    force_no_pair = rule_id == "nominative_identification"
    strategy = "no-pair" if force_no_pair else _option_strategy_for_level(answer["cefr"], rng)
    options = (
        _make_no_pair_options(cloze, answer, lexemes, rng)
        if strategy == "no-pair"
        else _make_two_pair_options(cloze, answer, lexemes, rng)
    )
    if not options and not force_no_pair:
        strategy = "two-pair"
        options = _make_two_pair_options(cloze, answer, lexemes, rng)
    for option in options:
        option["strategy"] = strategy
    return options


def _initial_capitalization(value: Any) -> bool | None:
    text = _clean_text(value)
    if not text:
        return None
    for char in text:
        if char.isalpha():
            return char.upper() == char and char.lower() != char
    return None


def _match_initial_capitalization(value: str, exemplar: Any) -> str:
    """Render a dictionary option with the source surface's initial case."""
    desired = _initial_capitalization(exemplar)
    if desired is None:
        return value
    chars = list(value)
    for index, char in enumerate(chars):
        if char.isalpha():
            chars[index] = char.upper() if desired else char.lower()
            return "".join(chars)
    return value


def validate_option_set(cloze: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    options = cloze.get("options")
    if not isinstance(options, list) or len(options) < 4:
        return ["option set must contain at least four options"]
    labels = [str(option.get("label") or "") for option in options if isinstance(option, dict)]
    if any(_meaning_label_is_phrase(label) for label in labels):
        errors.append("option labels must not be phrase glosses")
    normalized = [_plain(label) for label in labels]
    if len(set(normalized)) != len(normalized):
        errors.append("option labels must be unique after normalization")
    answer_count = sum(1 for label in normalized if label == _plain(str(cloze.get("form") or "")))
    if answer_count != 1:
        errors.append("answer form must be present exactly once")
    accepted = [cloze.get("form")]
    accepted_alt = cloze.get("acceptedAlt")
    if isinstance(accepted_alt, list):
        accepted.extend(accepted_alt)
    accepted_normalized = {_plain(str(value)) for value in accepted if _clean_text(value)}
    distractors = [
        option
        for option in options
        if isinstance(option, dict) and option.get("kind") != "answer"
    ]
    if any(_plain(str(option.get("label") or "")) in accepted_normalized for option in distractors):
        errors.append("accepted alternate must not equal a distractor")
    answer_labels = [
        str(option.get("label") or "")
        for option in options
        if isinstance(option, dict) and option.get("kind") == "answer"
    ]
    answer_cap = _initial_capitalization(answer_labels[0] if answer_labels else cloze.get("form"))
    distractor_caps = {
        cap
        for cap in (
            _initial_capitalization(option.get("label"))
            for option in distractors
            if isinstance(option, dict)
        )
        if cap is not None
    }
    if answer_cap is not None and len(distractor_caps) == 1 and answer_cap not in distractor_caps:
        errors.append("answer capitalization must not uniquely reveal the answer")
    oblique_count = sum(
        1
        for option in options
        if isinstance(option, dict)
        and option.get("case") not in {None, "", "nominative"}
    )
    oblique_distractor_count = sum(
        1
        for option in options
        if isinstance(option, dict)
        and option.get("kind") != "answer"
        and option.get("case") not in {None, "", "nominative"}
    )
    blank_case = _clean_text(cloze.get("blankCase")) or "nominative"
    if blank_case != "nominative" and (oblique_count < 2 or oblique_distractor_count < 1):
        errors.append("option set must contain at least two oblique-looking forms")
    pos_values = {
        str(option.get("pos") or "")
        for option in options
        if isinstance(option, dict) and option.get("pos")
    }
    if len(pos_values) > 1:
        errors.append("option set must stay within one POS bucket")
    root_counts: dict[str, int] = {}
    for option in options:
        if not isinstance(option, dict):
            continue
        lemma_id = str(option.get("lemmaId") or "")
        root_counts[lemma_id] = root_counts.get(lemma_id, 0) + 1
    pair_count = sum(1 for count in root_counts.values() if count >= 2)
    if pair_count == 1:
        errors.append("option set must not contain exactly one same-root pair")
    if pair_count > 1 and any(count > 2 for count in root_counts.values()):
        errors.append("option set must not contain answer-equivalent root leaks")
    lengths = [len(label) for label in labels]
    if lengths and max(lengths) - min(lengths) > 12:
        errors.append("option label lengths exceed bounded distribution")
    return errors


def validate_option_sets(cloze_items: list[dict[str, Any]]) -> list[str]:
    positions: list[int] = []
    for item in cloze_items:
        options = item.get("options")
        if not isinstance(options, list):
            continue
        normalized_answer = _plain(str(item.get("form") or ""))
        for index, option in enumerate(options):
            if isinstance(option, dict) and _plain(str(option.get("label") or "")) == normalized_answer:
                positions.append(index)
                break
    # Variance is only statistically meaningful with enough items: on tiny
    # decks (fixtures, thin levels) 2-3 seeded placements can legitimately
    # collide, and failing here wipes the LEVEL'S ENTIRE CLOZE with a WARN
    # (#4722: a seed change flipped fixture tests this way). Require variance
    # only from 4 items up, where a collision is a real anti-gaming signal.
    if len(positions) >= 4 and len(set(positions)) == 1:
        return ["answer position must vary across the deck"]
    return []


def _build_lexeme(entry: dict[str, Any], verifier: VesumVerifier) -> dict[str, Any] | None:
    lemma = _clean_text(entry.get("lemma"))
    gloss = _clean_text(entry.get("gloss"))
    level = _cefr_level(entry)
    if not lemma or not gloss:
        return None
    lemma_plain = _plain(lemma)
    pos = _clean_text(entry.get("pos"))
    gloss_clean = _gloss_clean(gloss)
    meaning_mc_eligible = _meaning_mc_eligible(gloss_clean, lemma_plain, pos)
    # Recognition (matching/choice/flashcard) needs only lemma+gloss, so an admitted
    # word stays in the deck even when CEFR is unknown. Attach the paradigm for flashcard declensions ONLY when every form
    # VESUM-verifies; otherwise blank it so the UI never displays an unverified declension.
    paradigm = _paradigm(entry)
    if not _verify_paradigm(lemma_plain, pos, paradigm, verifier):
        paradigm = {"cases": {}}
    lexeme: dict[str, Any] = {
        "lemmaId": _stable_lemma_id(entry),
        "lemma": lemma,
        "lemmaPlain": lemma_plain,
        "ipa": _ipa(entry),
        "gloss": gloss,
        "glossClean": gloss_clean,
        "meaningMcEligible": meaning_mc_eligible,
        "pos": pos,
        "cefr": level,
        "heritage": _heritage(entry),
        "severity": _severity(entry),
        "paradigm": paradigm,
        "semanticBucket": _clean_text(entry.get("semantic_bucket")),
    }
    example = entry.get("practice_example")
    if isinstance(example, dict):
        text = _clean_text(example.get("text"))
        provenance = example.get("provenance")
        if text and isinstance(provenance, dict):
            lexeme["example"] = text
            lexeme["exampleProvenance"] = provenance
    return lexeme


def _candidate_rule_id(candidate: dict[str, Any], case_name: str) -> str | None:
    raw_rule = (
        candidate.get("caseRuleId")
        or candidate.get("ruleId")
        or candidate.get("caseRule")
    )
    if isinstance(raw_rule, dict):
        raw_rule = raw_rule.get("ruleId") or raw_rule.get("id")
    rule_id = _clean_text(raw_rule)
    if rule_id:
        if rule_id in CASE_RULES and CASE_RULES[rule_id]["case"] == case_name:
            return rule_id
        return None
    # ``nominative_identification`` is reserved for the explicit dictionary-
    # form identity branch.  A non-identity inventory form must not inherit
    # its "dictionary form" feedback merely because nominative is the first
    # available rule for that case.
    if case_name == "nominative":
        return None
    for fallback_id, rule in CASE_RULES.items():
        if rule["case"] == case_name:
            return fallback_id
    return None


def _infer_number(paradigm: dict[str, Any], case_name: str, form: str | None) -> str | None:
    if form:
        normalized = _plain(form)
        for number in NUMBER_KEYS:
            candidate = _case_form(paradigm, case_name, number)
            if candidate and _plain(candidate) == normalized:
                return number
    return "singular"


def _accepted_alts(candidate: dict[str, Any]) -> list[str]:
    raw = candidate.get("acceptedAlt")
    if raw is None:
        raw = candidate.get("accepted_alt")
    if isinstance(raw, list):
        return [value for value in (_clean_text(item) for item in raw) if value]
    text = _clean_text(raw)
    if not text:
        return []
    return [value for value in (part.strip() for part in text.split("|")) if value]


def _build_cloze_items(
    lexeme: dict[str, Any],
    cloze_rows: list[dict[str, Any]],
    allowlist: ReviewedSourceAllowlist,
    verifier: VesumVerifier,
    deck_version: str,
) -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    for index, candidate in enumerate(cloze_rows):
        provenance = candidate.get("provenance")
        if not allowlist.allows(provenance):
            continue
        if not _cloze_candidate_ok_for_level(candidate, lexeme["cefr"]):
            continue
        curated_form = _clean_text(candidate.get("form"))
        inventory_candidate = candidate.get("sourceType") == "sentence_inventory"
        if (
            inventory_candidate
            and _is_function_identity_pos(lexeme.get("pos"))
            and candidate.get("curated") is not True
        ):
            continue
        if inventory_candidate:
            # A sentence inventory row represents an attested source sentence;
            # without its explicit target token, it cannot be safely blanked.
            if not curated_form:
                continue
            inventory_details = _inventory_form_details(
                lexeme["lemmaPlain"],
                lexeme.get("pos"),
                curated_form,
                verifier,
            )
            if inventory_details is None:
                continue
            case_name, number = inventory_details
            if _plain(curated_form) == lexeme["lemmaPlain"]:
                # The inventory is a source-backed example asset.  An exact
                # dictionary form is an identity cloze, not an inferred case
                # exercise; this remains valid for verbs, adverbs, proper
                # nouns, and syncretic noun forms.
                rule_id = "nominative_identification"
            else:
                # Future inventory rows may carry an inflected target form.
                # Use it only when VESUM gives one case/number and the
                # existing authored rule table can describe that case.
                rule_id = _candidate_rule_id(candidate, case_name)
                if not rule_id:
                    continue
        else:
            case_name = _clean_text(candidate.get("blankCase"))
            if not case_name or case_name not in CASE_LABELS_UA:
                continue
            rule_id = _candidate_rule_id(candidate, case_name)
            if not rule_id:
                continue
            number = _clean_text(candidate.get("number")) or _infer_number(
                lexeme["paradigm"],
                case_name,
                curated_form,
            )
        if number not in NUMBER_KEYS:
            continue
        if rule_id == "nominative_identification" and (
            case_name != "nominative" or number != "singular"
        ):
            continue
        form = curated_form or _case_form(lexeme["paradigm"], case_name, number)
        if not form or (not inventory_candidate and _plain(form) == lexeme["lemmaPlain"]):
            continue
        inventory_identity = inventory_candidate and _plain(form) == lexeme["lemmaPlain"]
        if not inventory_identity and not _verify_discriminative_form(
            lexeme["lemmaPlain"], lexeme.get("pos"), form, case_name, verifier
        ):
            continue
        sentence = _clean_text(candidate.get("sentence"))
        cloze_en = _clean_text(candidate.get("clozeEn")) or _clean_text(candidate.get("translation"))
        if not sentence or "___" not in sentence or (not inventory_candidate and not cloze_en):
            continue
        frame_key = "\x1f".join((deck_version, lexeme["lemmaId"], sentence, rule_id))
        sentence_frame_id = "sf_" + hashlib.sha1(frame_key.encode("utf-8")).hexdigest()[:12]
        cloze_id = _clean_text(candidate.get("clozeId")) or f"{lexeme['lemmaId']}:cloze:{index + 1}"
        case_rule = _case_rule_payload(rule_id, lexeme["lemma"], form)
        if not case_rule:
            continue
        assert isinstance(provenance, dict)
        attribution = _build_tatoeba_attribution(provenance)
        if _is_tatoeba_provenance(provenance) and attribution is None:
            continue
        if inventory_candidate:
            inventory_attribution = _build_source_attribution(provenance)
            if _license_requires_displayable_attribution(provenance) and inventory_attribution is None:
                continue
            if inventory_attribution is not None:
                attribution = inventory_attribution
        item = {
            "clozeId": cloze_id,
            "lemmaId": lexeme["lemmaId"],
            "sentenceFrameId": sentence_frame_id,
            "sentence": sentence,
            "blankCase": case_name,
            "form": form,
            "number": number,
            "lemma": lexeme["lemma"],
            "caseRule": case_rule,
            "cefr": _clean_text(candidate.get("cefr")) or lexeme["cefr"],
            "acceptedAlt": _accepted_alts(candidate),
            "provenance": _build_cloze_provenance(provenance),
        }
        if cloze_en:
            item["clozeEn"] = cloze_en
        if attribution is not None:
            item["attribution"] = attribution
        items.append(item)
    return items


def _stress_payload(
    entry: dict[str, Any],
    *,
    end_dictionary_stress: dict[str, dict[str, str]] | None = None,
) -> dict[str, Any] | None:
    stress = entry.get("enrichment", {}).get("stress") if isinstance(entry.get("enrichment"), dict) else None
    if isinstance(stress, dict):
        form = _clean_text(stress.get("form"))
        source = _clean_text(stress.get("source"))
    else:
        form = _clean_text(stress)
        source = None
    # End-dictionary overlay fills only when atlas enrichment has no stressed form.
    # Combining-acute forms only — lemma-only stress lists do not invent stress.
    if not form and end_dictionary_stress:
        lemma = _clean_text(entry.get("lemma")) or ""
        overlay = end_dictionary_stress.get(_plain(lemma))
        if isinstance(overlay, dict):
            form = _clean_text(overlay.get("form"))
            source = _clean_text(overlay.get("source")) or source
    if not form:
        return None
    unstressed, stress_index = _stress_position(form)
    nuclei = _vowel_nuclei(unstressed)
    if stress_index is None or len(nuclei) < 2:
        return None
    if sum(1 for nucleus in nuclei if nucleus["index"] == stress_index) != 1:
        return None
    lemma = _clean_text(entry.get("lemma")) or ""
    if lemma and _plain(unstressed) != _plain(lemma):
        return None
    return {
        "stressed": form,
        "unstressed": unstressed,
        "stressIndex": stress_index,
        "nuclei": nuclei,
        "source": source or "ukrainian-word-stress",
    }


def _morphology(entry: dict[str, Any]) -> dict[str, Any] | None:
    enrichment = entry.get("enrichment")
    if not isinstance(enrichment, dict):
        return None
    morphology = enrichment.get("morphology")
    return morphology if isinstance(morphology, dict) else None


def _morph_labels(morphology: dict[str, Any]) -> list[str]:
    forms = morphology.get("forms")
    if not isinstance(forms, list):
        return []
    labels: list[str] = []
    for row in forms:
        if not isinstance(row, dict):
            continue
        label = _clean_text(row.get("label"))
        if label is not None:
            labels.append(label)
    return labels


