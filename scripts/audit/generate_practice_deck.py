def _build_paronym_items(
    pair: dict[str, Any],
    lex_a: dict[str, Any],
    lex_b: dict[str, Any],
    deck_version: str,
    *,
    verifier: VesumVerifier | None = None,
    public_options: bool = True,
) -> list[dict[str, Any]]:
    if not _normalize_cefr(lex_a.get("cefr")) or not _normalize_cefr(lex_b.get("cefr")):
        return []
    frames = _valid_paronym_frames(pair)
    if not frames:
        return []
    distinction = _clean_text(pair.get("distinction_gloss_uk")) or ""
    citations = _clean_text_list(pair.get("citations"))
    if not citations:
        return []
    items: list[dict[str, Any]] = []
    lex_by_lemma = {
        _clean_text(lex_a.get("lemma")): lex_a,
        _clean_text(lex_b.get("lemma")): lex_b,
    }
    slugs = (_clean_text(pair.get("slugA")), _clean_text(pair.get("slugB")))
    for index, frame in enumerate(frames, start=1):
        sentence = _clean_text(frame.get("sentence_with_slot"))
        answer_form = _clean_text(frame.get("answer_form"))
        confusable_form = _clean_text(frame.get("confusable_form"))
        origin = _clean_text(frame.get("origin"))
        if not all((sentence, answer_form, confusable_form, origin)):
            print(
                f"WARN: paronym_pair {slugs} frame {index} dropped: missing required field",
                file=sys.stderr,
            )
            continue
        # Resolve target lexeme by lemma of the answer form (via VESUM)
        target_lex: dict[str, Any] | None = None
        ans_matches: list[dict[str, Any]] = []
        if verifier:
            try:
                vres = verifier.verify_words([answer_form])
                ans_matches = vres.get(answer_form, []) or []
            except Exception:
                ans_matches = []
        if ans_matches:
            ans_lemma = _clean_text(ans_matches[0].get("lemma"))
            if ans_lemma and ans_lemma in lex_by_lemma:
                target_lex = lex_by_lemma[ans_lemma]
        if target_lex is None:
            # Fallback: try direct lemma match on stored lemmas (for fixture paths)
            for cand in (lex_a, lex_b):
                if _clean_text(cand.get("lemma")) and answer_form.lower().startswith(_clean_text(cand.get("lemma")).lower()[:3]):
                    target_lex = cand
                    break
        if target_lex is None or not target_lex.get("cefr"):
            print(
                f"WARN: paronym_pair {slugs} frame {index} dropped: could not resolve lemma for answer_form {answer_form!r}",
                file=sys.stderr,
            )
            continue
        key = "\x1f".join((deck_version, target_lex["lemmaId"], sentence, answer_form, confusable_form))
        paronym_id = "par_" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]
        options = [
            {"label": answer_form, "kind": "answer", "lemmaId": target_lex["lemmaId"]},
            {"label": confusable_form, "kind": "confusable"},
        ]
        item: dict[str, Any] = {
            "paronymId": paronym_id,
            "lemmaId": target_lex["lemmaId"],
            "srsKey": f"{target_lex['lemmaId']}::paronym",
            "lemma": target_lex.get("lemma"),
            "prompt": sentence,
            "answer": answer_form,
            "confusable": confusable_form,
            "frameIndex": index,
            "cefr": target_lex["cefr"],
            "options": options,
            "distinction_gloss_uk": distinction,
            "citations": citations,
            "origin": origin,
        }
        if prompt_en := _curated_prompt_en(frame):
            item["promptEn"] = prompt_en
        # simple shuffle using deck seed if possible; fall back to list as-is
        # (real shuffle happens via rng in caller path for determinism; here keep order stable)
        items.append(_strip_paronym_option_metadata(item) if public_options else item)
    return items


def validate_classify_item(item: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    sets = item.get("sets")
    if not isinstance(sets, list) or not sets:
        return ["classify item must contain at least one category set"]
    for category_set in sets:
        if not isinstance(category_set, dict):
            errors.append("classify category set must be an object")
            continue
        set_id = category_set.get("setId")
        answer = category_set.get("answer")
        options = category_set.get("options")
        if set_id not in CLASSIFY_LABELS:
            errors.append("classify category set is not closed")
            continue
        closed_values = set(CLASSIFY_LABELS[str(set_id)])
        option_values = {
            option.get("value")
            for option in (options if isinstance(options, list) else [])
            if isinstance(option, dict)
        }
        if option_values != closed_values:
            errors.append(f"classify {set_id} options must equal the closed category set")
        if answer not in closed_values:
            errors.append(f"classify {set_id} answer must be in the closed category set")
    return errors


def validate_classify_session_cap(items: list[dict[str, Any]], cap: float = 0.60) -> list[str]:
    counts: Counter[str] = Counter()
    for item in items:
        sets = item.get("sets")
        if not isinstance(sets, list):
            continue
        for category_set in sets:
            if isinstance(category_set, dict):
                key = f"{category_set.get('setId')}:{category_set.get('answer')}"
                counts[key] += 1
    total = sum(counts.values())
    if total < 4:
        return []
    worst = max(counts.values()) / total
    if worst > cap:
        return [f"classify session category cap exceeded: {worst:.2%} > {cap:.0%}"]
    return []


def validate_synonym_item(item: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    options = item.get("options")
    if not isinstance(options, list) or len(options) < 4:
        return ["synonym option set must contain at least four options"]
    labels = [str(option.get("label") or "") for option in options if isinstance(option, dict)]
    normalized = [_plain(label) for label in labels]
    if len(set(normalized)) != len(normalized):
        errors.append("synonym options must be unique after normalization")
    answer = _plain(str(item.get("answer") or ""))
    if normalized.count(answer) != 1:
        errors.append("synonym answer must be present exactly once")
    lengths = [len(label) for label in labels]
    if lengths and max(lengths) - min(lengths) > 12:
        errors.append("synonym option label lengths exceed bounded distribution")
    prompt = _plain(str(item.get("prompt") or ""))
    for label in normalized:
        if label and label != answer and (label in {answer, prompt} or answer in label or label in answer):
            errors.append("synonym distractor must not be a near-duplicate of prompt or answer")
            break
    return errors


def validate_heritage_item(item: dict[str, Any], *, internal_options: bool = False) -> list[str]:
    errors: list[str] = []
    for field in ("heritageId", "lemmaId", "srsKey", "prompt", "answer", "calque", "rationale"):
        if not _clean_text(item.get(field)):
            errors.append(f"heritage item missing {field}")
    prompt = _clean_text(item.get("prompt"))
    if prompt and prompt.count("___") != 1:
        errors.append("heritage prompt must contain exactly one ___ slot")
    citations = item.get("citations")
    if not _clean_text_list(citations):
        errors.append("heritage citations must be a nonempty list")
    options = item.get("options")
    if not isinstance(options, list) or len(options) != 4:
        return [*errors, "heritage option set must contain exactly four options"]
    option_objects = [option for option in options if isinstance(option, dict)]
    if len(option_objects) != len(options):
        errors.append("heritage options must be objects")
    labels = [str(option.get("label") or "") for option in option_objects]
    if any(HERITAGE_OPTION_LEAK_PATTERN.search(label) for label in labels):
        errors.append("heritage options must not visually mark the calque pre-answer")
    if not internal_options:
        for option in option_objects:
            leaked_keys = sorted(set(option) - HERITAGE_PUBLIC_OPTION_KEYS)
            if leaked_keys:
                errors.append(
                    "heritage options must expose only label; "
                    f"remove leaked option keys {leaked_keys}"
                )
                break
    normalized = [_plain(label) for label in labels]
    if len(set(normalized)) != len(normalized):
        errors.append("heritage options must be unique after normalization")
    answer = _plain(str(item.get("answer") or ""))
    calque = _plain(str(item.get("calque") or ""))
    if normalized.count(answer) != 1:
        errors.append("heritage answer must be present exactly once")
    if normalized.count(calque) != 1:
        errors.append("heritage calque must be present exactly once")
    lengths = [len(label) for label in labels]
    if lengths and max(lengths) - min(lengths) > 12:
        errors.append("heritage option label lengths exceed bounded distribution")
    if internal_options:
        kinds = Counter(str(option.get("kind") or "") for option in option_objects)
        if kinds.get("answer") != 1:
            errors.append("heritage options must contain exactly one answer")
        if kinds.get("calque") != 1:
            errors.append("heritage options must contain exactly one calque")
        if kinds.get("distractor") != 2:
            errors.append("heritage options must contain exactly two distractors")
        pos_values = {
            str(option.get("pos") or "")
            for option in option_objects
            if option.get("kind") != "calque" and option.get("pos")
        }
        if len(pos_values) > 1:
            errors.append("heritage distractors must stay within one POS bucket")
        for option in option_objects:
            if option.get("kind") not in {"answer", "calque", "distractor"}:
                errors.append("heritage option kind is not recognized")
                break
    return errors


