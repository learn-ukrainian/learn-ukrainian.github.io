def build_all_lexical():
    out_cases = []
    for num, term, copy, prop, is_e, auth, orig1, corr1, expl in SPECS:
        cid = f"decol_lex_{num:03d}"
        split = "eval" if is_e else "train"
        c1, c2 = build_context_pair("calque_lexical", num, term, copy, prop, is_e, auth, orig1, corr1, expl)
        out_cases.append((cid, term, copy, prop, "calque_lexical", "correction", True, auth, split, c1, c2))
    return out_cases


def main():
    cases = build_all_lexical()
    print(f"Total lexical cases generated: {len(cases)}")
    with OUT_FILE.open("w", encoding="utf-8") as f:
        f.write(
            '"""Lexical calques cases definitions (#8340).\n\n60 phenomena (48 train, 12 eval -> 120 records).\n"""\n\n'
        )
        f.write("def get_lexical_cases(make_case):\n")
        f.write("    return [\n")
        for c in cases:
            cid, term, copy, prop, cat, disp, is_err, auth, split, c1, c2 = c
            f.write(
                f"        make_case({cid!r}, {term!r}, {copy!r}, {prop!r}, {cat!r}, {disp!r}, {is_err!r}, {auth!r}, {split!r},\n"
            )
            f.write(f"                  {c1!r},\n")
            f.write(f"                  {c2!r}),\n")
        f.write("    ]\n")
    print(f"Wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
