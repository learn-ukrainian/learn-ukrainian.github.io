def build_all_protective():
    out_cases = []
    for num, term, prop, is_e, auth, sentence, expl in SPECS:
        cid = f"decol_prot_{num:03d}"
        split = "eval" if is_e else "train"
        c1, c2 = build_protective_context_pair(num, term, prop, is_e, auth, sentence, expl)
        out_cases.append((cid, term, "", prop, "protective_authentic", "protection", False, auth, split, c1, c2))
    return out_cases


def main():
    cases = build_all_protective()
    print(f"Total protective cases generated: {len(cases)}")
    with OUT_FILE.open("w", encoding="utf-8") as f:
        f.write(
            '"""Protective authentic cases definitions (#8340).\n\n75 phenomena (60 train, 15 eval -> 150 records).\n"""\n\n'
        )
        f.write("def get_protective_cases(make_case):\n")
        f.write("    return [\n")
        for c in cases:
            cid, term, copy, prop, cat, disp, is_err, auth, split, c1, c2 = c
            f.write(
                f"        make_case({cid!r}, {term!r}, {copy!r}, {prop!r}, {cat!r}, {disp!r}, {is_err!r}, {auth!r}, {split!r},\n"
            )
            f.write(f"                  {c1!r},\n")
            f.write(f"                  {c2!r}),\n")
        f.write("    ]\n")
    print(f"Wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
