def clean_span_punct(s: str) -> str:
    """Normalize whitespace around punctuation in error and replacement spans."""
    if not s:
        return ""
    # Close spaces before standard punctuation: , . ! ? : ; % ) ] } » ” …
    s = re.sub(r"\s+([,.\!?:;%\]\}\)»”…])", r"\1", s)
    # Close spaces after opening punctuation: ( [ { « “
    s = re.sub(r"([(\[\{«“])\s+", r"\1", s)
    return s.strip()


