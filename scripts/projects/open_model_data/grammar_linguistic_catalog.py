_VESUM_CONN: sqlite3.Connection | None = None


def _get_vesum_connection() -> sqlite3.Connection | None:
    global _VESUM_CONN
    if _VESUM_CONN is None:
        try:
            from scripts.rag.config import VESUM_DB_PATH

            db_path = VESUM_DB_PATH
        except ImportError:
            db_path = Path(__file__).resolve().parents[3] / "data" / "vesum.db"
        if db_path.is_file():
            try:
                _VESUM_CONN = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
            except Exception:
                _VESUM_CONN = None
    return _VESUM_CONN


@functools.lru_cache(maxsize=100000)
def is_vocative_form(word: str) -> bool:
    """Check if word is a noun with a singular vocative form tag (v_kly) in VESUM (excluding pronouns and plurals)."""
    clean_word = word.strip().strip("«»\"'.,!?-–—;:()").lower()
    if not clean_word:
        return False
    conn = _get_vesum_connection()
    if conn is None:
        return False
    try:
        cur = conn.cursor()
        res = cur.execute(
            "SELECT pos, tags FROM forms_all WHERE word_form IN (?, ?, ?)",
            (clean_word, clean_word.capitalize(), clean_word.upper()),
        ).fetchall()
        return any(
            pos == "noun" and "v_kly" in tags and ":p:" not in tags and "p:" not in tags and "pron" not in tags
            for pos, tags in res
        )
    except Exception:
        return False


@functools.lru_cache(maxsize=100000)
def is_finite_active_verb(word: str) -> bool:
    """Check if word is a finite active verb in VESUM (not an infinitive, adjective, participle, or passive)."""
    clean_word = word.strip().strip("«»\"'.,!?-–—;:()").lower()
    if not clean_word:
        return False
    conn = _get_vesum_connection()
    if conn is None:
        return False
    try:
        cur = conn.cursor()
        res = cur.execute(
            "SELECT pos, tags FROM forms_all WHERE word_form IN (?, ?, ?)",
            (clean_word, clean_word.capitalize(), clean_word.upper()),
        ).fetchall()
        has_active_finite = any(
            pos == "verb" and "adjp" not in tags and "pasv" not in tags and "inf" not in tags for pos, tags in res
        )
        has_non_finite_or_passive = any("pasv" in tags or "adjp" in tags or "inf" in tags for pos, tags in res)
        return has_active_finite and not has_non_finite_or_passive
    except Exception:
        return False


