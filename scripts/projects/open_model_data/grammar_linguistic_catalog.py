def resolve_specific_linguistic_citation(
    primary_tag: str,
    error_span: str,
    replacement_span: str,
    orig_text: str,
    corr_text: str,
) -> tuple[str, str, str] | None:
    """Resolve an exact, facet-aware citation for the specific edit.

    Returns (authority, description, rule_template) or None if cannot resolve.
    If None is returned, the caller drops the explanation and converts the row
    to a silent rewrite per Spec §2.3.
    """
    err = (error_span or "").strip()
    corr = (replacement_span or "").strip()
    if not err or not corr:
        return None
    if err == corr:
        return None

    err_lower = err.lower()
    corr_lower = corr.lower()

    # 1. Specific lexical calque patterns (Antonenko-Davydovych, Karavanskyi, Ponomariv)
    if "наступним чином" in err_lower:
        return (
            "Борис Антоненко-Давидович «Як ми говоримо» / Олександр Пономарів",
            "калькований зворот «наступним чином» замінено на питомий «таким чином»",
            "Борис Антоненко-Давидович зазначає, що вислів «наступним чином» є калькою російського «следующим образом»; нормативним українським відповідником є «таким чином»."
        )
    if "приймати участь" in err_lower or "прийняти участь" in err_lower:
        return (
            "Борис Антоненко-Давидович «Як ми говоримо»",
            "кальковане сполучення слів виправлено на нормативне «брати участь»",
            "Борис Антоненко-Давидович наголошує, що в українській мові усталеною є сполука «брати участь», тоді як «приймати участь» — калька з російської."
        )
    if err_lower in {"у якості", "в якості"}:
        return (
            "Борис Антоненко-Давидович «Як ми говоримо»",
            f"кальковану сполуку «{err}» замінено на питомий прийменник «як»",
            f"Борис Антоненко-Давидович розглядає надмір конструкції «{err}» замість природного українського «як» і радить уникати цього канцеляризму.",
        )
    if "в залежності" in err_lower or "у залежності" in err_lower:
        return (
            "Олександр Пономарів «Культура слова»",
            "кальковану прийменникову сполуку замінено на «залежно від»",
            "Олександр Пономарів («Культура слова») указує на нормативність прийменникової сполуки «залежно від» на противагу калькованій «у залежності від»."
        )
    if "в кінці кінців" in err_lower:
        return (
            "Святослав Караванський «Російсько-український словник складної лексики»",
            "суржиковий вираз «в кінці кінців» замінено на питомий літературний еквівалент",
            "Святослав Караванський фіксує нормативні вислови «зрештою», «кінець кінцем» на заміну російської кальки «в кінці кінців»."
        )
    if "на протязі" in err_lower:
        return (
            "Борис Антоненко-Давидович «Як ми говоримо»",
            "помилкове слововживання «на протязі» виправлено на часовий прийменник «протягом» / «упродовж»",
            "Борис Антоненко-Давидович розмежовує пароніми: «на протязі» — на струмені повітря, тоді як для часових меж слід уживати «протягом» або «упродовж»."
        )
    if "в першу чергу" in err_lower or "у першу чергу" in err_lower:
        return (
            "Борис Антоненко-Давидович «Як ми говоримо»",
            f"кальковану сполуку «{err}» виправлено на нормативні прислівники «насамперед», «передусім»",
            f"Борис Антоненко-Давидович радить замість кальки «{err}» вживати природні українські відповідники «насамперед», «передусім», «найперше».",
        )

    # 2. General Calques (F/Calque)
    if primary_tag == "F/Calque":
        return (
            "Український правопис (2019) / Академічна граматика української мови",
            f"кальковану або невластиву мовну одиницю «{err}» замінено на питомий літературний еквівалент «{corr}»",
            f"Згідно з нормами сучасного українського слововжитку та «Українського правопису» (2019), конструкцію «{err}» виправлено на питомий український вислів «{corr}»."
        )

    # 3. Case government and inflection (G/Case)
    if primary_tag == "G/Case":
        err_words = err.strip().split()
        corr_words = corr.strip().split()
        if len(err_words) == 1 and len(corr_words) == 1:
            err_w, corr_w = err_words[0], corr_words[0]
            if is_vocative_form(corr_w) and not is_vocative_form(err_w):
                # Also verify err_w is a single noun and NOT a pronoun
                conn = _get_vesum_connection()
                is_err_noun = False
                if conn is not None:
                    res_err = conn.cursor().execute(
                        "SELECT pos, tags FROM forms_all WHERE word_form IN (?, ?, ?)",
                        (err_w.lower(), err_w.capitalize(), err_w.upper()),
                    ).fetchall()
                    is_err_noun = any(pos == "noun" and "pron" not in tags for pos, tags in res_err)
                if is_err_noun:
                    return (
                        "Український правопис (2019) § 87 / Олександр Пономарів «Культура слова»",
                        f"помилкове вживання називного відмінка замість кличного у звертанні «{err}» виправлено на «{corr}»",
                        f"«Український правопис» (2019, § 87) та норми культури мови (Олександр Пономарів) вимагають уживати у звертаннях кличний відмінок, а не називний: вживаємо «{corr}» замість «{err}»."
                    )
        return (
            "VESUM / Український правопис (2019)",
            f"помилку у відмінковій формі «{err}» виправлено на нормативну форму «{corr}»",
            f"Словникова база VESUM та граматичні норми української мови («Український правопис», 2019) визначають нормативні відмінкові форми слів у реченні: форму «{err}» виправлено на «{corr}»."
        )

    # 4. Prepositions (G/Prep)
    if primary_tag == "G/Prep":
        if any(p in err_lower for p in ["з під", "зпід", "з над", "знад", "з за", "зза", "із за"]):
            return (
                "Український правопис (2019) § 37, п. 2",
                f"орфографічну помилку у складному прийменнику «{err}» виправлено на дефісне написання «{corr}»",
                "«Український правопис» (2019, § 37, п. 2) встановлює, що складні прийменники з першою частиною «з-», «із-» пишуться через дефіс: з-під, з-над, з-за, із-за."
            )
        prep_words = {
            "у", "в", "на", "до", "з", "із", "зі", "по", "за", "про", "через", "при",
            "під", "над", "перед", "від", "для", "без", "біля", "проти", "серед",
            "завдяки", "щодо", "згідно", "стосовно", "всупереч", "посеред", "внаслідок",
            "навколо", "поруч", "поза"
        }
        if any(w in prep_words for w in err_lower.split()) or any(w in prep_words for w in corr_lower.split()):
            return (
                "Український правопис (2019) / Академічна граматика української мови",
                f"невластиву прийменникову конструкцію «{err}» замінено на літературну «{corr}»",
                f"Згідно з нормами «Українського правопису» (2019) та академічної граматики, прийменникові сполуки мають відповідати семантиці українського вислову: у цьому разі вживаємо «{corr}» замість «{err}»."
            )
        return None

    # 5. Gender agreement (G/Gender)
    if primary_tag == "G/Gender":
        return (
            "VESUM / Український правопис (2019)",
            f"порушення узгодження в роді «{err}» виправлено на форму «{corr}»",
            f"Морфологічна система української мови (VESUM) вимагає граматичного узгодження за родом: форму «{err}» виправлено на «{corr}»."
        )

    # 6. Number forms and quantifier agreement (G/Number)
    if primary_tag == "G/Number":
        return (
            "Український правопис (2019) § 32 / VESUM",
            f"помилку у формі числа «{err}» виправлено на нормативну «{corr}»",
            f"«Український правопис» (2019, § 32) та словникова база VESUM регламентують нормативні числові закінчення іменників і прикметників: вживаємо «{corr}» замість «{err}»."
        )

    # 7. Verb Voice (G/VerbVoice): heterogeneous tag covering reflexive usage, modal infinitives,
    # and passives; fails closed to silent_rewrite to prevent overbroad voice explanations.
    if primary_tag == "G/VerbVoice":
        return None

    # 8. Verb Aspect Form / Imperative / Adverbial Participle (G/VerbAForm)
    if primary_tag == "G/VerbAForm":
        if err_lower.startswith(("давай", "давайте")) or any(w.startswith(("давай", "давайте")) for w in err_lower.split()):
            return (
                "Борис Антоненко-Давидович «Як ми говоримо» / Олександр Пономарів",
                f"кальковану форму наказового способу з часткою «{err}» замінено на питому форму «{corr}»",
                f"Борис Антоненко-Давидович та Олександр Пономарів наголошують, що конструкції з «давай / давайте» є калькою з російської; в українській мові слід уживати синтетичні форми наказового способу («{corr}»)."
            )
        adv_sufs = ("чи", "ши", "вшись", "вшися", "ючись", "ючися")
        if any(err_lower.endswith(s) for s in adv_sufs) or any(any(w.endswith(s) for s in adv_sufs) for w in err_lower.split()):
            return (
                "Український правопис (2019) / Академічна граматика української мови",
                f"помилкове вживання або творення дієприслівникової форми «{err}» виправлено на «{corr}»",
                f"За нормами українського синтаксису дія дієприслівника обов'язково повинна стосуватися суб'єкта основної дії (присудка): форму «{err}» виправлено на «{corr}»."
            )
        return None

    # 9. Participle Voice (G/PartVoice): active participles
    if primary_tag == "G/PartVoice":
        pv_sufs = (
            "чий", "чого", "чому", "чим", "чім", "ча", "чої", "чій", "чу", "чою", "че",
            "чі", "чих", "чими", "ший", "шого", "шому", "шим", "шім", "ша", "шої", "шій",
            "шу", "шою", "ше", "ші", "ших", "шими"
        )
        if any(err_lower.endswith(s) for s in pv_sufs) or any(any(w.endswith(s) for s in pv_sufs) for w in err_lower.split()):
            return (
                "Олександр Пономарів «Культура слова» / Борис Антоненко-Давидович",
                f"невластивий активний дієприкметник «{err}» замінено на нормативну форму «{corr}»",
                f"Олександр Пономарів («Культура слова») та Борис Антоненко-Давидович наголошують, що активні дієприкметники теперішнього часу на «-чий» невластиві українській мові й мають замінюватися описовими зворотами або питомими прикметниками («{corr}» замість «{err}»)."
            )
        return None

    # 10. Participle (G/Participle): passive participles
    if primary_tag == "G/Participle":
        part_sufs = (
            "ний", "ного", "ному", "ним", "нім", "на", "ної", "ній", "ну", "ною", "не",
            "ні", "них", "ними", "тий", "того", "тому", "тим", "тім", "та", "тої", "тій",
            "ту", "тою", "те", "ті", "тих", "тими"
        )
        if any(err_lower.endswith(s) for s in part_sufs) or any(any(w.endswith(s) for s in part_sufs) for w in err_lower.split()):
            return (
                "Український правопис (2019) / VESUM",
                f"помилку у творенні або узгодженні пасивного дієприкметника «{err}» виправлено на «{corr}»",
                f"«Український правопис» (2019) та база VESUM закріплюють нормативні суфіксальні моделі дієприкметників: форму «{err}» виправлено на «{corr}»."
            )
        return None

    # 11. Comparison (G/Comparison)
    if primary_tag == "G/Comparison":
        comp_sufs = (
            "іший", "іша", "іше", "іші", "ішим", "іших", "ішими", "ішому",
            "ший", "ша", "ше", "ші", "шим", "ших", "шими", "шому"
        )
        comp_keywords = ["більш", "менш", "найбільш", "найменш", "сам", "кращ", "гірш"]
        words = err_lower.split()
        has_compound_marker = any(w in {"більш", "менш", "найбільш", "найменш"} for w in words)
        has_simple_comp_morph = any(
            w.endswith(comp_sufs) or any(k in w for k in ("кращ", "гірш", "вищ", "нижч", "глибш"))
            for w in words
            if w not in {"більш", "менш", "найбільш", "найменш"}
        )
        has_sam_marker = any(
            w in {"сам", "самий", "сама", "саме", "самі", "самих", "самим", "самому", "самою"}
            for w in words
        )

        # Case 1: Russianism with сам / самий
        if has_sam_marker:
            return (
                "Борис Антоненко-Давидович «Як ми говоримо» / Український правопис (2019) § 111",
                f"кальковану форму найвищого ступеня порівняння з часткою «сам» «{err}» замінено на нормативну «{corr}»",
                f"Борис Антоненко-Давидович та «Український правопис» (2019, § 111) зазначають, що творення найвищого ступеня порівняння за допомогою слів «самий/сама/саме» є калькою з російської мови; нормативна форма утворюється за допомогою префікса «най-» («{corr}» замість «{err}»)."
            )

        # Case 2: Mixing simple and compound forms (e.g. найбільш кращий)
        if has_compound_marker and has_simple_comp_morph:
            return (
                "Український правопис (2019) § 111 / Олександр Пономарів",
                f"помилкове змішування простої та складеної форм ступеня порівняння «{err}» виправлено на «{corr}»",
                f"«Український правопис» (2019, § 111) та Олександр Пономарів застерігають від змішування простої та складеної форм ступенів порівняння: замість ненормативного «{err}» уживаємо «{corr}»."
            )

        # Case 3: Compound (analytic) replaced by simple (synthetic) form (e.g. найбільш вдала -> найвдаліша)
        if has_compound_marker:
            return (
                "Олександр Пономарів «Культура слова» / Український правопис (2019) § 111",
                f"громіздку складену форму ступеня порівняння «{err}» замінено на природну просту форму «{corr}»",
                f"Олександр Пономарів («Культура слова») та мовна практика радять віддавати перевагу органічній простій (синтетичній) формі ступеня порівняння над громіздкою складеною: форму «{err}» замінено на «{corr}»."
            )

        # Case 4: General comparative/superlative formation error
        if (
            any(k in err_lower for k in comp_keywords)
            or any(err_lower.endswith(s) for s in comp_sufs)
            or any(any(w.endswith(s) for s in comp_sufs) for w in err_lower.split())
        ):
            return (
                "Український правопис (2019) § 111 / VESUM",
                f"помилку у творенні ступеня порівняння «{err}» виправлено на нормативну форму «{corr}»",
                f"«Український правопис» (2019, § 111) та словникова база VESUM визначають нормативні словотвірні моделі ступенів порівняння: форму «{err}» виправлено на «{corr}»."
            )
        return None

    # 12. Conjunctions (G/Conjunction)
    if primary_tag == "G/Conjunction":
        if "так як" in err_lower:
            return (
                "Борис Антоненко-Давидович «Як ми говоримо» / Олександр Пономарів",
                "калькований сполучник причини «так як» замінено на питомий літературний сполучник",
                "Борис Антоненко-Давидович та Олександр Пономарів послідовно вказують, що штучний сполучник «так як» в українській мові слід замінювати на «оскільки», «тому що» або «бо»."
            )
        if "в той час як" in err_lower:
            return (
                "Борис Антоненко-Давидович «Як ми говоримо»",
                "калькований сполучник «в той час як» замінено на питомий протиставний сполучник «тоді як»",
                "Борис Антоненко-Давидович рекомендує вживати природні сполучники «тоді як», «тим часом як» замість кальки «в той час як»."
            )
        conj_words = {
            "що", "щоб", "як", "якщо", "якби", "бо", "але", "а", "і", "й", "та", "хоч",
            "хоча", "мов", "неначе", "наче", "ніби", "немов", "котрий", "котра", "котре",
            "котрі", "який", "яка", "яке", "які", "чи", "тож", "проте", "однак", "зате",
            "коли", "доки", "поки"
        }
        if any(w in conj_words for w in err_lower.split()) or any(w in conj_words for w in corr_lower.split()):
            return (
                "Академічна граматика української мови / Олександр Пономарів",
                f"сполучний елемент «{err}» замінено на нормативний сполучник «{corr}»",
                f"Академічна граматика та Олександр Пономарів регламентують нормативне вживання сполучників у складному реченні: у цьому контексті слід уживати «{corr}» замість «{err}»."
            )
        return None

    # 13. Particles (G/Particle)
    if primary_tag == "G/Particle":
        if (
            any(p in corr_lower for p in ["будь-", "-небудь", "казна-", "хтозна-", "-таки", "-бо", "-но"])
            or any(p in err_lower for p in ["будь ", " neбудь", "небудь", "казна ", "хтозна ", " таки", " бо", " но"])
        ):
            return (
                "Український правопис (2019) § 40",
                f"написання частки у сполуці «{corr}» виправлено на дефісне (замість «{err}»)",
                "«Український правопис» (2019, § 40) визначає, що частки «будь-», «-небудь», «казна-», «хтозна-», «-бо», «-но», «-таки» пишуться через дефіс."
            )
        particle_words = {
            "не", "ні", "ж", "же", "би", "б", "хай", "нехай", "таки", "навіть", "лише",
            "тільки", "ось", "он", "ото", "онде", "мов", "ніби", "чи"
        }
        if any(w in particle_words for w in err_lower.split()) or any(w in particle_words for w in corr_lower.split()):
            return (
                "Український правопис (2019) § 40 / VESUM",
                f"помилку у вживанні чи написанні частки «{err}» виправлено на «{corr}»",
                f"«Український правопис» (2019, § 40) регламентує правила вживання та написання часток в українській мові: уживаємо «{corr}» замість «{err}»."
            )
        return None

    # 14. Aspect (G/Aspect)
    if primary_tag == "G/Aspect":
        return (
            "VESUM / Академічна граматика української мови",
            f"недоречну видову форму дієслова «{err}» замінено на доречну видову пару «{corr}»",
            f"В українській граматиці видова семантика дієслів відображає характер протікання дії; форму «{err}» виправлено на видову пару «{corr}» (VESUM)."
        )

    # 15. Tense (G/Tense)
    if primary_tag == "G/Tense":
        return (
            "Український правопис (2019) / Олександр Пономарів «Культура слова»",
            f"часову форму дієслова «{err}» узгоджено в контексті висловлювання як «{corr}»",
            f"Синтаксичні норми української мови (Олександр Пономарів, «Культура слова») вимагають узгодження часових форм: уживаємо «{corr}» замість «{err}»."
        )

    # 16. UngrammaticalStructure and Other -> fail closed, return None (drops to silent rewrite)
    if primary_tag in {"G/UngrammaticalStructure", "G/Other"}:
        return None

    return None


def build_reasoning_and_response(
    original_text: str,
    corrected_text: str,
    is_erroneous: bool,
    is_explained: bool,
    primary_tag: str,
    register: str,
    error_span: str,
    replacement_span: str,
    seed_index: int,
) -> tuple[list[str], str, dict[str, Any]]:
    """Build standardized reasoning steps, final response, and source metadata.

    Returns:
        (reasoning_steps, final_response, source_metadata)
    """
    if is_erroneous:
        err = (error_span or "").strip()
        corr = (replacement_span or "").strip()

        citation = resolve_specific_linguistic_citation(
            primary_tag, error_span, replacement_span, original_text, corrected_text
        )

        # Fail-closed explanation drop: if not explained or citation cannot be specifically verified
        if not is_explained or citation is None:
            source_metadata = {
                "authority": "Український правопис (2019)",
                "error_type": primary_tag,
                "category": TAG_TO_COARSE_CATEGORY.get(primary_tag, "syntax_structure"),
                "register": register,
                "error_span": err,
                "replacement_span": corr,
                "linguistic_rule": "",
            }
            return [], corrected_text, source_metadata

        authority, desc, rule = citation

        source_metadata = {
            "authority": authority,
            "error_type": primary_tag,
            "category": TAG_TO_COARSE_CATEGORY.get(primary_tag, "syntax_structure"),
            "register": register,
            "error_span": err,
            "replacement_span": corr,
            "linguistic_rule": rule,
        }

        # Build 3-step structured reasoning
        step1 = (
            f"1. Характер помилки ({register}): у наведеному тексті виявлено порушення ({primary_tag}) — {desc}. "
            f"Ненормативний фрагмент «{err}» потребує виправлення на «{corr}»."
        )
        step2 = f"2. Нормативне обґрунтування: {rule}"
        step3 = f"3. Літературне виправлення: замінюємо помилкову форму й отримуємо правильне речення: {corrected_text}"
        reasoning_steps = [step1, step2, step3]

        tmpl = RESPONSE_TEMPLATES_CORRECTION[seed_index % len(RESPONSE_TEMPLATES_CORRECTION)]
        final_response = tmpl.format(
            authority=authority,
            desc=desc,
            rule=rule,
            err=err,
            corr=corr,
            target=corrected_text,
        )

        return reasoning_steps, final_response, source_metadata

    else:
        # Clean control
        authority = CONTROL_PROFILE["authority"]
        rule = CONTROL_PROFILE["rule_template"]

        if not is_explained:
            source_metadata = {
                "authority": authority,
                "error_type": "control_clean",
                "category": "protective_authentic_control",
                "register": register,
                "linguistic_rule": "",
            }
            return [], original_text, source_metadata

        source_metadata = {
            "authority": authority,
            "error_type": "control_clean",
            "category": "protective_authentic_control",
            "register": register,
            "linguistic_rule": rule,
        }

        step1 = (
            f"1. Аналіз вихідного тексту ({register}): речення ретельно перевірено на наявність граматичних, "
            "морфологічних, орфографічних чи синтаксичних дефектів. Жодних відхилень від норми не виявлено."
        )
        step2 = f"2. Нормативне обґрунтування: {rule}"
        step3 = f"3. Висновок: текст повністю відповідає літературній нормі й залишається без змін: {original_text}"
        reasoning_steps = [step1, step2, step3]

        tmpl = RESPONSE_TEMPLATES_CONTROL[seed_index % len(RESPONSE_TEMPLATES_CONTROL)]
        final_response = tmpl.format(
            authority=authority,
            target=original_text,
        )

        return reasoning_steps, final_response, source_metadata


