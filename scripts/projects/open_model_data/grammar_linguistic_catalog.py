def classify_sentence_register(sentence: str) -> str:
    """Classify the authentic functional register of a Ukrainian sentence."""
    tokens = re.findall(r"[а-яіїєґА-ЯІЇЄҐ']+", sentence.lower())
    scores = {"administrative": 0, "educational": 0, "journalistic": 0, "literary": 0, "conversational": 0}

    for t in tokens:
        if t in {"акт", "акти", "акта", "акту", "актом", "актах"} or (
            t.startswith("справ") and not t.startswith("справжн")
        ):
            scores["administrative"] += 3
        elif any(t.startswith(s) for s in ADMIN_STEMS):
            scores["administrative"] += 2

        if any(t.startswith(s) for s in EDU_STEMS):
            scores["educational"] += 2

        if any(t.startswith(s) for s in JOURN_STEMS):
            scores["journalistic"] += 2

        if any(t.startswith(s) for s in LIT_STEMS):
            scores["literary"] += 2

        if any(t.startswith(s) for s in CONV_STEMS):
            scores["conversational"] += 2

    best = max(scores, key=scores.get)
    if scores[best] == 0:
        return "journalistic"
    return best


