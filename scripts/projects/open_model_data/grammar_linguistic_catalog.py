def build_reasoning_and_response(
    original_text: str,
    corrected_text: str,
    is_erroneous: bool,
    is_explained: bool,
    primary_tag: str,
    register: str,
    error_span: str,
    replacement_span: str,
    seed_index: int,
) -> tuple[list[str], str, dict[str, Any]]:
    """Build standardized reasoning steps, final response, and source metadata.

    Returns:
        (reasoning_steps, final_response, source_metadata)
    """
    if is_erroneous:
        prof = AUTHORITY_PROFILES.get(primary_tag) or AUTHORITY_PROFILES["G/Other"]
        authority = prof["authority"]
        desc = prof["description"]
        rule = prof["rule_template"]
        err = error_span or "помилковий фрагмент"
        corr = replacement_span or "виправлений варіант"

        source_metadata = {
            "authority": authority,
            "error_type": primary_tag,
            "category": TAG_TO_COARSE_CATEGORY.get(primary_tag, "syntax_structure"),
            "register": register,
            "error_span": err,
            "replacement_span": corr,
            "linguistic_rule": rule,
        }

        if not is_explained:
            return [], corrected_text, source_metadata

        # Build 3-step structured reasoning
        step1 = (
            f"1. Характер помилки ({register}): у наведеному тексті виявлено порушення ({primary_tag}) — {desc}. "
            f"Ненормативний фрагмент «{err}» потребує виправлення на «{corr}»."
        )
        step2 = f"2. Нормативне обґрунтування: {rule}"
        step3 = f"3. Літературне виправлення: замінюємо помилкову форму й отримуємо правильне речення: {corrected_text}"
        reasoning_steps = [step1, step2, step3]

        tmpl = RESPONSE_TEMPLATES_CORRECTION[seed_index % len(RESPONSE_TEMPLATES_CORRECTION)]
        final_response = tmpl.format(
            authority=authority,
            desc=desc,
            rule=rule,
            err=err,
            corr=corr,
            target=corrected_text,
        )

        return reasoning_steps, final_response, source_metadata

    else:
        # Clean control
        authority = CONTROL_PROFILE["authority"]
        rule = CONTROL_PROFILE["rule_template"]

        source_metadata = {
            "authority": authority,
            "error_type": "control_clean",
            "category": "protective_authentic_control",
            "register": register,
            "linguistic_rule": rule,
        }

        if not is_explained:
            return [], original_text, source_metadata

        step1 = (
            f"1. Аналіз вихідного тексту ({register}): речення ретельно перевірено на наявність граматичних, "
            "морфологічних, орфографічних чи синтаксичних дефектів. Жодних відхилень від норми не виявлено."
        )
        step2 = f"2. Нормативне обґрунтування: {rule}"
        step3 = f"3. Висновок: текст повністю відповідає літературній нормі й залишається без змін: {original_text}"
        reasoning_steps = [step1, step2, step3]

        tmpl = RESPONSE_TEMPLATES_CONTROL[seed_index % len(RESPONSE_TEMPLATES_CONTROL)]
        final_response = tmpl.format(
            authority=authority,
            target=original_text,
        )

        return reasoning_steps, final_response, source_metadata


