#!/usr/bin/env python3
"""Generate the fresh-arc landing data, landing page and module pages (#8397).

``python -m scripts.build.build_arc_landing <level> --write | --check``

Reads the accepted arc (``load_arc``), the v2 module plans, the scope sidecars
and the build-state files, and writes three kinds of generated file:

* ``site/src/data/arc-<level>.json`` — one record per arc position;
* ``site/src/content/docs/<level>/index.mdx`` — the landing;
* ``site/src/content/docs/<level>/<slug>/index.mdx`` — one module page per position;

and keeps ``docs/l2-uk-en/level-status.yaml``'s ``<level>.planned`` equal to the arc's
position count (only that value is rewritten).

The MDX files carry only frontmatter (``arc_kind``, ``arc_level``, ``arc_slug``)
and an empty body; ``site/src/pages/[...slug].astro`` mounts ``ArcLanding`` /
``ArcModule`` from the JSON when ``arc_kind`` is set. Nothing on those pages is
typed by hand: the module list is the arc, the numbers are the scope sidecars,
the states are files that exist. ``--check`` compares every output byte for
byte and exits non-zero on the first stale file.

State machine (file-defined; ``planned`` is the fallback and a missing file or
``_state/`` directory is never an error)::

    planned < plan_reviewed < built < reviewed

* ``plan_reviewed`` — the plan exists and ``_state/<slug>/plan-review.yaml``
  records ``verdict: APPROVE``;
* ``built`` — every lesson ``1..N`` of the plan (its numbers must be exactly ``1..N``; a
  plan that breaks that is an error, never ``built``) has ``<slug>/<n>.mdx`` and
  ``_state/<slug>/lesson-<n>.gates.yaml`` with ``passed: true``;
* ``reviewed`` — ``_state/<slug>/module-verdict.yaml`` records ``verdict: APPROVE``.

A position gets the highest state whose predicate holds when every lower
predicate holds too.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from scripts.curriculum.arc.loader import ArcPosition, load_arc
from scripts.curriculum.validate.loader import PlanError, check_plan_slug, load_plan

REPO_ROOT = Path(__file__).resolve().parents[2]

#: Levels whose landing this generator owns; scripts/build/build_landing_pages.py and
#: scripts/generate_landing_pages.py skip them (a test keeps the three in step).
ARC_LANDING_LEVELS = frozenset({"a1"})
CHECKPOINT_SLUG_PREFIX = "checkpoint-"
PREVIOUS_EDITION_TRACK = "{level}-v1"
#: A source line reference in an arc job, e.g. ``(`:485`)`` or ``(`:549-551`)``.
JOB_LINE_REF_RE = re.compile(r"\s*\(`:\d+(-\d+)?`\)")
GENERATED_NOTE = "Generated by scripts/build/build_arc_landing.py; do not edit by hand."


@dataclass(frozen=True)
class Roots:
    """Where the generator reads and writes; tests point this at a temp tree."""

    repo: Path
    level: str

    @property
    def plans(self) -> Path:
        return self.repo / "curriculum/l2-uk-en/lesson-plans" / self.level

    @property
    def scope(self) -> Path:
        return self.plans / "_scope"

    @property
    def state(self) -> Path:
        return self.repo / "curriculum/l2-uk-en/evidence" / self.level / "_state"

    @property
    def docs(self) -> Path:
        return self.repo / "site/src/content/docs" / self.level

    @property
    def previous_docs(self) -> Path:
        return self.repo / "site/src/content/docs" / PREVIOUS_EDITION_TRACK.format(level=self.level)

    @property
    def level_status(self) -> Path:
        return self.repo / "docs/l2-uk-en/level-status.yaml"

    @property
    def data_json(self) -> Path:
        return self.repo / "site/src/data" / f"arc-{self.level}.json"


def humanise_slug(slug: str) -> str:
    """``sounds-letters-and-hello`` -> ``Sounds letters and hello``."""
    words = slug.replace("-", " ")
    return words[:1].upper() + words[1:]


def display_job(job: str) -> str:
    """The arc job as plain learner-facing text: no source line references, no markdown backticks."""
    return JOB_LINE_REF_RE.sub("", job).replace("`", "")


def _read_mapping(path: Path) -> dict[str, Any] | None:
    """Parse a YAML mapping; a missing file is ``None``, a malformed one raises."""
    if not path.is_file():
        return None
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as error:
        raise ValueError(f"{path} is not valid YAML: {error}") from error
    if not isinstance(data, dict):
        raise ValueError(f"{path} does not hold a mapping at the top level")
    return data


def _load_module_plan(roots: Roots, slug: str) -> dict[str, Any] | None:
    plan_path = roots.plans / f"{slug}.yaml"
    if not plan_path.is_file():
        return None
    try:
        plan = load_plan(plan_path)
        check_plan_slug(plan_path, slug, plan)
    except PlanError as error:
        raise ValueError(f"cannot read plan {plan_path}: {error}") from error
    numbers = _lesson_numbers(plan)
    if not numbers or numbers != list(range(1, len(numbers) + 1)):
        raise ValueError(f"plan {slug}: lesson numbers must be exactly 1..N (contiguous, no duplicates, non-empty); found {numbers}")
    return plan


def _lesson_numbers(plan: dict[str, Any]) -> list[int]:
    return [int(lesson["n"]) for lesson in plan["lessons"]]


def _scope_record(roots: Roots, slug: str) -> dict[str, int] | None:
    scope = _read_mapping(roots.scope / f"{slug}.yaml")
    if scope is None:
        return None
    return {
        "letters": int(scope["letters"]["count"]),
        "grammar_points": int(scope["grammar"]["count"]),
        "core_lemmas": int(scope["vocabulary"]["core_count"]),
    }


def _built_lessons(roots: Roots, slug: str, plan: dict[str, Any]) -> list[int]:
    """Lessons with a page under ``docs/<level>/<slug>/<n>.mdx`` and passed gates."""
    built = []
    for n in _lesson_numbers(plan):
        page = roots.docs / slug / f"{n}.mdx"
        gates = _read_mapping(roots.state / slug / f"lesson-{n}.gates.yaml")
        if page.is_file() and gates is not None and gates.get("passed") is True:
            built.append(n)
    return built


def _approved(path: Path) -> bool:
    doc = _read_mapping(path)
    return doc is not None and doc.get("verdict") == "APPROVE"


def position_state(roots: Roots, slug: str, plan: dict[str, Any] | None, built: list[int]) -> str:
    """Highest state whose predicate holds with every lower predicate holding."""
    if plan is None or not _approved(roots.state / slug / "plan-review.yaml"):
        return "planned"
    if built != _lesson_numbers(plan):
        return "plan_reviewed"
    if not _approved(roots.state / slug / "module-verdict.yaml"):
        return "built"
    return "reviewed"


def build_record(roots: Roots, arc_position: ArcPosition) -> dict[str, Any]:
    slug = arc_position.slug
    plan = _load_module_plan(roots, slug)
    built = _built_lessons(roots, slug, plan) if plan is not None else []
    previous_page = roots.previous_docs / f"{slug}.mdx"
    return {
        "position": arc_position.position,
        "slug": slug,
        "phase": arc_position.phase,
        "title_uk": str(plan["title"]) if plan is not None else None,
        "title_en": humanise_slug(slug),
        "job": display_job(arc_position.job),
        "skills": list(arc_position.skills),
        "is_checkpoint": slug.startswith(CHECKPOINT_SLUG_PREFIX),
        "est_lessons": arc_position.est_lessons,
        "lessons": len(plan["lessons"]) if plan is not None else None,
        "built_lessons": built,
        "lesson_numbers": _lesson_numbers(plan) if plan is not None else [],
        "lesson_titles": [str(lesson["title"]) for lesson in plan["lessons"]] if plan is not None else [],
        "scope": _scope_record(roots, slug),
        "state": position_state(roots, slug, plan, built),
        "previous_edition_href": (
            f"/{PREVIOUS_EDITION_TRACK.format(level=roots.level)}/{slug}/" if previous_page.is_file() else None
        ),
    }


def _yaml_scalar(value: str) -> str:
    """A double-quoted YAML scalar (JSON strings are valid YAML flow scalars)."""
    return json.dumps(value, ensure_ascii=False)


def render_json(level: str, records: list[dict[str, Any]]) -> str:
    return json.dumps({"level": level, "positions": records}, ensure_ascii=False, indent=2) + "\n"


def render_landing(level: str, records: list[dict[str, Any]]) -> str:
    title = level.upper()
    description = f"{len(records)} modules in arc order, grouped by phase."
    return (
        "---\n"
        f"# {GENERATED_NOTE}\n"
        f"title: {_yaml_scalar(title)}\n"
        f"description: {_yaml_scalar(description)}\n"
        "arc_kind: landing\n"
        f"arc_level: {level}\n"
        "---\n"
    )


def render_module(level: str, record: dict[str, Any]) -> str:
    title = record["title_uk"] or record["title_en"]
    return (
        "---\n"
        f"# {GENERATED_NOTE}\n"
        f"title: {_yaml_scalar(title)}\n"
        f"description: {_yaml_scalar(record['job'])}\n"
        "sidebar:\n"
        f"  order: {record['position']}\n"
        "arc_kind: module\n"
        f"arc_level: {level}\n"
        f"arc_slug: {record['slug']}\n"
        "---\n"
    )


def render_level_status(text: str, level: str, planned: int) -> str:
    """``text`` with ``<level>.planned`` set to ``planned``; every other byte is untouched."""
    # The level's top-level block: indented or blank lines after ``<level>:`` up to its ``  planned:``.
    pattern = re.compile(rf"^(?P<head>{re.escape(level)}:\n(?:(?!\S).*\n)*?  planned: )\d+", re.MULTILINE)
    if pattern.search(text) is None:
        raise ValueError(f"level-status.yaml has no `{level}:` block with a `planned:` count")
    return pattern.sub(lambda match: f"{match.group('head')}{planned}", text, count=1)


def generated_files(roots: Roots, arc: list[ArcPosition]) -> dict[Path, str]:
    """Every output file (path -> exact text) for the level, in arc order."""
    records = [build_record(roots, arc_position) for arc_position in arc]
    files: dict[Path, str] = {
        roots.data_json: render_json(roots.level, records),
        roots.docs / "index.mdx": render_landing(roots.level, records),
        roots.level_status: render_level_status(
            roots.level_status.read_text(encoding="utf-8"), roots.level, len(arc)
        ),
    }
    for record in records:
        files[roots.docs / record["slug"] / "index.mdx"] = render_module(roots.level, record)
    return files


def write_files(files: dict[Path, str]) -> None:
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def stale_files(files: dict[Path, str]) -> list[Path]:
    """Paths whose bytes on disk differ from the generated text (missing counts)."""
    return [
        path for path, text in files.items() if not path.is_file() or path.read_bytes() != text.encode("utf-8")
    ]


def orphan_pages(roots: Roots, arc: list[ArcPosition]) -> list[Path]:
    """``<slug>/index.mdx`` pages on disk for a slug that is not in the arc.

    Lesson files (``<slug>/<n>.mdx``) belong to the lesson build, not this generator.
    """
    slugs = {arc_position.slug for arc_position in arc}
    if not roots.docs.is_dir():
        return []
    return sorted(
        page
        for directory in roots.docs.iterdir()
        if directory.is_dir() and directory.name not in slugs and (page := directory / "index.mdx").is_file()
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("level", help="level whose arc to render, e.g. a1")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the generated files")
    mode.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    args = parser.parse_args(argv)

    roots = Roots(REPO_ROOT, args.level)
    arc = load_arc(args.level)
    files = generated_files(roots, arc)
    if args.write:
        write_files(files)
        print(f"wrote {len(files)} files for {args.level}")
        return 0
    stale = stale_files(files)
    orphans = orphan_pages(roots, arc)
    if stale or orphans:
        for path in stale:
            print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        for path in orphans:
            print(f"orphan (slug not in the arc; delete it): {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        if stale:
            print(
                f"{len(stale)} of {len(files)} generated files are stale; run "
                f"python -m scripts.build.build_arc_landing {args.level} --write",
                file=sys.stderr,
            )
        return 1
    print(f"{args.level}: {len(files)} generated files are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
