def _huge_process_table(monkeypatch: pytest.MonkeyPatch, marker: str) -> dict[str, int]:
    """Count names a full listing would return, and entries a lazy scan actually pulls."""
    stats = {"listdir_names": 0, "scandir_pulls": 0}
    real_listdir = os.listdir
    real_scandir = os.scandir
    real_readlink = os.readlink

    def fake_listdir(path: object) -> list[str]:
        if os.fspath(path) == marker:
            names = [str(index) for index in range(1, 100_001)]
            stats["listdir_names"] += len(names)
            return names
        return real_listdir(path)

    class _Scan:
        def __enter__(self) -> _Scan:
            return self

        def __exit__(self, *_args: object) -> bool:
            return False

        def __iter__(self) -> _Scan:
            return self

        def __next__(self) -> object:
            stats["scandir_pulls"] += 1
            if stats["scandir_pulls"] > 100_000:
                raise StopIteration
            return type("Entry", (), {"name": str(stats["scandir_pulls"])})()

        def close(self) -> None:
            return None

    def fake_scandir(path: object) -> object:
        if os.fspath(path) == marker:
            return _Scan()
        return real_scandir(path)

    def fake_readlink(path: object) -> str:
        text = os.fspath(path)
        if text.endswith("/exe"):
            return "/var/secret/place/python"
        if text.endswith("/cwd"):
            return "/var/secret/place/workdir"
        return real_readlink(text)

    monkeypatch.setattr(os, "listdir", fake_listdir)
    monkeypatch.setattr(os, "scandir", fake_scandir)
    monkeypatch.setattr(os, "readlink", fake_readlink)
    return stats


def test_process_scan_stops_when_the_deadline_has_expired(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """An already-expired deadline must not materialise the process table."""
    marker = str(tmp_path / "proc")
    stats = _huge_process_table(monkeypatch, marker)
    rows = _collect_processes(Path(marker), time.monotonic() - 1)
    assert rows == []
    assert stats["listdir_names"] == 0
    assert stats["scandir_pulls"] == 0


def test_process_scan_stops_at_the_row_limit_without_reading_the_rest(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The row limit is applied while scanning, not after a full listing."""
    marker = str(tmp_path / "proc")
    stats = _huge_process_table(monkeypatch, marker)
    rows = _collect_processes(Path(marker), time.monotonic() + 30)
    assert len(rows) == _PROCESS_ROW_LIMIT
    assert stats["listdir_names"] == 0
    assert stats["scandir_pulls"] == _PROCESS_ROW_LIMIT
    assert rows[0]["command"] == "python"
    assert "/" not in rows[0]["command"]


