"""Tests for the node_modules integrity probe (#6818).

scripts/audit/check_node_modules_integrity.py — detection ONLY of symlink
corruption reaching through ``_provision_data_symlinks``'s direct
``node_modules -> <primary>/node_modules`` conduit (scripts/delegate.py). No
repair path exists here; a detection is always an ALERT.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from scripts.audit.check_node_modules_integrity import (
    check_node_modules_integrity,
    check_sentinel,
    find_outside_symlinks,
    main,
)


def _events(state_dir: Path) -> list[dict]:
    path = state_dir / "events.jsonl"
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _make_acpx_sentinel(repo: Path) -> None:
    """Install a healthy acpx sentinel (cli.js + resolving .bin shim)."""
    acpx_dist = repo / "node_modules" / "acpx" / "dist"
    acpx_dist.mkdir(parents=True)
    (acpx_dist / "cli.js").write_text("#!/usr/bin/env node\n")
    bin_dir = repo / "node_modules" / ".bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    (bin_dir / "acpx").symlink_to(Path("..") / "acpx" / "dist" / "cli.js")


# ---------------------------------------------------------------------------
# healthy cases
# ---------------------------------------------------------------------------


def test_clean_primary_is_ok(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)

    assert find_outside_symlinks(repo) == []
    ok, message = check_node_modules_integrity(repo, tasks_dir=tmp_path / "no-tasks", state_dir=tmp_path / "state")
    assert ok is True
    assert "ok" in message


def test_normal_bin_shim_resolving_inside_is_not_flagged(tmp_path: Path) -> None:
    """A real npm ``.bin`` shim (relative symlink to a sibling package) must
    never be mistaken for an escape — that would make every healthy install
    alert."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    pkg_bin = repo / "node_modules" / "some-pkg" / "bin"
    pkg_bin.mkdir(parents=True)
    (pkg_bin / "cli.js").write_text("#!/usr/bin/env node\n")
    (repo / "node_modules" / ".bin" / "some-pkg").symlink_to(Path("..") / "some-pkg" / "bin" / "cli.js")

    assert find_outside_symlinks(repo) == []
    ok, _ = check_node_modules_integrity(repo, tasks_dir=tmp_path / "no-tasks", state_dir=tmp_path / "state")
    assert ok is True


def test_scoped_package_symlink_inside_is_not_flagged(tmp_path: Path) -> None:
    """Depth-2 entries (``@scope/pkg``) that resolve inside the primary are healthy."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    real_pkg = repo / "node_modules" / "real-pkg"
    real_pkg.mkdir()
    scope_dir = repo / "node_modules" / "@scope"
    scope_dir.mkdir()
    (scope_dir / "pkg").symlink_to(real_pkg)

    assert find_outside_symlinks(repo) == []


