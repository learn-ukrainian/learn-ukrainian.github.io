_ARGV_MARKER = "ARGV_MARKER_7f3c1a"
_ENV_MARKER = "ENV_MARKER_7f3c1a"
_HOME_MARKER = "HOME_MARKER_7f3c1a"
_LONG_COMMAND = "cmd_" + ("x" * 80)
_LONG_CWD = "cwd_" + ("y" * 80)


def _fake_proc(root: Path, count: int) -> Path:
    """A process table whose argv, environ, and home path must not be recorded."""
    home = root / "tree" / _HOME_MARKER / _LONG_CWD
    home.mkdir(parents=True)
    exe = root / "tree" / _HOME_MARKER / _LONG_COMMAND
    exe.write_text("#!/bin/sh\n", encoding="utf-8")
    proc = root / "proc"
    proc.mkdir()
    junk = proc / "not-a-pid"
    junk.mkdir()
    (junk / "cmdline").write_text(_ARGV_MARKER, encoding="utf-8")
    for index in range(count):
        pid = proc / str(2000 + index)
        pid.mkdir()
        (pid / "cmdline").write_text(_ARGV_MARKER + "\x00--secret", encoding="utf-8")
        (pid / "environ").write_text(_ENV_MARKER + "=1\x00HOME=" + _HOME_MARKER, encoding="utf-8")
        (pid / "comm").write_text("comm-should-not-win\n", encoding="utf-8")
        (pid / "cwd").symlink_to(home)
        (pid / "exe").symlink_to(exe)
    return proc


def _alert(state_dir: Path) -> dict:
    alerts = [event for event in _events(state_dir) if event["event"] == "node_modules_integrity_alert"]
    assert alerts
    return alerts[-1]


def test_empty_node_modules_alert_records_attribution(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    modules = repo / "node_modules"
    modules.mkdir(parents=True)
