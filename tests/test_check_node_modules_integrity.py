def test_symlink_resolving_outside_primary_is_detected(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    outside_target = tmp_path / "outside-worktree" / "node_modules" / "evil-pkg"
    outside_target.mkdir(parents=True)
    (repo / "node_modules" / "evil-pkg").symlink_to(outside_target)

    found = find_outside_symlinks(repo)
    assert len(found) == 1
    assert found[0]["link"] == "node_modules/evil-pkg"
    assert str(outside_target.resolve()) in found[0]["target"] or os.path.realpath(outside_target) == found[0]["target"]

    ok, message = check_node_modules_integrity(repo, tasks_dir=tmp_path / "no-tasks", state_dir=tmp_path / "state")
    assert ok is False
    assert "OUTSIDE" in message
    assert "evil-pkg" in message

    alerts = [e for e in _events(tmp_path / "state") if e["event"] == "node_modules_integrity_alert"]
    assert alerts
    assert alerts[0]["outside_symlinks"][0]["link"] == "node_modules/evil-pkg"


def test_outside_bin_shim_is_detected(tmp_path: Path) -> None:
    """The exact incident shape: a ``.bin`` shim rewired to point at a
    worktree path instead of a sibling package inside the primary."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    worktree_bin = tmp_path / ".worktrees" / "dispatch" / "agy" / "task" / "node_modules" / ".bin" / "astro"
    worktree_bin.parent.mkdir(parents=True)
    worktree_bin.write_text("#!/usr/bin/env node\n")
    (repo / "node_modules" / ".bin" / "astro").symlink_to(worktree_bin)

    found = find_outside_symlinks(repo)
    assert any(f["link"] == "node_modules/.bin/astro" for f in found)

    ok, message = check_node_modules_integrity(repo, tasks_dir=tmp_path / "no-tasks", state_dir=tmp_path / "state")
    assert ok is False
    assert "astro" in message


def test_site_node_modules_is_checked_independently(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    outside_target = tmp_path / "outside" / "pkg"
    outside_target.mkdir(parents=True)
    site_nm = repo / "site" / "node_modules"
    site_nm.mkdir(parents=True)
    (site_nm / "evil").symlink_to(outside_target)

    found = find_outside_symlinks(repo)
    assert any(f["link"] == "site/node_modules/evil" for f in found)


def test_depth_beyond_two_is_not_walked(tmp_path: Path) -> None:
    """Depth <= 2 per the K3-reviewed scope: a symlink three levels deep is
    out of scope (never walked into in the first place)."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    outside_target = tmp_path / "outside" / "pkg"
    outside_target.mkdir(parents=True)
    deep_dir = repo / "node_modules" / "@scope" / "pkg" / "nested"
    deep_dir.mkdir(parents=True)
    (deep_dir / "evil").symlink_to(outside_target)

    found = find_outside_symlinks(repo)
    assert found == []


