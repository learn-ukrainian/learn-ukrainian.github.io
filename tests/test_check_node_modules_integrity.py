def test_unreadable_node_modules_and_process_table_do_not_raise(tmp_path: Path) -> None:
    """Searchable-but-unreadable install and an unreadable process table stay null or empty."""
    repo = tmp_path / "repo"
    modules = repo / "node_modules"
    modules.mkdir(parents=True)
    blocked = tmp_path / "blocked-proc"
    blocked.mkdir()
    (blocked / "9").mkdir()
    (blocked / "9" / "cmdline").write_text(_ARGV_MARKER, encoding="utf-8")
    state = tmp_path / "state"
    locked = os.geteuid() != 0
    if locked:
        # Execute without read: name lookup works, listing does not.
        modules.chmod(0o111)
        blocked.chmod(0)
    try:
        ok, message = check_node_modules_integrity(
            repo, tasks_dir=tmp_path / "no-tasks", state_dir=state, proc_root=blocked
        )
    finally:
        if locked:
            modules.chmod(0o755)
            blocked.chmod(0o755)
    assert ok is False
    assert "sentinel" in message
    alert = _alert(state)
    raw = (state / "events.jsonl").read_text(encoding="utf-8")
    assert _ARGV_MARKER not in raw and _ARGV_MARKER not in message
    if locked:
        assert alert["node_modules_entry_count"] is None
        assert alert["node_modules_mtime_utc"] is not None
        assert alert["processes"] == []
    else:
        assert isinstance(alert["processes"], list)
