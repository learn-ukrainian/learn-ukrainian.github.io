def test_missing_node_modules_directory_is_ok_not_a_crash(tmp_path: Path) -> None:
    """No node_modules at all (e.g. a fresh clone pre-install) must not
    itself be treated as an outside-symlink alert — only the sentinel check
    should fail, and it must not raise."""
    repo = tmp_path / "repo"
    repo.mkdir()

    assert find_outside_symlinks(repo) == []
    ok, message = check_node_modules_integrity(repo, tasks_dir=tmp_path / "no-tasks", state_dir=tmp_path / "state")
    assert ok is False
    assert "sentinel" in message


# ---------------------------------------------------------------------------
# attribution: running dispatches recorded on the alert event
# ---------------------------------------------------------------------------


def test_alert_event_names_running_dispatches(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    _make_acpx_sentinel(repo)
    outside_target = tmp_path / "outside"
    outside_target.mkdir()
    (repo / "node_modules" / "evil").symlink_to(outside_target)

    tasks_dir = tmp_path / "tasks"
    tasks_dir.mkdir()
    (tasks_dir / "agy-suspect.json").write_text(
        json.dumps(
            {
                "task_id": "agy/suspect",
                "agent": "agy",
                "status": "running",
                "pid": os.getpid(),
            }
        )
    )

    check_node_modules_integrity(repo, tasks_dir=tasks_dir, state_dir=tmp_path / "state")
    alerts = [e for e in _events(tmp_path / "state") if e["event"] == "node_modules_integrity_alert"]
    assert alerts
    running = alerts[0]["running_dispatches"]
    assert any(d["task_id"] == "agy/suspect" for d in running)


