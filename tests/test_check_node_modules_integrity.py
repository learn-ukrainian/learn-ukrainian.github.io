@pytest.fixture(autouse=True)
def _pin_main_root_to_the_given_repo(monkeypatch: pytest.MonkeyPatch) -> None:
    """Return the repo path ``_resolve_main_root`` was given.

    The probe asks Git for the primary checkout. A temp directory inside any
    Git tree resolves to that tree's primary, so the probe would inspect the
    real install instead of the fixture. These tests build ``repo`` themselves.
    """

    def _identity(repo: Path) -> Path:
        return Path(repo)

    monkeypatch.setattr("scripts.audit.check_node_modules_integrity._resolve_main_root", _identity)


def _events(state_dir: Path) -> list[dict]:
    path = state_dir / "events.jsonl"
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _make_acpx_sentinel(repo: Path) -> None:
    """Install a healthy acpx sentinel (cli.js + resolving .bin shim)."""
    acpx_dist = repo / "node_modules" / "acpx" / "dist"
    acpx_dist.mkdir(parents=True)
    (acpx_dist / "cli.js").write_text("#!/usr/bin/env node\n")
    bin_dir = repo / "node_modules" / ".bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    (bin_dir / "acpx").symlink_to(Path("..") / "acpx" / "dist" / "cli.js")


