def _clean_env(extra: dict[str, str] | None = None, unset: tuple[str, ...] = ()) -> dict[str, str]:
    # Entire 0.11.5's chain block exports ENTIRE_CHAINING_<HOOK> and skips the
    # chain while it is set, so a run from inside a chained hook (the pre-push
    # gate) must not leak it into these fixture repositories.
    env = {key: value for key, value in os.environ.items() if not key.startswith(("GIT_", "ENTIRE_CHAINING_"))}
    if extra:
        env.update(extra)
    for key in unset:
        env.pop(key, None)
    return env


def _run(
    command: list[str],
    *,
    cwd: Path,
    env: dict[str, str] | None = None,
    check: bool = True,
    unset: tuple[str, ...] = (),
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command,
        capture_output=True,
        check=check,
        cwd=cwd,
        env=_clean_env(env, unset),
        text=True,
        timeout=60,
    )


def _git(
    repo: Path,
    *args: str,
    env: dict[str, str] | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    return _run(["git", *args], cwd=repo, env=env, check=check)


def _write_executable(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    path.chmod(0o755)


def _fixture_repository(tmp_path: Path) -> tuple[Path, dict[str, str]]:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-b", "main")
    _git(repo, "config", "user.email", "hook-test@example.invalid")
    _git(repo, "config", "user.name", "Hook Test")

    (repo / "scripts").mkdir()
    shutil.copy2(INSTALLER_SCRIPT, repo / "scripts/install_git_hooks.sh")
    (repo / "scripts/install_git_hooks.sh").chmod(0o755)

    hook_log = tmp_path / "hook.log"
    env = {
        "HOOK_LOG": str(hook_log),
    }

    for hook_name in REQUIRED_HOOKS:
        if hook_name == "commit-msg":
            _write_executable(
                repo / f".githooks/{hook_name}",
                '#!/usr/bin/env bash\nset -euo pipefail\nprintf "commit-msg:%s\\n" "$1" >> "$HOOK_LOG"\n',
            )
        else:
            _write_executable(
                repo / f".githooks/{hook_name}",
                f'#!/usr/bin/env bash\nset -euo pipefail\nprintf "{hook_name}\\n" >> "$HOOK_LOG"\n',
            )

    for support_file in SUPPORT_FILES:
        (repo / f".githooks/{support_file}").write_text(f"# {support_file}\n", encoding="utf-8")

    (repo / "README.md").write_text("initial\n", encoding="utf-8")
    _git(repo, "add", ".")
    _git(repo, "commit", "-m", "initial commit", env=env)

    # --check parses the config with the project interpreter; untracked, like a real .venv.
    for helper in CHECK_HELPERS:
        (repo / helper).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO_ROOT / helper, repo / helper)
    _write_executable(repo / ".venv/bin/python", f'#!/bin/sh\nexec "{sys.executable}" "$@"\n')

    return repo, env


def test_installer_unsets_core_hooks_path_and_creates_delegators(tmp_path: Path) -> None:
    repo, env = _fixture_repository(tmp_path)
    # Simulate prior state where core.hooksPath was pointed at .githooks
    _git(repo, "config", "core.hooksPath", ".githooks", env=env)
    assert _git(repo, "config", "--get", "core.hooksPath", env=env).stdout.strip() == ".githooks"

    result = _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)
    assert result.returncode == 0
    for hook_name in REQUIRED_HOOKS:
        assert f"{hook_name}: installed" in result.stdout

    # (a) core.hooksPath is unset
    check_config = _git(repo, "config", "--get", "core.hooksPath", env=env, check=False)
    assert check_config.returncode != 0

    # (b) delegators present + executable
    hooks_dir = repo / ".git/hooks"
    for hook_name in REQUIRED_HOOKS:
        delegator = hooks_dir / hook_name
        assert delegator.is_file(), f"Expected delegator at {delegator}"
        assert os.access(delegator, os.X_OK), f"Delegator at {delegator} must be executable"
        content = delegator.read_text(encoding="utf-8")
        assert "# generated by scripts/install_git_hooks.sh" in content
        assert f'hook="$root/.githooks/{hook_name}"' in content

    # Non-hook files must not have delegators
    for support_file in SUPPORT_FILES:
        assert not (hooks_dir / support_file).exists()


def test_commit_in_linked_worktree_triggers_tracked_hook(tmp_path: Path) -> None:
    repo, env = _fixture_repository(tmp_path)
    _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)

    worktree = tmp_path / "worktree"
    _git(repo, "worktree", "add", "-b", "feature", str(worktree), env=env)

    (worktree / "change.txt").write_text("worktree change\n", encoding="utf-8")
    _git(worktree, "add", "change.txt", env=env)
    _git(worktree, "commit", "-m", "feature commit", env=env)

    hook_log = Path(env["HOOK_LOG"]).read_text(encoding="utf-8").splitlines()
    # commit-msg, pre-commit, and post-commit in linked worktree triggered the tracked hook
    assert "pre-commit" in hook_log
    assert any(line.startswith("commit-msg:") for line in hook_log)
    assert "post-commit" in hook_log


def test_installer_is_idempotent(tmp_path: Path) -> None:
    repo, env = _fixture_repository(tmp_path)

    # First run: installed
    run1 = _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)
    assert run1.returncode == 0
    for hook_name in REQUIRED_HOOKS:
        assert f"{hook_name}: installed" in run1.stdout

    # Second run: kept
    run2 = _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)
    assert run2.returncode == 0
    for hook_name in REQUIRED_HOOKS:
        assert f"{hook_name}: kept" in run2.stdout

    check_config = _git(repo, "config", "--get", "core.hooksPath", env=env, check=False)
    assert check_config.returncode != 0

    # Commit inside a LINKED worktree and verify tracked hooks fire
    worktree = tmp_path / "worktree"
    _git(repo, "worktree", "add", "-b", "feature-idempotent", str(worktree), env=env)
    (worktree / "change.txt").write_text("idempotent change\n", encoding="utf-8")
    _git(worktree, "add", "change.txt", env=env)
    _git(worktree, "commit", "-m", "idempotent commit", env=env)

    hook_log = Path(env["HOOK_LOG"]).read_text(encoding="utf-8").splitlines()
    assert "pre-commit" in hook_log
    assert any(line.startswith("commit-msg:") for line in hook_log)
    assert "post-commit" in hook_log


# Wrappers exactly as Entire CLI 0.11.5 writes them (`entire enable --force`; the same
# bytes 0.8.42 wrote) when no <name>.pre-entire exists yet, and after one exists
# (chain block appended; canary evidence for #10846).
ENTIRE_WRAPPERS = {
    "commit-msg": (
        "#!/bin/sh\n"
        "# Entire CLI hooks\n"
        "# Commit-msg hook: strip trailer if no user content (allows aborting empty commits)\n"
        'if command -v entire >/dev/null 2>&1; then entire hooks git commit-msg "$1" || true; '
        "else printf '%s\\n' '[entire] Entire CLI is enabled but not installed or not on PATH. "
        "Skipping Entire Git hook; continuing. Installation guide: "
        "https://docs.entire.io/cli/installation#installation-methods' >&2 || :; fi\n"
    ),
    "pre-push": (
        "#!/bin/sh\n"
        "# Entire CLI hooks\n"
        "# Pre-push hook: push session logs alongside user's push\n"
        '# $1 is the remote name (e.g., "origin")\n'
        'if command -v entire >/dev/null 2>&1; then entire hooks git pre-push "$1"; else :; fi\n'
    ),
    "post-commit": (
        "#!/bin/sh\n"
        "# Entire CLI hooks\n"
        "# Post-commit hook: condense session data if commit has Entire-Checkpoint trailer\n"
        "if command -v entire >/dev/null 2>&1; then entire hooks git post-commit 2>/dev/null || true; else :; fi\n"
    ),
}


# Entire's own wrappers for the two managed hooks with no tracked repo hook.
ENTIRE_UNCHAINED_WRAPPERS = {
    "prepare-commit-msg": (
        "#!/bin/sh\n"
        "# Entire CLI hooks\n"
        'if command -v entire >/dev/null 2>&1; then entire hooks git prepare-commit-msg "$1" "$2" 2>/dev/null || true; '
        "else :; fi\n"
    ),
    "post-rewrite": (
        "#!/bin/sh\n"
        "# Entire CLI hooks\n"
        "# Post-rewrite hook: remap session linkage after amend/rebase rewrites\n"
        'if command -v entire >/dev/null 2>&1; then entire hooks git post-rewrite "$1" 2>/dev/null || true; else :; fi\n'
    ),
}
# The installer reroutes each wrapper's Entire call through the capture guard (#10846).
GUARDED_CALL = (
    'then sh -c \'g="$(git rev-parse --show-toplevel)/scripts/entire/capture_guard.sh"; '
    'if [ -x "$g" ]; then exec "$g" "$@"; fi; '
    'echo "[entire] capture refused (guard_missing): no checkpoint written" >&2\' entire-capture-guard hooks git '
)
GUARD_FILES = (
    "scripts/__init__.py",
    "scripts/entire/capture_guard.sh",
    "scripts/entire/capture_guard.py",
    "scripts/entire/validate_checkpoint_routing.py",
    ".entire/settings.json",
    ".entire/phase05-allowlist.json",
    ".entire/private-recall.json",
)
# The live CLI usually lives in a user bin directory; a fixed system PATH keeps it out.
SYSTEM_PATH = "/usr/local/bin:/usr/bin:/bin"


def _guarded(wrapper: str) -> str:
    assert wrapper.count("then entire hooks git ") == 1
    return wrapper.replace("then entire hooks git ", GUARDED_CALL)


def _entire_chained(hook_name: str) -> str:
    guard = "ENTIRE_CHAINING_" + hook_name.upper().replace("-", "_")
    status = (
        '_entire_status=$?\nif [ "$_entire_status" -ne 0 ]; then exit "$_entire_status"; fi\n'
        if hook_name == "pre-push"
        else ""
    )
    return (
        ENTIRE_WRAPPERS[hook_name] + status + "# Chain: run pre-existing hook\n"
        '_entire_hook_dir="$(dirname "$0")"\n'
        f'if [ -z "${{{guard}:-}}" ]; then\n'
        f"    {guard}=1\n"
        f"    export {guard}\n"
        '    if [ -n "${PRE_COMMIT_RUNNING_LEGACY:-}" ] && grep -q '
        "'^# File generated by pre-commit: https://pre-commit.com' "
        f'"$_entire_hook_dir/{hook_name}.pre-entire" 2>/dev/null; then\n'
        f'        if [ -x "$_entire_hook_dir/{hook_name}.legacy.pre-entire" ]; then\n'
        f'            "$_entire_hook_dir/{hook_name}.legacy.pre-entire" "$@"\n'
        "        fi\n"
        f'    elif [ -x "$_entire_hook_dir/{hook_name}.pre-entire" ]; then\n'
        f'        "$_entire_hook_dir/{hook_name}.pre-entire" "$@"\n'
        "    fi\n"
        "fi\n"
    )


def _entire_0842_chained(hook_name: str) -> str:
    """The unguarded chain Entire 0.8.42 wrote; installed hosts may still carry it."""
    return (
        ENTIRE_WRAPPERS[hook_name] + "# Chain: run pre-existing hook\n"
        '_entire_hook_dir="$(dirname "$0")"\n'
        f'if [ -x "$_entire_hook_dir/{hook_name}.pre-entire" ]; then\n'
        f'    "$_entire_hook_dir/{hook_name}.pre-entire" "$@"\n'
        "fi\n"
    )


def _install_entire_wrappers(
    repo: Path,
    env: dict[str, str],
    tmp_path: Path,
    *,
    version: str = "Entire CLI 0.11.5",
    hook_exit: int = 0,
) -> Path:
    """Install Entire's unchained wrappers, the capture guard and a stub `entire`.

    The stub answers the guard's probes (``version``, ``status --json`` with the
    dedicated private route) and logs every call; ``hooks`` calls exit ``hook_exit``.
    """
    hooks_dir = repo / ".git/hooks"
    for hook_name, content in {**ENTIRE_WRAPPERS, **ENTIRE_UNCHAINED_WRAPPERS}.items():
        _write_executable(hooks_dir / hook_name, content)
    for relative in GUARD_FILES:
        (repo / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO_ROOT / relative, repo / relative)
    status = '{"checkpoint_sync_remote":"learn-ukrainian/entire-checkpoints-private","checkpoint_sync_remote_source":"dedicated"}'
    stub_bin = tmp_path / "bin"
    _write_executable(
        stub_bin / "entire",
        "#!/bin/sh\n"
        'printf "entire:%s\\n" "$*" >> "$HOOK_LOG"\n'
        'case "$1" in\n'
        f"  version) echo '{version}';;\n"
        f"  status) echo '{status}';;\n"
        f"  hooks) exit {hook_exit};;\n"
        "esac\n",
    )
    env["PATH"] = f"{stub_bin}{os.pathsep}{SYSTEM_PATH}"
    return hooks_dir


def test_entire_wrappers_gain_entire_chain_block(tmp_path: Path) -> None:
    repo, env = _fixture_repository(tmp_path)
    hooks_dir = _install_entire_wrappers(repo, env, tmp_path)

    result = _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)
    for hook_name in ENTIRE_WRAPPERS:
        assert f"{hook_name}: added Entire chain to {hook_name}.pre-entire" in result.stdout
        assert f"{hook_name}: chained-under-entire" in result.stdout
        # What Entire itself writes once <name>.pre-entire exists, with the Entire call guarded.
        assert (hooks_dir / hook_name).read_text(encoding="utf-8") == _guarded(_entire_chained(hook_name))
        assert os.access(hooks_dir / hook_name, os.X_OK)
        pre_entire = hooks_dir / f"{hook_name}.pre-entire"
        assert os.access(pre_entire, os.X_OK)
        assert "# generated by scripts/install_git_hooks.sh" in pre_entire.read_text(encoding="utf-8")

    rerun = _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)
    assert "added Entire chain" not in rerun.stdout
    for hook_name in ENTIRE_WRAPPERS:
        assert f"{hook_name}: chained-under-entire" in rerun.stdout
        assert (hooks_dir / hook_name).read_text(encoding="utf-8") == _guarded(_entire_chained(hook_name))

    worktree = tmp_path / "worktree"
    _git(repo, "worktree", "add", "-b", "feature-entire", str(worktree), env=env)
    # The guard is tracked in the real repository, so every worktree carries it.
    for relative in GUARD_FILES:
        (worktree / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(repo / relative, worktree / relative)
    (worktree / "wt-file.txt").write_text("entire payload\n", encoding="utf-8")
    _git(worktree, "add", "wt-file.txt", env=env)
    _git(worktree, "commit", "-m", "chained commit in worktree", env=env)

    hook_log = Path(env["HOOK_LOG"]).read_text(encoding="utf-8").splitlines()
    assert any(line.startswith("entire:hooks git commit-msg ") for line in hook_log)
    assert any(line.startswith("commit-msg:") for line in hook_log)
    assert "entire:hooks git post-commit" in hook_log
    assert "post-commit" in hook_log


