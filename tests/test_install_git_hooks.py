def _hooks_snapshot(hooks_dir: Path) -> dict[str, str]:
    return {
        path.name: (
            f"-> {os.readlink(path)}"
            if path.is_symlink()
            else sorted(child.name for child in path.iterdir())
            if path.is_dir()
            else path.read_text(encoding="utf-8")
        )
        for path in sorted(hooks_dir.iterdir())
    }


