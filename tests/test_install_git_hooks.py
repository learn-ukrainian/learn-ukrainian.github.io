def test_check_covers_every_stage_the_repository_config_declares(tmp_path: Path) -> None:
    yaml = pytest.importorskip("yaml")
    config_text = (REPO_ROOT / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    config = yaml.safe_load(config_text)
    aliases = {"commit": "pre-commit", "push": "pre-push", "merge-commit": "pre-merge-commit"}
    declared = set(config.get("default_install_hook_types", [])) | set(config.get("default_stages", []))
    for repo_entry in config["repos"]:
        for hook in repo_entry["hooks"]:
            declared |= set(hook.get("stages", []))
    declared = {aliases.get(stage, stage) for stage in declared} - {"manual"}
    assert {"commit-msg", "pre-push"} <= declared

    repo, env = _fixture_repository(tmp_path)
    _write_pre_commit_config(repo, config_text)
    _run(["bash", "scripts/install_git_hooks.sh"], cwd=repo, env=env)

    check = _run(["bash", "scripts/install_git_hooks.sh", "--check"], cwd=repo, env=env)
    reported = {line.split(":", 1)[0] for line in check.stdout.splitlines() if ": ok (" in line}
    assert reported == declared


